// ============================================================
// **مَن نبيع منه ومَن نستأجره** — قياسٌ يُجهِّز قرارًا، ولا يتّخذه.
//
//   ── السؤالُ الذي وُلد منه ──
//   قِيست جملُ الناس فظهر تفاوتٌ داخل النظام نفسِه:
//
//       «كنقلب على كسوة لبنتي» ⇒ buy      ⇒ «تشري شي حاجة»
//       «بغيت شي بيتزا»         ⇒ find_pro ⇒ «تقلّب على **حرفي ولا مختصّ**»
//
//   وكلاهما إنسانٌ يريد أن يقتني شيئًا. والوجهةُ **واحدةٌ في الحالتَين**
//   (`/market`) — فالعطبُ في ما يُقال للإنسان لا في أين يُساق. ومَن يطلب
//   بيتزا يُقال له إنّه «يقلّب على حرفيّ»، ومفهومُه في القاعدة **«مطعم»**،
//   ومفهومُ «salam bghit djaj» **«بائع دواجن»** — والكلمةُ «بائع» مكتوبةٌ
//   في اسم المفهوم نفسِه.
//
//   ── لماذا قياسٌ لا إصلاح ──
//   الفرقُ بين «بائعٍ تشتري منه» و«حِرفيٍّ تستأجره» **لا يُشتقّ من معطًى
//   قائم**. فُحص `category` فوُجد: ١٠٤ من ٢٠٧ بلا فئةٍ أصلًا، و٥٨ قيمةً
//   متمايزةً للباقي تخلط الإنجليزيّةَ بالعربيّة بسابقة «دارجة:»، وفيها
//   قيمةٌ واحدةٌ **جملةُ نثرٍ** تسرّبت من ملفّ CSV. فالحقلُ موجودٌ ولا
//   إشارةَ فيه.
//
//   ولذلك هذا الملفُّ **يقيس ولا يقرّر**: يعرض كلَّ مفهومٍ يُقرأ طلبُه
//   `find_pro`، وما يُقال لصاحبه، وقرائنَ من البيانات نفسِها تُرجِّح أهو
//   بائعٌ أم حِرفيّ. والحسمُ لصاحب المشروع — فهو معرفةٌ عن السوق المغربيّ
//   لا استنتاجٌ من كود.
//
//   ── وحدُّه ──
//   قراءةٌ خالصة: لا يُعدّل ملفًّا ولا يمسّ محرّكًا. يُشغَّل بـ
//   `npm run report:ask-kind`.
// ============================================================

import { CONCEPTS } from '../src/lib/akg/kb/concepts';
import { parseNeed } from '../src/lib/needEngine';

/** قرائنُ «بائعٌ تشتري منه» — من نصّ المفهوم نفسِه، لا من قائمةٍ مخترَعة. */
const SELLER_CUES = ['بائع', 'بيع', 'محل', 'متجر', 'مطعم', 'مقهى', 'مخبز', 'سوق', 'دكان', 'حانوت'];
/** وقرائنُ «حِرفيٌّ تستأجره» — الفعلُ على شيءٍ يملكه الإنسانُ أصلًا. */
const TRADE_CUES  = ['تصليح', 'إصلاح', 'صيانة', 'تركيب', 'تنظيف', 'نقل', 'بناء', 'دهان', 'خدمة', 'خدمات'];

export interface Row {
  id: string;
  name: string;
  intent: string;
  say: string;
  /** ما تقوله البياناتُ نفسُها — لا حكمَ نهائيّ. */
  cue: 'بائع' | 'حِرفيّ' | 'ملتبس';
  why: string;
}

const textOf = (c: any) => [
  c.concept?.ar, c.concept?.darija, c.concept?.fr, c.concept?.en,
  ...(c.services || []),
].filter(Boolean).join(' · ');

/** يقرأ كلَّ مفهومٍ عبر **الطريق الحيّ** — نفسِ ما تسلكه جملةُ الإنسان. */
export function measure(): Row[] {
  const rows: Row[] = [];
  for (const c of CONCEPTS as any[]) {
    // الكلمةُ التي يقولها المغربيُّ عادةً: الدارجةُ إن وُجدت، وإلّا العربيّة.
    const term = c.concept?.darija || c.concept?.ar;
    if (!term) continue;
    const r = parseNeed(`بغيت ${term}`, {} as any) as any;
    if (!r || (r.intent !== 'find_pro' && r.intent !== 'urgent')) continue;

    const t = textOf(c);
    const sell = SELLER_CUES.filter(w => t.includes(w));
    const trade = TRADE_CUES.filter(w => t.includes(w));
    const cue: Row['cue'] = sell.length && !trade.length ? 'بائع'
      : trade.length && !sell.length ? 'حِرفيّ' : 'ملتبس';
    rows.push({
      id: c.id, name: c.concept?.ar || c.id, intent: r.intent, say: r.label || '—',
      cue,
      why: cue === 'ملتبس'
        ? (sell.length || trade.length ? `بيعٌ وحِرفةٌ معًا: ${[...sell, ...trade].join('، ')}` : 'لا قرينةَ في نصّ المفهوم')
        : [...sell, ...trade].join('، '),
    });
  }
  return rows.sort((a, b) => a.cue.localeCompare(b.cue) || a.id.localeCompare(b.id));
}

const n = (x: number | string) => String(x).replace(/\d/g, d => '٠١٢٣٤٥٦٧٨٩'[+d]);

export function render(rows: Row[]): string {
  const by = (k: Row['cue']) => rows.filter(r => r.cue === k);
  const L: string[] = [];
  const p = (s = '') => L.push(s);

  p('# مَن نشتري منه ومَن نستأجره — قياسٌ يُجهِّز قرارًا');
  p();
  p('> **مُولَّدٌ آليًّا** بـ`npm run report:ask-kind` — لا يُحرَّر بيد.');
  p('> يقرأ كلَّ مفهومٍ عبر `parseNeed` — **نفسِ الطريق الحيّ** الذي تسلكه جملةُ الإنسان.');
  p();
  p(`آخرُ توليد: ${new Date().toISOString().slice(0, 10)}`);
  p();
  p('## ① لماذا هذا القياس');
  p();
  p('```');
  p('«كنقلب على كسوة لبنتي» ⇒ buy      ⇒ «تشري شي حاجة»');
  p('«بغيت شي بيتزا»         ⇒ find_pro ⇒ «تقلّب على حرفي ولا مختصّ»');
  p('```');
  p();
  p('وكلاهما إنسانٌ يريد أن يقتني شيئًا. والوجهةُ واحدةٌ (`/market`) في الحالتَين —');
  p('فالفرقُ في **ما يُقال للإنسان** لا في أين يُساق.');
  p();
  p('## ② الخلاصة');
  p();
  p('| ما هو | العدد |');
  p('|---|---|');
  p(`| مفهومًا يُقرأ طلبُه «تقلّب على حرفي» | **${n(rows.length)}** |`);
  p(`| منها ترجّح البياناتُ أنّه **بائع** | **${n(by('بائع').length)}** |`);
  p(`| منها ترجّح البياناتُ أنّه **حِرفيّ** | **${n(by('حِرفيّ').length)}** |`);
  p(`| منها **ملتبس** — يحتاج حكمَ إنسان | **${n(by('ملتبس').length)}** |`);
  p();
  p('## ③ ما ترجّح البياناتُ أنّه **بائعٌ** — وهو يُقال له «حِرفيّ»');
  p();
  p('كلُّ سطرٍ هنا إنسانٌ يريد أن **يشتري**، ويُقال له إنّه يقلّب على حِرفيّ.');
  p();
  p('| المفهوم | يُعرَض له | القرينة |');
  p('|---|---|---|');
  for (const r of by('بائع')) p(`| \`${r.id}\` — ${r.name} | ${r.say} | ${r.why} |`);
  p();
  p('## ④ ما ترجّح البياناتُ أنّه **حِرفيّ** — وهو صوابٌ كما هو');
  p();
  p('| المفهوم | يُعرَض له | القرينة |');
  p('|---|---|---|');
  for (const r of by('حِرفيّ')) p(`| \`${r.id}\` — ${r.name} | ${r.say} | ${r.why} |`);
  p();
  p('## ⑤ الملتبسُ — لا تحسمه البيانات');
  p();
  p('هذه هي التي **تحتاج قرارَ صاحب المشروع**: معرفةٌ عن السوق المغربيّ لا تُشتقّ من كود.');
  p();
  p('> **وفيها صنفٌ ثالثٌ أوضحُ خطأً من الاثنين**: مفاهيمُ ليست نشاطًا تجاريًّا');
  p('> أصلًا بل **سلعةً تُشترى** — `baby_onesies` (ملابس رضّع) · `bicycle`');
  p('> (درّاجة هوائيّة) · `automobile`. ومَن يطلب واحدةً منها يُقال له إنّه');
  p('> «يقلّب على حِرفيّ». وهذه لا تحتاج حكمًا على السوق: سلعةٌ ليست حِرفةً،');
  p('> ولا خلافَ فيها. لم تُفرَد في عمودٍ لأنّ تمييزَها آليًّا يحتاج معطًى');
  p('> غيرَ موجود — ولو اخترعتُ له قاعدةً لأخطأت في مفاهيمَ تحمل الاسمَين');
  p('> معًا («درّاجة» سلعةٌ و«تصليح الدرّاجات» حِرفة).');
  p();
  p('| المفهوم | يُعرَض له | لماذا التبس |');
  p('|---|---|---|');
  for (const r of by('ملتبس')) p(`| \`${r.id}\` — ${r.name} | ${r.say} | ${r.why} |`);
  p();
  p('## ⑥ وحدُّ هذا التقرير');
  p();
  p('القرينةُ **ليست حكمًا**. هي ما وجدته في نصّ المفهوم نفسِه (اسمُه وخدماتُه)،');
  p('وقد تخطئ: «محل» في وصفِ حِرفيٍّ لا تجعله بائعًا. والحقلُ الذي كان يجب أن');
  p('يحسم — `category` — فُحص فوُجد ١٠٤ من ٢٠٧ بلا فئة، و٥٨ قيمةً متمايزةً');
  p('للباقي، وفيها قيمةٌ واحدةٌ **جملةُ نثرٍ** تسرّبت من ملفّ CSV. فالحقلُ');
  p('موجودٌ ولا إشارةَ فيه — ولذلك يُقاس بالقرائن ويُحسَم بإنسان.');
  return L.join('\n');
}

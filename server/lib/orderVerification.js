'use strict';

// ============================================================
// أيحتاج هذا الطلبُ تأكيدَ نمرة؟ — **مكانٌ واحدٌ يُجيب**.
//
//   ── المعضلةُ كما طُرحت، ولماذا هي كاذبة ──
//   «التحقّقُ يقلّل الطلباتِ الوهميّةَ ويقلّل الحقيقيّةَ معها» — صحيحٌ **لو**
//   كان الخيارُ بين تأكيدِ الكلّ وتأكيدِ لا أحد. وليس كذلك.
//
//   ── الاقتصادُ الحقيقيّ ──
//   الدفعُ عند الاستلام. فالطلبُ الوهميُّ لا يُخسِر التاجرَ سلعةً بل **ثمنَ
//   توصيلٍ حقيقيّ** لطردٍ يُرفَض عند الباب — يدفعه من جيبه مرّةً بعد مرّة.
//   وهذه خسارةٌ تقع كلَّها في **الطلب الأوّل من نمرةٍ لا يعرفها**.
//
//   ── والقاعدةُ التي تحسم ──
//   «لا يسأل التطبيقُ سؤالًا يعرف جوابَه». زبونٌ وصلَه طردٌ من قبلُ **أثبت
//   نمرتَه بالفعل**: حملها المندوبُ واتّصل بها وسلّم إليها. فسؤالُه ثانيةً
//   هو «موتُ السحر» بعينه — يعرف ثمّ يسأل.
//
//   فالتأكيدُ يقع حيث تقع الخسارة (أوّلُ طلبٍ من مجهول)، ويختفي حيث يقع
//   الدخل (الزبونُ العائد). ولا تناقضَ بين الحمايةِ والتحويل.
//
//   ── وقرارُ التاجر يبقى له ──
//   `off` لمن يعرف زبناءه واحدًا واحدًا · `always` لمن اكتوى · و`first`
//   افتراضًا لأنّها الوضعُ الذي لا يخسر في الحالتَين.
// ============================================================

const { db } = require('../database');
const verify = require('./verify');

/** أوضاعُ التأكيد المُعلَنة. ما ليس منها يُعامَل معاملةَ الافتراضيّ. */
const MODES = ['off', 'first', 'always'];
const DEFAULT_MODE = 'first';

function modeOf(settings) {
  const m = settings?.security?.verifyOrders;
  return MODES.includes(m) ? m : DEFAULT_MODE;
}

/**
 * @returns {Promise<{required:boolean, reason:string, mode:string}>}
 *   `reason` يُسجَّل ويُعرَض عند السؤال «لماذا طُلب منّي التأكيد؟» — قرارٌ
 *   بلا سببٍ ظاهرٍ يبدو تعسّفًا.
 */
async function needsVerification({ userId, phone, settings }) {
  const mode = modeOf(settings);
  if (mode === 'off') return { required: false, reason: 'التاجرُ أوقف التأكيد', mode };

  // ── **بوّابةٌ لا مفتاحَ لها ليست بوّابة، هي حائط** ─────────────────
  //
  //   قِيس بأوّل مشيٍ كاملٍ للطريق — حسابٌ جديد ⟵ منتج ⟵ طلبُ زبون:
  //
  //     النمرةُ لها قناتان لا غير: SMS (مفتاحُ منصّةٍ في البيئة) وواتساب
  //     (توكنٌ يربطه التاجرُ بنفسه). وحسابٌ جديدٌ **لا يملك أيًّا منهما**.
  //     فيُطلَب التأكيدُ، ويُطلَب الرمزُ، فيرجع `no-channel`.
  //
  //   والنتيجةُ أنّ **كلَّ زبونٍ لكلّ تاجرٍ جديدٍ يُوقَف عند بابٍ لا يُفتَح
  //   أبدًا**. لا طلبَ واحدًا يمرّ. وهذا لا يظهر في اختبارِ وحدةٍ لأنّ كلَّ
  //   طرفٍ صحيحٌ وحدَه: التأكيدُ يقرّر صوابًا، والقناةُ تُعلن عجزَها صدقًا،
  //   والسلسلةُ مقطوعة.
  //
  //   ── ولماذا التخفيفُ هنا صوابٌ لا تنازل ──
  //   التأكيدُ بُني ليمنع خسارةَ **ثمنِ توصيلٍ** في طلبٍ وهميّ. وحائطٌ يمنع
  //   الطلباتِ كلَّها يمنع الخسارةَ بمنع التجارة — وهو أسوأُ لصاحب المحلّ
  //   من الخسارة التي يحمي منها. والحمايةُ تعود **في اللحظة** التي يربط
  //   فيها التاجرُ قناةً، بلا أن يفعل شيئًا آخر.
  //
  //   ── ولا يُسكَت عنه ──
  //   يُرجَع `undeliverable: true` ليكتبه المسارُ في سجلّ التاجر. فرقٌ بين
  //   حمايةٍ **مُوقَفةٍ بقرارٍ** وحمايةٍ **ساقطةٍ بصمت**؛ والثانيةُ أخطر.
  let channels = [];
  try { channels = verify.channelsFor(phone, { settings, userId }); }
  catch { channels = []; }
  if (!channels.length) {
    return {
      required: false, mode, undeliverable: true,
      reason: 'ما كايناش قناة باش نصيفطو الكود — التأكيد موقوف حتّى تربط واتساب ولا SMS',
    };
  }

  if (mode === 'always') return { required: true, reason: 'التاجرُ يطلب التأكيد دائمًا', mode };

  // `first`: يُسأل مَن لم نُسلّم إليه شيئًا قطّ.
  //
  //   والفشلُ يُغلَق آمنًا: تعذّرت القراءةُ ⇒ **يُطلَب التأكيد**. عطبُ قاعدةٍ
  //   لا يجوز أن يفتح البابَ لطلباتٍ وهميّة.
  let known = false;
  try { known = await db.hasDeliveredOrderFromPhone(userId, phone); }
  catch { known = false; }
  return known
    ? { required: false, reason: 'زبونٌ سبق أن وصلَه طلب — نمرتُه مُثبَتة', mode }
    : { required: true, reason: 'أوّلُ طلبٍ من هذه النمرة', mode };
}

module.exports = { needsVerification, MODES, DEFAULT_MODE };

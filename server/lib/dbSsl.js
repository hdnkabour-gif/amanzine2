'use strict';
// ============================================================
// **ثقةُ TLS لقاعدة البيانات — صريحةٌ، لا ضمنيّة.**
//
//   كان الافتراضُ لأيّ قاعدةٍ بعيدةٍ هو `{ rejectUnauthorized: false }` — أي
//   **تشفيرٌ بلا هويّة**. القناةُ مُعمّاةٌ فعلًا، لكنّ الخادمَ الذي في الطرف
//   الآخر لا يُتحقَّق منه: من جلس بين التطبيق وقاعدته قدّم شهادتَه هو، وقُبِلت،
//   وقرأ كلَّ طلبٍ وكتب كلَّ جواب. والتعميةُ بلا مصادقةِ طرفٍ تحمي من المتنصّت
//   السلبيّ وحدَه، ولا تحمي من المعترِض — وهو الخطرُ الحقيقيّ على وصلةٍ تعبر
//   شبكةَ مزوّدٍ عامّة.
//
//   وكان فيه عطبٌ ثانٍ أخفى: من ضبط `DATABASE_CA` بمسارٍ خاطئ كان يُطبَع له
//   تحذيرٌ ثمّ **يُخفَّض إلى الوضع المتسامح صامتًا**. أي أنّ محاولةَ التشديد
//   نفسَها كانت تنتهي إلى التساهل، ويظنّ صاحبُها أنّه شدّد.
//
//   ── القرار ──
//   ①  تعطيلٌ صريح (`PGSSLMODE=disable` · `DB_SSL=false` · `sslmode=disable`)
//      ⇒ بلا TLS. صريحٌ ومقصود.
//   ②  شهادةُ جذرٍ مُعطاة (`DATABASE_CA` نصًّا أو `PGSSLROOTCERT`/
//      `DATABASE_CA_PATH` مسارًا) ⇒ تحقّقٌ صارمٌ بها. وفشلُ تحميلها **يرمي**
//      ولا يُخفَّض.
//   ③  قاعدةٌ محلّيّةٌ في غير الإنتاج ⇒ بلا TLS (تطويرٌ وقواعدُ زائلة).
//   ④  ما عدا ذلك — قاعدةٌ بعيدة ⇒ **`rejectUnauthorized: true`**: تُتحقَّق
//      الهويّةُ من متجر الشهادات المعياريّ.
//
//   وأثرُ ④ معلَنٌ ولا يُخفى: مزوّدٌ يقدّم شهادةً موقّعةً ذاتيًّا سيفشل
//   الاتّصالُ به الآن بدل أن يمرّ. وهذا هو المقصود — والرسالةُ تقول ما يُضبَط
//   بالضبط. **الفشلُ المعلَنُ خيرٌ من وصلةٍ تبدو آمنةً وليست كذلك.**
// ============================================================

/**
 * **وصلةُ Railway الخاصّة — بابٌ ضيّقٌ واحد، لا تخفيفٌ عامّ.**
 *
 *   قِيس على الإنتاج: `self-signed certificate in certificate chain`. قاعدةُ
 *   Railway تقدّم شهادةً موقّعةً من جذرٍ موقَّعٍ ذاتيًّا، واسمُها لا يطابق
 *   مضيفَ الشبكة الخاصّة. فالتحقّقُ الصارمُ يفشل بحقٍّ — والوصلةُ **ليست**
 *   مكشوفةً رغم ذلك: شبكةُ Railway الخاصّة نفسُها مُعمّاةٌ بـWireGuard
 *   ومعزولةٌ بين البيئات، ولا تخرج إلى الإنترنت.
 *
 *   ── ولماذا لا يُطفَأ التحقّقُ عامّةً ──
 *   `rejectUnauthorized:false` يجعل **كلَّ** قاعدةٍ بعيدةٍ تقبل أيَّ شهادة —
 *   بما فيها قاعدةٌ تعبر إنترنتًا عامًّا. فمن جلس في الطريق قدّم شهادتَه
 *   وقُرئ كلُّ شيء. والعلاجُ الصحيحُ ليس تخفيفَ القاعدة العامّة بل **وصفَ
 *   النقل** الذي نثق به بالاسم، ورفضَ ما عداه.
 *
 *   ── ويفشل مغلقًا ──
 *   إعلانُ `DB_TRANSPORT=railway-private` لمضيفٍ ليس في `.railway.internal`
 *   **يرمي**. ولا يُقارَن بالنصّ: `railway.internal.attacker.com` ينتهي
 *   بـ`.com` لا بـ`.railway.internal`، و`evilrailway.internal` ليس مضيفًا
 *   داخلَ النطاق بل اسمًا يشبهه. فالمضيفُ يُستخرَج بمحلّل URL ويُقارَن
 *   بالتسمية، لا بـ`includes` ولا بـ`endsWith` على نصٍّ خام.
 */
const PRIVATE_SUFFIX = '.railway.internal';

/** مضيفُ الوصلة كما يفهمه محلّلُ URL — لا استخراجَ بتعبيرٍ نمطيّ. */
function hostOf(url) {
  try {
    // `postgres://` و`postgresql://` مخطَّطان لا يعرفهما WHATWG بالضرورة،
    //   فيُبدَّلان بـ`http:` كي يُحلَّل المضيفُ بالقواعد نفسِها التي
    //   تحلّل بها المتصفّحات — بما فيها تطبيعُ النقطة الختاميّة والحالة.
    const u = new URL(String(url).replace(/^postgres(ql)?:/i, 'http:'));
    return u.hostname.replace(/\.$/, '').toLowerCase();
  } catch { return ''; }
}

/** أهو مضيفٌ **داخلَ** شبكة Railway الخاصّة؟ لا اسمٌ يشبهها. */
function isRailwayPrivateHost(url) {
  const h = hostOf(url);
  return h.length > PRIVATE_SUFFIX.length && h.endsWith(PRIVATE_SUFFIX);
}

/** رسالةٌ تقول ما يُفعَل، لا «فشل الاتّصال». */
const ADVICE =
  'DB TLS: تعذّر التحقّق من هويّة خادم القاعدة. اضبط DATABASE_CA (نصّ الشهادة) '
  + 'أو PGSSLROOTCERT/DATABASE_CA_PATH (مسارها). وللتطوير المحلّيّ استعمل PGSSLMODE=disable.';

/**
 * @param {object} env — عادةً `process.env`. يُمرَّر ليكون القرارُ قابلًا للقياس.
 * @param {(p: string) => string} readFile — يُحقَن في الاختبار.
 * @returns {false | { rejectUnauthorized: boolean, ca?: string }}
 */
function buildSSL(env = process.env, readFile = null) {
  const url = String(env.DATABASE_URL || '');

  const isLocalUrl = /@(localhost|127\.0\.0\.1|\[?::1\]?)[:/]/i.test(url);
  const wantsDisable = env.PGSSLMODE === 'disable' || env.DB_SSL === 'false' || /sslmode=disable/i.test(url);

  // ── ⓪ نقلُ Railway الخاصّ — يُسبَق كلَّ شيءٍ لأنّه **وصفُ نقلٍ** لا تخفيفَ ثقة
  //   ثلاثةُ شروطٍ مجتمعةٍ ولا واحدَ منها يكفي. وأيُّ إعلانٍ لا تكتمل شروطُه
  //   **يرمي** — لا يسقط بصمتٍ إلى الوضع الصارم فيظنّ صاحبُه أنّه ضبط شيئًا،
  //   ولا يسقط إلى المتساهل فيُفتَح ما ظنّه مغلقًا.
  if (env.DB_TRANSPORT === 'railway-private') {
    if (env.NODE_ENV !== 'production') {
      throw new Error('DB TLS: `DB_TRANSPORT=railway-private` وضعُ إنتاجٍ وحدَه — '
        + 'وفي غيره تكفي القواعدُ المحلّيّةُ الزائلة. ' + ADVICE);
    }
    // ── **والبيّنةُ من البيئة نفسِها، لا من إعلان صاحبها** ──────────
    //   الشروطُ الثلاثةُ الأولى كلُّها **يكتبها من يضبط المتغيّرات**: اسمٌ
    //   ينتهي بـ`.railway.internal` يُكتَب في أيّ مكان، و`NODE_ENV` كذلك.
    //   فلو نُقل هذا الإعداد إلى خادمٍ خارج Railway — بالنسخ، أو بترحيلٍ
    //   إلى مزوّدٍ آخر، أو في حاوية محلّيّة — لبقيت الشروطُ صادقةً شكلًا
    //   والشبكةُ الخاصّةُ **غيرَ موجودة**، فتمرّ كلمةُ مرور القاعدة وكلُّ
    //   صفٍّ نصًّا صريحًا.
    //
    //   و`RAILWAY_ENVIRONMENT_ID` تكتبه المنصّةُ نفسُها في وقت التشغيل، لا
    //   المشغِّل. فهو الشاهدُ الوحيدُ هنا الذي **لا يأتي من الملفّ الذي
    //   يدّعي**. وغيابُه يعني أنّنا لسنا داخل Railway مهما قال الإعلان.
    if (!String(env.RAILWAY_ENVIRONMENT_ID || '').trim()) {
      throw new Error('DB TLS: أُعلن `DB_TRANSPORT=railway-private` وليس ثمّة '
        + '`RAILWAY_ENVIRONMENT_ID` — أي أنّ التطبيق ليس داخل Railway. '
        + 'وهذا الوضعُ يتّكئ على شبكةٍ خاصّةٍ لا وجودَ لها هنا. ' + ADVICE);
    }
    // ── **إعدادٌ ملتبسٌ يُردّ، ولا يُختار عن صاحبه** ────────────────
    //   شهادةُ جذرٍ مضبوطةٌ **مع** نقلٍ خاصّ: نيّتان متعارضتان — واحدةٌ
    //   تقول «تحقّق بهذه الشهادة» والأخرى تقول «لا TLS أصلًا». وأيُّ ترجيحٍ
    //   صامتٍ يترك صاحبَه يظنّ أنّ الأخرى هي العاملة. فيُقال ويُوقَف.
    const caSet = ['DATABASE_CA', 'PGSSLROOTCERT', 'DATABASE_CA_PATH']
      .filter((k) => String(env[k] || '').trim());
    if (caSet.length) {
      throw new Error('DB TLS: `DB_TRANSPORT=railway-private` مضبوطٌ مع '
        + `${caSet.join(' · ')} — نيّتان متعارضتان. `
        + 'النقلُ الخاصُّ لا TLS فوقه، وشهادةُ الجذر لا معنى لها بلا TLS. '
        + 'احذف إحداهما صراحةً. ' + ADVICE);
    }
    // ── **وقرارُ نقلٍ ثانٍ التباسٌ كذلك — ولو اتّفقت النتيجة** ────────
    //   `railway-private` **قرارُ نقلٍ كامل**. ووجودُ إشارةِ تعطيلٍ صريحةٍ
    //   معه يعني ملفَّ إعدادٍ فيه سياستان. والنتيجةُ العمليّةُ اليوم واحدة
    //   (لا TLS في الحالَين) — وهذا بالضبط ما يجعل السكوتَ خطرًا: يُكتَب
    //   `PGSSLMODE=disable` فلا يُقرأ ولا يُشتكى، ويظنّ صاحبُه أنّه هو
    //   العامل. ثمّ يُحذَف `DB_TRANSPORT` يومًا فينكشف أنّ الثانيةَ كانت
    //   نائمةً طوالَ الوقت، وتتبدّل السياسةُ بلا أن يقصد أحد.
    //
    //   وهذا الفرعُ يسبق فرعَ التعطيل الصريح أدناه، فلولا هذا الفحصُ
    //   لابتلعه ابتلاعًا تامًّا.
    if (wantsDisable) {
      const which = [
        env.PGSSLMODE === 'disable' ? 'PGSSLMODE=disable' : '',
        env.DB_SSL === 'false' ? 'DB_SSL=false' : '',
        /sslmode=disable/i.test(url) ? 'sslmode=disable في DATABASE_URL' : '',
      ].filter(Boolean);
      throw new Error('DB TLS: `DB_TRANSPORT=railway-private` مضبوطٌ مع '
        + `${which.join(' · ')} — سياستا نقلٍ في إعدادٍ واحد. `
        + 'النقلُ الخاصُّ يصف الطبقةَ التي تحتَه؛ والتعطيلُ الصريحُ قرارٌ آخر. '
        + 'أبقِ واحدةً. ' + ADVICE);
    }
    if (!isRailwayPrivateHost(url)) {
      throw new Error('DB TLS: أُعلن `DB_TRANSPORT=railway-private` لمضيفٍ خارجَ '
        + `\`${PRIVATE_SUFFIX}\` (المضيف: ${hostOf(url) || '—'}). `
        + 'هذا الوضعُ يتّكئ على تعميةِ شبكة Railway الخاصّة، ولا معنى له خارجَها — '
        + 'ولو قُبِل لمرّت قاعدةٌ عامّةٌ نصًّا صريحًا. ' + ADVICE);
    }
    // النقلُ مُعمًّى بـWireGuard تحت الطبقة، فلا TLS ثانيةً فوقه.
    return false;
  }

  // ── ① تعطيلٌ صريح — **وللمحلّيّ أو غير الإنتاج وحدَه** ────────
  //   كان هذا الفرعُ يسبق تمييزَ المحلّيّ من البعيد، فمتغيّرُ بيئةٍ واحدٌ
  //   (`PGSSLMODE=disable`) يجعل قاعدةَ إنتاجٍ بعيدةً تعمل **نصًّا صريحًا**
  //   عبر الشبكة: لا تشفيرَ ولا هويّة. وهو أسوأُ من التساهل الذي أُصلح قبله،
  //   ويقع بسطرِ إعدادٍ يُنسَخ من وثيقةِ تطوير.
  //
  //   والقاعدةُ: التعطيلُ أداةُ تطويرٍ محلّيّ. فإن كانت القاعدةُ بعيدةً
  //   **وكانت البيئةُ إنتاجًا**، يُرفَض ويُقال السبب — ولا يُخمَّن أنّ صاحبَه
  //   قصد النصَّ الصريح.
  if (wantsDisable) {
    if (isLocalUrl || env.NODE_ENV !== 'production') return false;
    throw new Error(
      'DB TLS: طُلب تعطيلُ TLS لقاعدةٍ بعيدةٍ في الإنتاج — وهذا يجعل الاتّصالَ نصًّا صريحًا. '
      + 'التعطيلُ للتطوير المحلّيّ وحدَه. ' + ADVICE);
  }

  // ② شهادةُ جذرٍ مُعطاة — والفشلُ هنا يرمي ولا يُخفِّض
  const caInline = env.DATABASE_CA;
  const caPath = env.PGSSLROOTCERT || env.DATABASE_CA_PATH;
  if (caInline) return { rejectUnauthorized: true, ca: caInline };
  if (caPath) {
    const read = readFile || ((p) => require('fs').readFileSync(p, 'utf8'));
    let ca;
    try { ca = read(caPath); } catch (e) {
      // لا سقوطَ إلى التساهل: من قصد التشديد لا يُعطى ضدَّه.
      throw new Error(`DB TLS: تعذّرت قراءة شهادة الجذر من ${caPath} (${e.message}). ${ADVICE}`);
    }
    return { rejectUnauthorized: true, ca };
  }

  // ③ قاعدةٌ محلّيّةٌ في غير الإنتاج
  if (isLocalUrl && env.NODE_ENV !== 'production') return false;

  // ④ بعيدةٌ بلا شهادةٍ مُعطاة ⇒ تحقّقٌ من الهويّة، لا تساهُل
  return { rejectUnauthorized: true };
}

module.exports = { buildSSL, ADVICE };

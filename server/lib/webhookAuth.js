'use strict';
// ============================================================
// **مصادقةُ الإشعار الوارد — مالكٌ واحدٌ للمقارنة.**
//
//   استُخرجت من `routes/webhooks.js` لسببٍ قِيس، لا لترتيب:
//   **أمانُ التوقيت غيرُ مرئيٍّ سلوكيًّا.** جُرِّب سبرُ إعادة `!==` مكان
//   المقارنة الثابتة، فلم يسقط اختبارٌ واحد — لأنّ رمزَ الحالة واحدٌ في
//   الحالتين (٤٠١)، والفرقُ في الزمن وحدَه. ثمّ قِيس الزمنُ نفسُه على سلسلتَين
//   بطول ٤٠٩٦ حرفًا وأربعين ألفَ تكرار:
//
//       `!==`                    early=2.2ms  late=1.2ms   (نسبة 0.54×)
//       تجزئة + timingSafeEqual  early=1056ms late=1038ms  (نسبة 0.98×)
//
//   أي أنّ إشارةَ الخروج المبكّر **غرقت في الضجيج** — V8 يقارن الطولَ أوّلًا
//   ثمّ يستعمل مقارنةً متّجهة، فلا يظهر تدرّجٌ نظيف. فاختبارٌ زمنيٌّ هنا يكون
//   متذبذبًا، **والحارسُ المتذبذبُ أسوأُ من غيابه**.
//
//   فالبديلُ بنيويٌّ لا زمنيّ: تُجمَع المقارنةُ في **موضعٍ واحدٍ مسمّى**، ويُحرَس
//   أنّ المسارَ لا يقارن بنفسه. حارسُ الشكل يبقى شكلًا — لكنّه على ملفٍّ صغيرٍ
//   ذي مقارنةٍ واحدة، لا على مسارٍ من مئة سطر. وهذا حدُّ ما يمكن إثباتُه هنا،
//   ويُقال كما هو بدل ادّعاء إثباتٍ سلوكيّ.
// ============================================================
const crypto = require('crypto');

/**
 * مقارنةُ سرَّين بزمنٍ لا يتبع محتواهما.
 *
 *   `crypto.timingSafeEqual` **يرمي** عند اختلاف الطول، فلا يجوز أن يُنادى
 *   على مدخلٍ خارجيٍّ مباشرةً — ومعالجةُ الطول بمخرجٍ مبكّر تُسرِّب الطولَ نفسَه.
 *   فيُجزَّأ الطرفان إلى بصمةٍ ثابتة الطول ثمّ يُقارنان: طولٌ واحدٌ دائمًا.
 */
function timingSafeEqualStr(a, b) {
  const ha = crypto.createHash('sha256').update(String(a), 'utf8').digest();
  const hb = crypto.createHash('sha256').update(String(b), 'utf8').digest();
  return crypto.timingSafeEqual(ha, hb);
}

/** الترويسةُ القانونيّةُ الوحيدة. لا أسماءَ بديلةً بلا حاجةٍ مُثبَتة. */
const HEADER = 'x-webhook-secret';

/**
 * أيُقبَل هذا الإشعار؟
 *
 *   **لا يقرأ `req.query` إطلاقًا** — وهذا جزءٌ من العقد لا تفصيلُ تنفيذ:
 *   ما في المسار يُكتَب في سجلّات الوسطاء ويبقى في `Referer`.
 *   **ولا يسقط إلى `row.apiKey`** — مفتاحُ الصادر يُشارَك مع الشركة ويمرّ في
 *   طلباتٍ خارجة، فلا يصلح إذنًا للوارد.
 *
 * @param {{ webhookSecret?: string }} row صفُّ المزوّد
 * @param {object} headers ترويساتُ الطلب
 */
function verifyWebhookSecret(row, headers = {}) {
  const secret = (row && row.webhookSecret) || '';
  if (!secret) return false;                       // لا سرَّ مضبوطًا ⇒ بابٌ مغلق
  const given = headers[HEADER] || '';
  if (!given) return false;
  return timingSafeEqualStr(String(given), secret);
}

module.exports = { verifyWebhookSecret, timingSafeEqualStr, HEADER };

'use strict';
// ============================================================
// **فحصٌ لا ينطبق ليس فحصًا فاشلًا.**
//
//   قِيس على Promo Livraison من لوحة صاحب المشروع: الشركةُ **قبلت
//   المفتاح** («ردَّت الشركةُ بالقبول»)، وكلُّ الفحوص خضراء — ثمّ ❌ واحدةٌ
//   على «المدن مربوطة»، ولافتةٌ تقول «بعض الفحوص لم تنجح».
//
//   والمزامنةُ لا تقع إلّا لمن `cities: 'api'` — وذاك صوابٌ: جدولٌ مكتوبٌ
//   عندنا لا يُثبت أنّ مفتاحَ التاجر يعمل. فمزوّدٌ جدولُه ثابتٌ يُقابَل
//   بأحمرَ **لا سبيلَ إلى إزالته**: لا زرَّ مزامنةٍ يظهر له أصلًا.
//
//   وإنذارٌ كاذبٌ أسوأُ من غياب الفحص: يُعلَّم التاجرُ أن يتجاهل الأحمر،
//   فيتجاهله يومَ يكون حقيقيًّا.
// ============================================================
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const SRC = fs.readFileSync(path.join(__dirname, '..', 'routes', 'delivery.js'), 'utf8');

test('ربطُ المدن يُحكَم عليه بالفشل **فقط** لمن يستطيع المزامنة', () => {
  const block = SRC.split("add('mapping'")[1]?.split('});')[0] || '';
  assert.ok(block, 'اختفى فحصُ ربط المدن — الحارسُ أعمى');
  assert.match(block, /syncable \? maps\.length > 0 : null/,
    '**الفحصُ يحكم بالفشل على مزوّدٍ لا يستطيع المزامنة** — أحمرُ بلا علاج');
  const decl = SRC.split("add('mapping'")[0];
  assert.match(decl, /const syncable = plugin\.capabilities\?\.cities === 'api'/,
    'شرطُ الانطباق لا يُقرأ من قدرة المزوّد');
});

test('و«لا ينطبق» لا يُحسَب فشلًا في الحصيلة', () => {
  assert.match(SRC, /checks\.filter\(c => c\.ok === false\)/,
    'الحصيلةُ تعدّ `null` فشلًا — فتبقى اللافتةُ الكاذبةُ رغم الإصلاح');
});

test('والمزامنةُ نفسُها تبقى على `api` وحدَه — لا تُوسَّع تخلّصًا من الأحمر', () => {
  // أسهلُ «إصلاحٍ» أن نكتب خرائطَ من جدولنا الثابت فيصير الفحصُ أخضر.
  // وذاك يجعل الفحصَ يشهد على أنفسنا لا على مفتاح التاجر — فحصٌ يُصدّق
  // نفسَه دائمًا، وهو أسوأُ من فحصٍ لا ينطبق.
  const sync = SRC.split('saveCityMappings')[0];
  assert.match(sync, /capabilities\?\.cities === 'api' && typeof plugin\.getCities/,
    'المزامنةُ صارت تقبل الجدولَ الثابت — الفحصُ يشهد على نفسه');
});

'use strict';

// ============================================================
// «وافقتُ على الطلب ولم يُرسَل لشركة التوصيل» — سؤالُ المالك.
//
//   ── الجوابُ، مقيسًا ──
//   الموافقةُ **ليست** شحنًا بالتصميم: للشحن زرُّه («🚚 إنشاء الشحنة»).
//   وهناك مفتاحٌ يجعلها تشحن — `delivery.autoSendOnApproval` — وهو
//   **مطفأٌ افتراضيًّا** (`types.ts:397`).
//
//   ── والعطبُ الحقيقيُّ الذي كُشف عند القياس ──
//   الفرعُ التلقائيُّ كان **ينادي الخادمَ نفسَه عبر HTTP**:
//       fetch(`${req.protocol}://${req.get('host')}/api/delivery/create/…`)
//   وهي أهشُّ طريقةٍ لاستدعاء دالّةٍ في نفس العمليّة: `req.protocol` خلف
//   وسيطٍ يُعطي `http` بينما المنصّةُ تفرض HTTPS، فيُرفَض الطلبُ أو يُعاد
//   توجيهُه — والتاجرُ لا يرى إلّا صمتًا. وهو **مسارُ شحنٍ ثانٍ** بعد أن
//   وُحِّد المسارُ في `lib/shipmentAttempt`.
//
//   ولم يكن على هذا الفرع **اختبارٌ واحد**. فلا أحدَ كان يعرف إن كان يعمل.
// ============================================================

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const SRC = (f) => fs.readFileSync(path.join(__dirname, '..', f), 'utf8');

/**
 * **الكودُ بلا تعليقات.** أوّلُ تشغيلٍ لهذا الملفّ سقط على تعليقٍ كتبتُه أنا
 * يصف العطبَ المحذوف — فكان الحارسُ يقرأ الكلامَ لا الفعل. وحارسٌ يُمسك
 * وصفَ العطب بدل العطب يسقط على مَن يوثّق ويمرّ على مَن يُعيده بلا كلمة.
 */
const CODE = (f) => SRC(f)
  .replace(/\/\*[\s\S]*?\*\//g, ' ')
  .split('\n').map(l => l.replace(/(^|[^:])\/\/.*$/, '$1')).join('\n');

test('الموافقةُ لا تشحن إلّا بمفتاحٍ مُعلَن — والافتراضُ ألّا تشحن', () => {
  // شحنٌ بلا طلبٍ صريحٍ يُنشئ شحنةً حقيقيّةً بمالٍ حقيقيّ عند كلّ موافقة.
  // فالافتراضُ «لا»، والمفتاحُ موجودٌ لمن أراد.
  const types = SRC('../src/types.ts');
  assert.match(types, /autoSendOnApproval:\s*false/, 'الشحنُ التلقائيُّ صار افتراضًا');
  // **الشرطُ نفسُه لا ذِكرُ الاسم.** أوّلُ سَبرٍ نزع الشرطَ من `if` ومرّ
  // الحارسُ: الاسمُ باقٍ في سطر `console.log` فوقه. حارسٌ يقبل ذِكرَ الشيء
  // بدل فعله يمرّ على أخطر تغييرٍ ممكنٍ هنا — شحنٌ حقيقيٌّ بلا إذن.
  const code = CODE('routes/orders.js');
  assert.match(code, /if\s*\(\s*settings\.delivery\?\.autoSendOnApproval\s*&&/,
    'الموافقةُ تشحن بلا أن تسأل عن المفتاح');
});

test('والمفتاحُ له زرٌّ يُرى — لا إعدادٌ لا سبيلَ إلى تشغيله', () => {
  // مفتاحٌ في `types.ts` بلا زرٍّ في الواجهة إعدادٌ لا يُغيَّر أبدًا، ويبقى
  // التاجرُ يسأل «لماذا لا يُرسَل؟» بلا جوابٍ يستطيع تنفيذَه.
  //   والاسمُ يُطابَق **كاملًا**: `autoSendOnApprovalX` تحوي الاسمَ ولا تقرأ
  //   المفتاحَ نفسَه. سَبرٌ بإعادة تسميةٍ حرفٍ واحدٍ مرّ على الحارس أوّلَ مرّة.
  const ui = SRC('../src/pages/DeliveryPage.tsx') + SRC('../src/pages/SettingsPage.tsx');
  assert.match(ui, /\bautoSendOnApproval\b/, 'المفتاحُ بلا زرٍّ في أيّ صفحة');
});

test('**مسارُ شحنٍ واحد**: الموافقةُ تنادي `runShipment` لا الخادمَ عبر HTTP', () => {
  const orders = SRC('routes/orders.js');
  assert.match(orders, /require\('\.\.\/lib\/shipmentAttempt'\)/,
    'الموافقةُ لا تعرف مسارَ الشحن الموحَّد');
  assert.match(orders, /await runShipment\(\{/, 'المفتاحُ مقروءٌ ولا يُستدعى الشحن');
  // الحارسُ الأهمّ: لا عودةَ إلى نداء الخادم نفسَه.
  const code = CODE('routes/orders.js');
  assert.ok(!/req\.protocol/.test(code),
    'عاد نداءُ الخادم نفسِه عبر HTTP — يسقط خلف أيّ وسيطٍ يفرض HTTPS');
  assert.ok(!/api\/delivery\/create/.test(code), 'عاد المسارُ الثاني للشحن');
});

test('الأبوابُ الثلاثةُ تسلك نفسَ الدالّة — الزرُّ والمُعيدُ والموافقة', () => {
  // ثلاثةُ مداخلَ ومسارُ شحنٍ واحد. ونسختان تتباعدان في شحنةٍ حقيقيّةٍ لزبون
  // — وهو ما وقع في هذا المشروع مرّةً وكلّف توحيدًا كاملًا.
  for (const [file, label] of [
    ['routes/delivery.js', 'زرُّ «إنشاء الشحنة»'],
    ['index.js', 'المُعيدُ الدوريّ'],
    ['routes/orders.js', 'الموافقةُ التلقائيّة'],
  ]) {
    assert.match(SRC(file), /shipmentAttempt/, `${label} لا يسلك المسارَ الموحَّد`);
  }
});

test('وإخفاقُ الشحن لا يُسقط الموافقة', () => {
  // الموافقةُ فعلٌ تجاريٌّ تمّ: خُصم المخزونُ وأُشعِر الزبون. ولو رمى الشحنُ
  // فأسقط المسارَ كلَّه لعاد الطلبُ «بانتظار» بعد أن أُخبِر صاحبُه بالتأكيد.
  const orders = SRC('routes/orders.js');
  const at = orders.indexOf('await runShipment({');
  assert.ok(at > 0);
  const around = orders.slice(Math.max(0, at - 700), at + 900);
  assert.match(around, /try\s*\{/, 'الشحنُ التلقائيُّ بلا حارسِ استثناء');
  assert.match(around, /catch/, 'استثناءٌ في الشحن يُسقط الموافقةَ كلَّها');
});

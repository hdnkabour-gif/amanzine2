'use strict';
// ============================================================
// رابطُ الإشعار — **الطرفُ الذي لم يُعطَ لأحد**.
//
//   `POST /api/webhooks/delivery/:providerRowId` يعمل ويُطبّع الحالةَ ويحرّك
//   دورةَ حياة الطلب. وشركاتُ التوصيل تعرض في لوحاتها حقلًا اسمُه «Webhook»
//   تنتظر رابطًا. ولم يكن في التطبيق **مكانٌ واحدٌ يُظهر ذلك الرابط** — لا
//   صفحةَ ولا زرَّ نسخ. بابٌ مفتوحٌ على خادم التاجر لا يعرف عنوانَه.
//
//   والسرُّ هو `apiKey` الصفِّ نفسُه: بلا سرٍّ يُردُّ كلُّ إشعارٍ بـ401. وشركةٌ
//   تُدار بلوحةٍ فقط لا تُعطي مفتاحًا ⇒ العمودُ فارغ ⇒ الرابطُ ميّتٌ من أوّل
//   يوم. ولذلك «ولّد سرّ» — والطرفان يتّفقان عليه، لا الشركةُ تمنحه.
// ============================================================
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..', '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

const WEBHOOKS = read('server/routes/webhooks.js');
const PAGE = read('src/pages/DeliveryPage.tsx');

test('المسارُ ما زال قائمًا بالشكل الذي يُبنى منه الرابط', () => {
  // الحارسُ يقرأ الطرفَين: لو تغيّر شكلُ المسار وبقيت الواجهةُ تبني الرابطَ
  // القديمَ لصار زرُّ النسخ يُعطي عنوانًا يبدو صحيحًا ولا يصل — وهو أسوأُ من
  // غياب الزرّ، لأنّ التاجرَ سيظنّ أنّه ربَط ثمّ ينتظر إشعاراتٍ لا تأتي.
  assert.match(WEBHOOKS, /router\.post\('\/delivery\/:providerRowId'/,
    'تغيّر شكلُ مسار الإشعار — والرابطُ المعروضُ في الواجهة صار كاذبًا');
});

test('والسرُّ يبقى شرطًا — من الترويسة وحدَها (حُدِّث في المرحلة ①)', () => {
  // ── **تغيُّرُ عقدٍ مقصود، لا كسرُ اختبار** ──────────────────────
  //   كان هذا الحارسُ يشترط قبولَ `?secret=` ويعلّل: «لوحاتُ الشركات لا تُرسل
  //   رؤوسًا مخصّصة، فالرابطُ وحدَه ما تملكه». والمرحلةُ ① أزالت ذلك المسار،
  //   وثلاثةُ أسبابٍ تسند القرار:
  //
  //   ①  ما في المسار يُكتَب في سجلّ كلّ وسيطٍ وممثّلٍ عكسيّ ويبقى في
  //      `Referer`. سرُّ قبولٍ لمسارٍ عامٍّ لا يُنشَر هكذا.
  //   ②  **الواجهةُ نفسُها كانت تقول العكس** منذ زمن: نصُّ `DeliveryPage`
  //      يطلب من التاجر وضعَ السرّ في `x-webhook-secret` «بلا ما تحطّو ف
  //      الرابط». فالمسارُ كان يقبل ما تنهى عنه شاشتُه.
  //   ③  السرُّ **يُولَّد عندنا** ويُلصَق في لوحة الشركة، فليس مفروضًا علينا
  //      من طرفٍ خارجيّ.
  //
  //   **ويبقى هذا مطلبَ توافقٍ مفتوحًا ولم يُحسَم بدليل:** لم تُختبَر أيُّ لوحةِ
  //   شركةِ توصيلٍ حقيقيّةٍ هنا (F-025 محجوبة: لا اعتمادَ صندوقِ رمل). فإن
  //   ثبت أنّ شركةً بعينها لا تُرسل رؤوسًا، فالحلُّ **مسارُ توافقٍ مسمّى لها**
  //   بسرٍّ منفصلٍ ومحدودِ الصلاحيّة — لا إعادةُ فتحِ سرِّ الاستعلام للجميع.
  // **يُقتطَع معالجُ التوصيل وحدَه.** أوّلُ صياغةٍ قصّت «كلَّ ما بعد المسار»،
  //   فابتلعت مسارَ Meta الذي يقرأ `req.query['hub.verify_token']` بحقٍّ —
  //   وهو خارج نطاق هذه المرحلة (§6). حارسٌ يقيس أكثرَ من موضعه يتّهم بريئًا.
  const start = WEBHOOKS.indexOf(":providerRowId'");
  const nextRoute = WEBHOOKS.indexOf('router.', WEBHOOKS.indexOf('res.json({ ok: true, orderId'));
  // ويُجرَّد التعليقُ أوّلًا: الشرحُ يذكر `req.query.secret` بوصفه العطبَ
  //   المُزال، فحارسٌ يقرأ التعليقَ يتّهم الشرحَ بأنّه الكود.
  const h = WEBHOOKS.slice(start, nextRoute > start ? nextRoute : undefined)
    .split('\n').filter(l => !/^\s*(\/\/|\*|\/\*)/.test(l)).join('\n');
  assert.match(h, /verifyWebhookSecret\(/, 'بابُ الإشعار لم يعد يستعمل مالكَ المصادقة');
  assert.doesNotMatch(h, /req\.query/, 'عاد سرُّ الاستعلام — انظر التعليل أعلاه قبل إعادته');
  assert.match(h, /401/, 'صفٌّ بلا سرٍّ صار يقبل الإشعارات — المسارُ عامٌّ، فهذا فتحُه للجميع');
});

test('**والواجهةُ تُولّد سرَّ الوارد لا مفتاحَ الصادر**', () => {
  // ارتدادٌ كان سيقع صامتًا: الخادمُ صار يقرأ `webhookSecret`، وزرُّ «ولّد سرّ»
  //   كان ما يزال يكتب `apiKey`. فالتاجرُ يضغط، ويُقال له «تولّد السرّ»،
  //   ولا يُقبَل إشعارٌ واحد — بابٌ ميّتٌ يبدو حيًّا.
  assert.match(PAGE, /p\.webhookSecret/, 'الواجهةُ تقرأ سرَّ الوارد من حقلٍ آخر');
  assert.match(PAGE, /onSave\(\{ \.\.\.p, webhookSecret:/, 'زرُّ التوليد لا يكتب سرَّ الوارد');
  assert.doesNotMatch(PAGE, /\?secret=\$\{encodeURIComponent/, 'الرابطُ المنسوخُ ما زال يحمل السرَّ في المسار');
});

test('**والتاجرُ يرى رابطَه** — البابُ الذي كان ناقصًا', () => {
  assert.match(PAGE, /api\/webhooks\/delivery\//,
    'لا مكانَ في التطبيق يُظهر رابطَ الإشعار — التاجرُ يملك بابًا ولا يعرف عنوانَه');
  assert.match(PAGE, /window\.location\.origin/,
    'الرابطُ يُبنى من مصدرٍ غير العنوان الذي يراه التاجر — متغيّرٌ خاطئٌ يُنتج رابطًا لا يصل');
  assert.match(PAGE, /clipboard\.writeText/, 'رابطٌ يُعرَض ولا يُنسَخ — يُكتب باليد فيُخطَأ فيه');
});

test('ومن لا سرَّ له يستطيع أن يُولّده — وإلّا فالرابطُ ميّتٌ من أوّل يوم', () => {
  assert.match(PAGE, /getRandomValues/,
    'لا توليدَ للسرّ (أو يُولَّد بـ`Math.random`) — وهو سرُّ قبولٍ لمسارٍ عامّ');
  assert.ok(!/Math\.random\(\)[\s\S]{0,120}apiKey/.test(PAGE),
    'السرُّ يُولَّد بعشوائيّةٍ قابلةٍ للتنبّؤ');
});

'use strict';
// ============================================================
// رابطُ الإشعار — **الطرفُ الذي لم يُعطَ لأحد**.
//
//   `POST /api/webhooks/delivery/:providerRowId` يعمل ويُطبّع الحالةَ ويحرّك
//   دورةَ حياة الطلب. وشركاتُ التوصيل تعرض في لوحاتها حقلًا اسمُه «Webhook»
//   تنتظر رابطًا. ولم يكن في التطبيق **مكانٌ واحدٌ يُظهر ذلك الرابط** — لا
//   صفحةَ ولا زرَّ نسخ. بابٌ مفتوحٌ على خادم التاجر لا يعرف عنوانَه.
//
//   والسرُّ هو `apiKey` الصفِّ نفسُه: بلا سرٍّ يُردُّ كلُّ إشعارٍ بـ401. وشركةٌ
//   تُدار بلوحةٍ فقط لا تُعطي مفتاحًا ⇒ العمودُ فارغ ⇒ الرابطُ ميّتٌ من أوّل
//   يوم. ولذلك «ولّد سرّ» — والطرفان يتّفقان عليه، لا الشركةُ تمنحه.
// ============================================================
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..', '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

const WEBHOOKS = read('server/routes/webhooks.js');
const PAGE = read('src/pages/DeliveryPage.tsx');

test('المسارُ ما زال قائمًا بالشكل الذي يُبنى منه الرابط', () => {
  // الحارسُ يقرأ الطرفَين: لو تغيّر شكلُ المسار وبقيت الواجهةُ تبني الرابطَ
  // القديمَ لصار زرُّ النسخ يُعطي عنوانًا يبدو صحيحًا ولا يصل — وهو أسوأُ من
  // غياب الزرّ، لأنّ التاجرَ سيظنّ أنّه ربَط ثمّ ينتظر إشعاراتٍ لا تأتي.
  assert.match(WEBHOOKS, /router\.post\('\/delivery\/:providerRowId'/,
    'تغيّر شكلُ مسار الإشعار — والرابطُ المعروضُ في الواجهة صار كاذبًا');
});

test('والسرُّ يبقى شرطًا — لا إشعارَ يُقبَل بلا سرّ', () => {
  const h = WEBHOOKS.split(":providerRowId'")[1] || '';
  assert.match(h, /x-webhook-secret/, 'رأسُ السرّ لم يعد مقروءًا');
  assert.match(h, /req\.query\.secret/,
    '`?secret=` لم يعد مقبولًا — ولوحاتُ الشركات لا تُرسل رؤوسًا مخصّصة، فالرابطُ وحدَه ما تملكه');
  assert.match(h, /!secret[\s\S]{0,80}401|401/,
    'صفٌّ بلا سرٍّ صار يقبل الإشعارات — المسارُ عامٌّ، فهذا فتحُه للجميع');
});

test('**والتاجرُ يرى رابطَه** — البابُ الذي كان ناقصًا', () => {
  assert.match(PAGE, /api\/webhooks\/delivery\//,
    'لا مكانَ في التطبيق يُظهر رابطَ الإشعار — التاجرُ يملك بابًا ولا يعرف عنوانَه');
  assert.match(PAGE, /window\.location\.origin/,
    'الرابطُ يُبنى من مصدرٍ غير العنوان الذي يراه التاجر — متغيّرٌ خاطئٌ يُنتج رابطًا لا يصل');
  assert.match(PAGE, /clipboard\.writeText/, 'رابطٌ يُعرَض ولا يُنسَخ — يُكتب باليد فيُخطَأ فيه');
});

test('ومن لا سرَّ له يستطيع أن يُولّده — وإلّا فالرابطُ ميّتٌ من أوّل يوم', () => {
  assert.match(PAGE, /getRandomValues/,
    'لا توليدَ للسرّ (أو يُولَّد بـ`Math.random`) — وهو سرُّ قبولٍ لمسارٍ عامّ');
  assert.ok(!/Math\.random\(\)[\s\S]{0,120}apiKey/.test(PAGE),
    'السرُّ يُولَّد بعشوائيّةٍ قابلةٍ للتنبّؤ');
});

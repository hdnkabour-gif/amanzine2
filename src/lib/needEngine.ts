/**
 * **أيسمّي هذا المفهومُ مجالًا، أم هو عنوانُ بابٍ في فهرس؟**
 *
 *   وُلدت هذه الدالّة من تراجعٍ أحدثتُه: لمّا صار انحلالُ المفهوم كافيًا
 *   لإسقاط سؤال التصنيف، سقط سؤالُ «أنا حرفي» كذلك — و«حرفي» تنحلّ إلى
 *   `artisanat_et_m_tiers_manuels`، أي **«الحرف والصنائع»**. وهي جوابُ
 *   السؤال بعينه («🔧 حرفيّ») لا شيءٌ أخصُّ منه، فإسقاطُه يترك الرجلَ بلا
 *   حرفةٍ معلومة.
 *
 *   ── والفرقُ مقيسٌ لا مُخترَع ──
 *   فُحصت بنيةُ المفهومَين، فظهر توقيعٌ بنيويّ: دارجةُ هذا المفهوم
 *   **`` `crafts` ``** — كلمةٌ إنجليزيّةٌ بين علامتَي اقتباسٍ خلفيّتَين، أي
 *   **خانةُ جدولٍ** لا كلمةٌ ينطقها أحد. وأعمدةُ لغاته مُزاحة (`fr` فيه
 *   عربيّةٌ و`en` فيه فرنسيّة). وهو **سطرُ عنوانٍ** في ملفّ CSV صار مفهومًا.
 *
 *   ومسحٌ على المفاهيم كلِّها: **اثنان لا غير** يحملان هذا التوقيع. فليست
 *   قاعدةً واسعةً تُسقط معرفةً حقيقيّة، ولا قائمةً مكتوبةً بيدٍ تتخلّف عن
 *   البيانات — بل صفةٌ في البيانات نفسِها.
 *
 *   ── وحدُّها ──
 *   تُستعمل **هنا وحدَها**: سؤالُ التصنيف لا يُسقَط بعنوان باب. ولا تُقصى
 *   هذه المفاهيمُ من الفهم كلِّه — «طوموبيل» أحدُهما، ومن يبحث عن سيّارةٍ
 *   يجب أن يجدها. وإصلاحُ البيانات نفسِها في ملفّات الحساب الآخر، فأُبلغه.
 */
function namesADomain(c: { id?: string; concept?: { darija?: string } } | null | undefined): boolean {
  if (!c?.id) return false;
  return !/^`.*`$/.test(String(c.concept?.darija || ''));
}

// المدخل العام: يفهم النيّة ثم يُثريها بالسياق (Understanding = طلب + سياق).
export function parseNeed(raw: string, ctx: NeedContext = {}): NeedResult {
  // طبقةٌ أولى — «ماذا يحاول هذا الإنسان أن يفعل؟» قبل تصنيف المهنة/المنتج.
  const human = readHuman(raw);
  let hr = human.intent !== 'NONE' ? humanResult(human.intent) : null;

  // **لا تسأل سؤالًا تعرف جوابه.**
  //
  //   قياسٌ من أهمّ لحظةٍ في المشروع — الحلّاقُ يكتب في محلّه «عندي محل حلاقة»:
  //     المفهوم:  `barber` ✓ محلول
  //     النيّة:   `create_service` ✓ صحيحة
  //     والسؤال: «شنو نوع الخدمة اللي كتقدّم؟ 🔧 حرفيّ / 🎓 مهنيّ / 🏪 محلّ»
  //
  //   يعرف أنّه حلّاقٌ ثمّ يسأله إن كان حرفيًّا أم مهنيًّا. والسحرُ يموت هناك.
  //   السببُ بنيويّ: طبقةُ النيّة الإنسانيّة تُجيب أوّلًا وتُرجع سؤالَ تصنيفٍ
  //   عامًّا، فلا يصل الدورُ إلى المعرفة التي حلّت المفهومَ سلفًا.
  //
  //   والشرطُ ضيّقٌ عمدًا: يسقط **سؤالُ التصنيف** وحدَه حين يكون المجالُ
  //   معلومًا. أمّا الاستيضاحاتُ الأخرى فتبقى — من قال «عندي مشكل» يُسأل عن
  //   مشكله ولو عرفنا جهازَه.
  //
  //   ── **والحارسُ كان صحيحًا ومُعطَّلًا بصمت** (من شاشة صاحب المشروع) ──
  //
  //     «عندي مشكل فالتلفازة»
  //        المفهوم: `tv_repair` ✓ محلول
  //        والسؤال: «أشنو نوع المشكل؟ … ❄️ **جهاز خربان** (ثلّاجة، مكيّف…)»
  //
  //   قرأ الجوابَ ثمّ عرضه خيارًا. وشرطُه الثاني كان `categoryForConcept` —
  //   وهي دالّةٌ تختار **قالبَ الاستمارة** (حقولُ سلعةٍ أم حقولُ خدمة)، لا
  //   تقيس معرفتَنا بالمجال. و`tv_repair` لا تطالب بها فئةٌ ولا `services[]`
  //   لها، فرجعت `undefined` — فسقط الحارسُ **مفتوحًا** على الحالة التي
  //   كُتب لها بالضبط، ولم يظهر ذلك في أيّ اختبار.
  //
  //   والسؤالُ الصحيح **«هل عُرف المجال؟»**، وجوابُه أنّ المفهومَ انحلّ.
  //   وقالبُ الاستمارة سؤالٌ آخرُ تمامًا يُطرَح في موضعٍ آخر — ونيابةُ سؤالٍ
  //   عن سؤالٍ تعمل حتّى تكفّ عن العمل بلا صوت.
  const DOMAIN_QUESTIONS = ['service_kind', 'problem_kind'];
  if (hr?.steps?.length && DOMAIN_QUESTIONS.includes(hr.steps[0].clarifyId || '')
      && namesADomain(resolveConcept(raw))) {
    hr = null;                       // نعرف المجال ⇒ لا نسأل عنه، نُكمل بالمعرفة
  }
  // الموقفُ يُحسَب مرّةً ويُرافق النتيجةَ إلى آخرها — لا يُحسَب ثمّ يُرمى.
  const stance = stanceOf(raw);
  if (hr) {
    hr.confidence = confidenceOf(hr);
    hr.stance = stance;
    hr.object = buildNeedObject(hr, raw, ctx);
    if (hr.object) { hr.object.confidence = hr.confidence; hr.object.reason = human.reason; }
    return hr;
  }
  const r = enrich(coreParse(raw), normalize(raw), ctx);
  r.confidence = confidenceOf(r);
  // **مَن أخبر عن حاجةِ حياةٍ طلبَ ولم يَعرض.** «عندي مولود جديد» تبدأ بـ«عندي»
  // وهي علامةُ عرض، فكان الأبُ الجديدُ يُقرأ عارضًا. والقاعدةُ تُطبَّق هنا لا
  // في `detectStance` كي لا تستورد طبقةُ المعرفة طبقةَ الأهداف فتدور الحلقة.
  r.stance = detectLifeNeed(raw) ? 'seek' : stance;
  r.object = buildNeedObject(r, raw, ctx);
  if (r.object) r.object.confidence = r.confidence;
  return r;
}


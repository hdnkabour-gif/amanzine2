function coreParse(raw: string): NeedResult {
  // اسمُ المدينةِ يُنتزَع قبل قراءةِ الموضوع — وإلّا سُمّي طلبُ سبّاكٍ عقارًا.
  const t = maskCities(normalize(raw));
  const urgent = has(t, URGENT);
  // الاتّجاه من طبقة المعرفة — مصدرٌ واحد. كان هنا `wants` بقائمةٍ أفقر (بلا
  // «أبحث» و«محتاج» و«خاصني» و«شكون»)، فكان «أبحث عن سبّاك» يُقرأ إعلانًا عن
  // النفس ويُلقى صاحبُه في صفحة النشر. الاتّجاه الآن يُقرأ مرّةً ويُحترَم.
  const stance = stanceOf(raw);

  // 0) **تصريحٌ عن حالِ الحياة** — يسبق كلَّ قاعدةٍ موضوعيّة.
  //
  //   «تنقلت لدار جديدة» كانت تُقرأ **عرضَ عقارٍ للبيع**: القاعدةُ العقاريّةُ
  //   ترى «دار» فتحسم قبل أن يصل الدورُ إلى الحاجة. ومَن انتقل لدارٍ لا يبيع
  //   دارًا — يحتاج نقلًا وصباغةً وكهرباء.
  //
  //   ولا يدخل هنا إلّا **التصريحُ الصريح** («غادي نتزوج» · «عندي مولود»)،
  //   أمّا المناسبةُ المستنتَجةُ من الوصف («قفطان ديال العرس») فتُفحَص متأخّرةً
  //   وبشرطِ ألّا يكون الطلبُ واضحًا — وإلّا ثرثرنا على من يعرف ما يريد.
  const said = saidLifeNeed(raw);
  if (said && said.concepts.length) return lifeNeedResult(said);

  // 1) مشكل عاجل موصوف (أهمّ حالة): «الماء كيقطر»، «طاح الضو»
  //
  //    **لا تُطلَق على من يَعرض.** «أنا كهربائي فكازا» كانت تُقرأ **عُطلًا
  //    كهربائيًّا عاجلًا** لأنّ «كهربائي» كلمةُ مشكلةٍ أيضًا — فيُستقبَل
  //    الحرفيُّ الذي يعرّف بنفسه بشاشةِ طوارئ. الموقفُ يُقرأ قبل القاعدة،
  //    وهو صنفٌ لا حالة: كلُّ قاعدةِ مشكلةٍ تصلح لأن تنقلب هكذا.
  for (const p of PROBLEM_TO_PRO) {
    if (stance !== 'offer' && has(t, p.kw)) {
      const isUrgent = urgent || p.urgentByDefault;
      return {
        intent: isUrgent ? 'urgent' : 'find_pro',
        label: isUrgent ? 'عاجل' : 'حِرفي',
        color: isUrgent ? 'var(--red,#F5484A)' : 'var(--info,#3B82F6)',
        tags: [`المشكل → ${p.pro}`, ...(isUrgent ? ['اليوم'] : [])],
        url: isUrgent ? `${MARKET}?urgent=1` : MARKET,
        next: isUrgent
          ? `أقرب ${p.pro} متاح الآن — بلا ما تبحث بنفسك.`
          : `${p.pro} متاحون قربك حسب التقييم.`,
      };
    }
  }

  // 2) «أنا كندير…» → إنشاء صفحة خدمة. **عرضٌ صريح فقط**: غياب كلمة طلبٍ ليس
  //    إعلانًا عن النفس. «سبّاك» وحدها لا تعني «أنا سبّاك» — تُسأل في (6.5).
  // «عندي محل للكراء» ليست تعريفًا بالنفس بل إعلانَ عقار. كلمةُ الإعلان
  // (للكراء/للبيع) تحسم قبل أن تُقرأ كلمةُ المهنة.
  const IS_LISTING = has(t, ['للكراء', 'للبيع', 'للإيجار', 'للايجار', 'للتفويت']);
  for (const p of IAM_PRO) {
    if (stance === 'offer' && !IS_LISTING && has(t, p.kw)) {
      return {
        intent: 'create_service',
        label: 'إنشاء خدمة',
        color: 'var(--mint,#12A150)',
        tags: [`مهنة → ${p.pro}`],
        page: 'publish',
        next: `ننشئ صفحة «${p.pro}» ديالك — أمانزين يبني السيناريو المناسب من جملتك.`,
      };
    }
  }

  // 3) إنشاء متجر — صيغتان:
  //    (أ) نيّةٌ صريحة: «بغيت نفتح متجر». كانت تُقرأ **بحثًا عن حِرفيّ** لأنّ
  //        «بغيت» طلبٌ ولا كلمةَ مِهنةٍ بعدها، فيُلقى صاحبُ المشروع في السوق.
  //    (ب) «عندي محل…» — ملكيّةٌ قائمة (لا إن كان يبحث عن مطعمٍ قربه).
  const OPEN_STORE = ['نفتح متجر', 'نفتح حانوت', 'نفتح محل', 'ندير متجر', 'نصاوب متجر',
                      'نبدا متجر', 'متجر ديالي', 'نفتح دكان', 'ندير حانوت'];
  if (has(t, OPEN_STORE)) {
    return {
      intent: 'create_store',
      label: 'إنشاء متجر',
      color: 'var(--mint,#12A150)',
      tags: ['نوع → متجر'],
      page: 'settings',
      next: 'نجهّز متجرك — الاسم، الشعار، والمنتجات — وننشره للزبناء.',
    };
  }
  // «عندي محل **للكراء**» ليست إنشاءَ نشاطٍ بل إعلانَ عقار. الكلمةُ الحاسمة
  // هي ما بعد المحلّ لا المحلُّ نفسُه — وكانت هذه القاعدةُ تسبق قاعدةَ العقار
  // فتبتلعها، فيُساق من يريد كراءَ محلِّه إلى إعداداتِ متجر.
  const LISTING = ['للكراء', 'للبيع', 'للإيجار', 'للايجار', 'للتفويت'];
  if (stance !== 'seek' && !has(t, LISTING)
      && has(t, ['عندي محل', 'محل ديالي', 'مطعم', 'كافي', 'سناك', 'حانوت', 'بقاله'])) {
    // **إن عرفنا نوعَ المحلّ فلنقله.** كان الوسمُ «متجر/مطعم» دائمًا، وهو
    // صحيحٌ ولا ينفع: الطبقةُ الأخرى تعرف أنّه **خضّار** أو **بائعُ سمك**
    // من نفس الجملة. وقياسُ النبض عدَّ ذلك «تفاوتَ دقّة» في أربع جملٍ —
    // عقلان لا يتناقضان، لكنّ أحدَهما يعرف والآخر يكتفي بالعموم.
    // واسمٌ عربيٌّ لا مُعرِّف (القانون ١٠): الوسمُ يُعرَض للإنسان.
    const kind = resolveConcept(raw)?.concept;
    return {
      intent: 'create_store',
      label: 'إنشاء متجر',
      color: 'var(--mint,#12A150)',
      tags: [`نوع → ${kind?.darija || kind?.ar || 'متجر/مطعم'}`],
      page: 'settings',
      next: 'نجهّز متجرك — الاسم، الشعار، والمنتجات — وننشره للزبناء.',
    };
  }

  // 4) عقار (كراء/شراء دار)
  //
  //   ── **و«الدار» تعني البيتَ قبل أن تعني عقارًا يُباع** ─────────
  //
  //     «كنصايب كسكسو **من الدار**» ⇒ **«باغي تعرض عقار للبيع»**
  //
  //   من شاشة صاحب المشروع. وامرأةٌ تطبخ الكسكس في بيتها تُقرأ سمسارةَ
  //   عقار. و«من الدار» ظرفُ مكانٍ لا سلعة — وهي أشيعُ ما يقوله من يبيع
  //   طعامًا مغربيًّا: «من الدار» شهادةُ جودةٍ لا إعلانُ بيع.
  //
  //   والحسمُ من البيانات لا من قائمةٍ جديدة: قِيست الجملُ فظهر أنّ ما هو
  //   عقارٌ حقًّا ينحلّ إلى `real_estate_agency` أو لا ينحلّ إلى شيء
  //   («بغيت نبيع دار» · «عندي شقة للبيع»)، وما ليس عقارًا ينحلّ إلى
  //   **مفهومٍ آخرَ صريح** (`restaurant` هنا). فالمفهومُ المنحلُّ إلى شيءٍ
  //   ثالثٍ يقول إنّ «دار» في هذه الجملة ظرفٌ لا موضوع.
  //
  //   وهو نفسُ مبدأ الملفّ كلِّه — **الأخصُّ قبل الأعمّ** — ونفسُ علاج
  //   «شق» داخل «شقة»: لا يُحذَف العامُّ، بل يُمنَع أن يبتلع الخاصّ.
  //   ── وحدُّه: **الكلمةُ العامّةُ وحدَها تُكبَح** ──────────────────
  //   قِيس أوّلًا على الفرع كلِّه فسقطت «بغيت نكري **سيارة**»: كراءُ السيّارات
  //   يدخل من كلمة «نكري» لا من كلمة «دار»، ومفهومُه ليس عقارًا — فأُقصي
  //   بحقٍّ عن العقار وبغير حقٍّ عن الكراء. فالكبحُ على **بابِ الدخول
  //   العامّ** وحدَه: مَن صرّح بالكراء صرّح، ومَن ذُكرت في جملته «دار» عرضًا
  //   لا يُحسَب عارضَ عقار.
  const settledId = resolveConcept(raw)?.id;
  const settledElsewhere = !!settledId && !/real_estate|3aqar|immo/.test(settledId);
  const byProperty = has(t, ['دار', 'شقه', 'منزل', 'ستوديو', 'فيلا', 'محل تجاري']);
  if ((byProperty && !settledElsewhere) || has(t, RENT)) {
    // العرضُ يُقرأ من **الموقف** لا من كلمةٍ بعينها. كان يشترط «عندي»، فكانت
    // «بغيت نبيع داري» تسقط في البحث — ويُرسَل صاحبُ الدار ليشتري ما يملك.
    // والموقفُ يعرف الملكيّةَ الآن: «داري» · «ديالي» تقلبان الاتّجاه.
    const offering = stance === 'offer';
    if (offering) {
      const pledge = has(t, PLEDGE);
      return {
        intent: has(t, RENT) ? 'rent' : 'sell',
        label: pledge ? 'رهن عقار' : has(t, RENT) ? 'كراء' : 'عقار للبيع',
        color: 'var(--mint,#12A150)',
        tags: [pledge ? 'عرض رهن' : has(t, RENT) ? 'عرض كراء' : 'عرض عقار'],
        page: 'publish',
        next: pledge
          ? 'نبنيو إعلان الرهن — نوضّحو المدّة والشروط.'
          : 'نبنيو إعلان العقار من جملتك مباشرة.',
      };
    }
    // ── **و«شرا ولا كرا؟» لا تُسأل لمن قال «نكري»** ────────────────
    //
    //     «بغيت نكري سيارة»       ⇒ **عقار** + «شرا ولا كرا؟»
    //     «كنقلب على دار للكراء»  ⇒ «شرا ولا كرا؟»
    //
    //   ثالثُ موضعٍ في هذه الدفعة يُسأل فيه عمّا قيل. والسؤالُ بُني لمن قال
    //   «دار» وحدَها ولم يقل أيَّهما يريد — فإن قالها سقط سببُ السؤال.
    //
    //   والعنوانُ كذلك: «عقار» تُقال لمن ذكر دارًا أو شقّة. ومَن دخل من باب
    //   «نكري» وحدَه قد يكري **سيّارة** — فيُسمّى بما يُعرَف عنه: «كراء».
    //   والقاعدةُ على **السؤال** لا على فرعٍ منه: «شرا ولا كرا؟» تسقط متى
    //   قيل أحدُهما — كراءً كان («نكري») أو شراءً («نشري»). فـ«بغيت نشري
    //   دار» كانت تُسأل أيضًا، وهي رابعُ موضعٍ يُسأل فيه عمّا قيل في هذه
    //   الدفعة وحدَها. والصنفُ واحدٌ: سؤالٌ يُطرَح بلا أن يُنظَر في الجواب.
    const wantsRent = has(t, RENT);
    const settled = wantsRent || has(t, BUY);
    return {
      intent: wantsRent ? 'rent' : 'buy',
      label: byProperty ? 'عقار' : 'كراء',
      color: 'var(--info,#3B82F6)',
      tags: wantsRent ? ['كراء'] : [],
      open: wantsRent ? 'واخّا 👍 كتقلّب على شي حاجة للكراء.' : 'مزيان 👍 كتقلب على عقار.',
      ...(settled ? {} : { steps: HOUSE_STEPS }),
      next: settled ? 'نوجّهك لما هو متاح قربك.' : 'نوجّهك للعقارات المناسبة بسؤال واحد.',
      url: MARKET,
    };
  }

  // 5) بيع عام → النشر الموحّد مباشرة (روح AMANZINE: من جملة، لا من نموذج)
  //    «بغيت نشري حاجة للبيع» طلبٌ لا عرض ⇒ الاتّجاه يحسم.
  if (stance !== 'seek' && has(t, SELL)) {
    return {
      intent: 'sell',
      label: 'بيع',
      color: 'var(--ember,#FF6A00)',
      tags: [],
      page: 'publish',
      next: 'نفتح النشر الذكيّ — تكتب أو تصوّر وأمانزين يهيّئ الإعلان تلقائيًّا.',
    };
  }

  // 5.5) طلب مهنة عامّة بالاسم: «كنقلب على طبيب»
  if (has(t, PROFESSIONS)) {
    const pro = PROFESSIONS.find(p => t.includes(p)) || 'مختصّ';
    // طبيب بلا تخصّص = يقين منخفض ⇒ نسأل «شنو التخصّص؟» قبل التوجيه.
    if ((pro === 'طبيب' || pro === 'دكتور') && !has(t, ['اسنان', 'عظام', 'جلد', 'اطفال', 'عيون', 'قلب', 'عام'])) {
      return {
        intent: 'find_pro', label: 'حِرفي', color: 'var(--info,#3B82F6)', tags: ['تخصّص → طبيب'],
        open: 'واخّا 👍 باغي طبيب.',
        steps: [{ q: 'شنو التخصّص؟', clarifyId: 'doctor_specialty', options: [
          { id: 'general', label: 'عامّ', url: MARKET, next: 'أطبّاء عامّون متاحون قربك.' },
          { id: 'dental', label: 'أسنان', url: MARKET, next: 'أطبّاء أسنان قربك.' },
          { id: 'ortho', label: 'عظام', url: MARKET, next: 'أطبّاء عظام قربك.' },
          { id: 'derma', label: 'جلد', url: MARKET, next: 'أطبّاء جلد قربك.' },
          { id: 'pediatric', label: 'أطفال', url: MARKET, next: 'أطبّاء أطفال قربك.' },
        ] }],
        next: 'نحدّد التخصّص باش نوصلك بالأنسب.',
      };
    }
    return {
      intent: urgent ? 'urgent' : 'find_pro',
      label: urgent ? 'عاجل' : 'حِرفي',
      color: urgent ? 'var(--red,#F5484A)' : 'var(--info,#3B82F6)',
      tags: [`تخصّص → ${pro}`, ...(urgent ? ['اليوم'] : [])],
      url: urgent ? `${MARKET}?urgent=1` : MARKET,
      next: `نوصلك بأقرب ${pro} متاح${urgent ? ' الآن' : ''} قربك.`,
    };
  }

  // 6) طلب حِرفي بالاسم: «بغيت سباك»، «بغيت بناي»
  for (const p of IAM_PRO) {
    if (has(t, [p.pro, ...p.kw]) && stance === 'seek') {
      return {
        intent: urgent ? 'urgent' : 'find_pro',
        label: urgent ? 'عاجل' : 'حِرفي',
        color: urgent ? 'var(--red,#F5484A)' : 'var(--info,#3B82F6)',
        tags: [`حرفة → ${p.pro}`],
        open: `واخّا 👍 باغي ${p.pro}.`,
        steps: proStep(p.pro),
        next: `نوصلك بأقرب ${p.pro} مناسب.`,
      };
    }
  }

  // 6.5) حِرفةٌ بلا اتّجاه: «سبّاك» وحدها. لا نخمّن — نسأل سؤالًا واحدًا.
  //      كان التخمين يقول «أنت سبّاك» ويفتح النشر لمن جاء يبحث عن سبّاك؛
  //      وهو أسوأ خطأ ممكن لأنّ أغلب مَن يكتب حرفةً إنّما يطلبها.
  for (const p of IAM_PRO) {
    if (has(t, [p.pro, ...p.kw])) {
      return {
        intent: 'find_pro',
        label: p.pro,
        color: 'var(--info,#3B82F6)',
        tags: [`حرفة → ${p.pro}`],
        open: `${p.pro} 👍 باش نوجّهك صحيح:`,
        steps: [{ q: `واش كتقلّب على ${p.pro}، ولا نتا ${p.pro} وباغي تعلن؟`, options: [
          { label: `🔎 كنقلّب على ${p.pro}`, url: MARKET, next: `نوصّلوك بأقرب ${p.pro} قربك.` },
          { label: `🧰 أنا ${p.pro} — بغيت نعلن`, page: 'publish', next: `ننشئ صفحة «${p.pro}» ديالك من جملة.` },
        ] }],
        next: `سؤالٌ واحد ونوجّهك — بلا ما نخمّنو عليك.`,
      };
    }
  }

  // 7) موعد/حجز
  if (has(t, BOOK)) {
    return {
      intent: 'book',
      label: 'حجز',
      color: 'var(--purple,#8B5CF6)',
      tags: [],
      page: 'bookings',
      next: 'يفتح الحجوزات — تختار المزوّد والوقت المناسب.',
    };
  }

  // ── المحوران معًا: الفعلُ من المفهوم، والاتّجاهُ من الموقف ──────────
  //
  //   القاعدةُ التي تُغني عن قوائمَ يدويّة:
  //     • يطلب + **شيء**  ⇒ شراء        «بغيت كسوة» · «خاصني حاسوب»
  //     • يعرض + **مهنة** ⇒ إنشاء خدمة  «أنا كهربائي»
  //
  //   كان `IAM_PRO` قائمةً يدويّةً بثماني مهنٍ بجانب ١٩٧ مفهومًا في قاعدة
  //   المعرفة، فمن ليست مهنتُه فيها يسقط في العامّ. و«بغيت كسوة» كانت تُقرأ
  //   **بحثًا عن حرفيّ** لأنّ «بغيت» طلبٌ ولا قاعدةَ تقول إنّ الكسوةَ شيءٌ
  //   لا إنسان — فيُساق من يريد ثوبًا إلى قائمة الصنّاع.
  const known = resolveConcept(raw);
  const kind = categoryForConcept(known?.id)?.kind;

  // ── حاجةُ الحياة: ما وراء الطلب ─────────────────────────────
  //
  //   «بنتي داخلة للمدرسة» و«غادي نتزوج» كانتا **نيّةً مجهولة**، و«عندي
  //   مولود جديد» كانت تُقرأ **عرضَ خدمة** — أبٌ جديدٌ يُعامَل كتاجر.
  //
  //   ولا تُفحَص إلّا حين **لا يذكر المستخدمُ شيئًا بعينه**: مَن قال «قفطان
  //   ديال العرس» يعرف ما يريد، فاقتراحُ القاعةِ والتصويرِ عليه ثرثرة. ومَن
  //   قال «غادي نتزوج» لا يعرف من أين يبدأ — وهذا مَن نساعده.
  {
    // المناسبةُ وحدَها (بلا تصريحٍ عن الحال) لا تكفي إن كان الطلبُ واضحًا.
    const need = known ? undefined : occasionLifeNeed(raw);
    if (need && need.concepts.length) return lifeNeedResult(need);
  }

  // إعلانُ عقارٍ ليس تعريفًا بمهنة: «عندي محل للكراء» يقع فيها مفهومُ «محل»
  // وهو خدمةٌ في القاعدة، فتبتلعها قاعدةُ العرض. كلمةُ الإعلان تحسم أوّلًا.
  if (stance === 'offer' && IS_LISTING) {
    const renting = has(t, RENT);
    return {
      intent: renting ? 'rent' : 'sell',
      label: renting ? 'كراء' : 'عرض للبيع',
      color: 'var(--mint,#12A150)',
      tags: [renting ? 'عرض كراء' : 'عرض بيع'],
      page: 'publish',
      next: 'نبنيو الإعلان من جملتك مباشرة.',
    };
  }
  if (stance === 'seek' && kind === 'product') {
    return {
      intent: 'buy',
      label: 'شراء',
      color: 'var(--info,#3B82F6)',
      tags: known?.concept?.ar ? [`المطلوب → ${known.concept.ar}`] : [],
      url: MARKET,
      next: 'نعرضو عليك المتوفّر قربك.',
    };
  }
  // **الذراعُ الرابعة.** كانت ناقصةً، وقياسٌ كشفها: «كنقلب على ميكانيكي»
  // ⇒ `buy` بينما «كنقلب على سباك» ⇒ `find_pro`. السببُ أنّ الحسمَ كان
  // بقائمةِ أسماءِ أشخاصٍ مكتوبةٍ بيد (`SEEKS_PERSON`: مدرس · تقني · حرفي…)
  // لا تعرف «ميكانيكي»؛ والمعرفةُ تعرفه خدمةً منذ البداية. **قاعدةٌ لا قائمة**:
  // مَن طلب خدمةً طلب إنسانًا يؤدّيها، لا سلعةً في السوق.
  if (stance === 'seek' && kind === 'service' && known) {
    return {
      intent: 'find_pro',
      label: known.concept?.ar || 'حِرفي',
      color: 'var(--info,#3B82F6)',
      tags: known.concept?.ar ? [`المطلوب → ${known.concept.ar}`] : [],
      url: MARKET,
      next: 'نلقّيو ليك اللي كيخدم هاد الخدمة قربك.',
    };
  }
  if (stance === 'offer' && kind === 'service') {
    return {
      intent: 'create_service',
      label: 'تعريف',
      color: 'var(--mint,#12A150)',
      tags: known?.concept?.ar ? [`المهنة → ${known.concept.ar}`] : [],
      page: 'publish',
      next: 'نبنيو صفحة نشاطك — الخدمات، المدينة، والتواصل.',
    };
  }

  // 8) شراء / بحث عام
  //
  //   **تمييزٌ لازم:** «كنقلب على» و«نقلب على» في معجم `BUY`، وهما في الدارجة
  //   «أبحث عن» — لا «أشتري». فكان «كنقلب على مدرس دعم» و«بغيت واحد ينقل ليا
  //   الموبيليا» يُقرآن **شراءً** ويُلقى صاحبُهما في السوق يبحث عن سلعة، وهو
  //   يطلب **إنسانًا**. القاعدةُ الآن: مَن يطلب شخصًا يُوجَّه لمن يطلب شخصًا.
  const SEEKS_PERSON = ['شكون', 'واحد ي', 'واحد كي', 'شي واحد', 'مدرس', 'معلم', 'استاذ',
                        'مربيه', 'مدبره', 'عامله', 'حرفي', 'مختص', 'تقني', 'صانع', 'خدام'];
  if (has(t, SEEKS_PERSON) && stance === 'seek') {
    //   النيّةُ محسومة (**إنسانٌ لا سلعة**) والمجالُ قد لا يكون كذلك:
    //   «بغيت شي واحد يقاد ليا الضو» واضحُ الاتّجاه، لكنّ «شي واحد» وحدَها لا
    //   تقول أيَّ حرفة. فنحسم ما نعرف ونسأل عمّا لا نعرف — لا نُلغي السؤالَ
    //   لأنّنا فهمنا نصفَ الجملة، ولا نُلغي الفهمَ لأنّ نصفَها ناقص.
    return {
      intent: 'find_pro',
      label: 'حِرفي',
      color: 'var(--info,#3B82F6)',
      tags: [],
      open: 'واخّا 👍 كتقلّب على شي واحد يعاونك.',
      steps: [domainStep()],
      next: 'سؤالٌ واحد ونوصّلوك بالشخص المناسب — لا بسلعة.',
    };
  }
  if (has(t, BUY) || has(t, ['صباط', 'تليفون', 'حوايج', 'موبيليا', 'ماكله'])) {
    return {
      intent: 'buy',
      label: 'شراء',
      color: 'var(--info,#3B82F6)',
      tags: [],
      url: MARKET,
      next: 'يعرض السوق نتائج مطابقة قربك، حسب الثمن.',
    };
  }

  // 9) إدارة/متابعة (بائع): طلبات، مبيعات، رسائل…
  if (has(t, ['الطلبات', 'شحال بعت', 'المبيعات', 'الارباح', 'الاحصائيات'])) {
    return { intent: 'manage', label: 'متابعة', color: 'var(--ember,#FF6A00)', tags: [], page: 'orders', next: 'يفتح طلباتك وحالاتها.' };
  }
  if (has(t, ['الرسايل', 'رسايل', 'الزبناء', 'محادثات'])) {
    return { intent: 'manage', label: 'متابعة', color: 'var(--ember,#FF6A00)', tags: [], page: 'conversations', next: 'يفتح رسائل زبنائك في مكان واحد.' };
  }

  // 9.5) طبقة المعرفة المتعدّدة اللغات — قبل الاستسلام: هل النصّ (فرنسيّة/إنجليزيّة/
  //      دارجة لاتينيّة) يحمل خدمةً معروفة؟ «je cherche un plombier» ⇒ سبّاك.
  const kc = resolveConcept(raw);
  if (kc && kc.concept?.ar) {
    const svcName = kc.concept.ar;
    return {
      intent: 'find_pro', label: svcName, color: 'var(--info,#3B82F6)', tags: [],
      url: MARKET,
      open: `فهمت 👍 كتقلّب على «${svcName}».`,
      next: `نوصّلك بأقرب «${svcName}» قربك.`,
    };
  }

  // ── **٩٫٦) مَن يدير حسابَه ليس في السوق** ─────────────────────
  //
  //   من شاشتَي صاحب المشروع:
  //
  //     «fin wesselat lcommande deyal tanger»  ⇒ **«أشنو المجال؟ 💧 الماء / ⚡ الكهرباء…»**
  //     «بغيت نبدل النمرة ديالي»                ⇒ **«شنو كتعرض؟ 🧰 خدمة / 🏪 محلّ…»**
  //
  //   والفعلُ في كلتَيهما مقروءٌ بيقين: `view/orders` و`update/phone` بثقة
  //   ٠٫٨٥. فمن يسأل عن طردِه يُسأل عن السباكة، ومن يبدّل نمرتَه يُسأل عمّا
  //   يعرضه للبيع. وهذا هو المستويان اللذان لا يلتقيان في أوضح صورةٍ لهما:
  //   **يقرأ الفعلَ الإداريَّ ثمّ يسأل سؤالَ سوق**.
  //
  //   والسببُ أنّ هذا المحرّك مبنيٌّ على محور السوق وحدَه (`sell`/`buy`/
  //   `find_pro`) — لا يحوي «يبدّل نمرتَه» ولا «يتتبّع طلبَه». فحين لا يجد
  //   بضاعةً يسقط على الاتّجاه، والاتّجاهُ يقول «يطلب» فيسأل سؤالَ طلب.
  //
  //   ولا يُخترَع هنا بابٌ ولا وجهة: يُقال **`manage`** ويُصمَت. البابُ
  //   يعرفه الكتالوجُ من الفعل نفسِه (`decideExecution.dest`)، وهو أدرى به
  //   من محرّك السوق. وسؤالٌ خاطئٌ أسوأُ من لا سؤال.
  //
  //   ── وحدُّه: **٠٫٥ — القراءةُ الضعيفةُ لا تحسم** ──
  //   `readAction` تسقط على `settings` بثقة ٠٫٣٥ حين تجد فعلًا بلا هدف —
  //   و«بغيت نبيع شي حاجة **جديدة**» منها («جديد» فعلُ إنشاءٍ ظاهرًا).
  //   فلو قُبلت لَصار كلُّ بائعٍ «يدير حسابَه». وهو نفسُ الحدّ المكتوب في
  //   `executionPolicy` لنفس السبب.
  const adminAct = readAction(raw);
  if (adminAct && adminAct.confidence >= 0.5) {
    // ── **والعنوانُ يُقال بالدارجة لا يُخترَع** (تراجعٌ أحدثتُه) ────
    //
    //   كتبتُ `label: 'تدبير'` فظهرت على شاشة صاحب المشروع:
    //     **«فهمت أنّك باغي تدبير — صح؟»**
    //   وهي ليست جملةً يقولها مغربيّ. و`interfaceDecision` تركّب
    //   `فهمت أنّك باغي ${label}` — فالعنوانُ يجب أن يكون **فعلًا** يصلح
    //   بعد «باغي»، لا اسمًا مجرّدًا. وهذا القانونُ العاشر بعينه.
    //
    //   والجملةُ الصحيحةُ مكتوبةٌ في الكتالوج أصلًا (`Ability.say`): «تشوف
    //   الطلبات» · «تبدّل النمرة ديالك» · «تزيد تصاور للمنتوج». فتُؤخَذ
    //   منه ولا تُكتَب هنا ثانيةً — ونسختان من نصٍّ واحدٍ تتباعدان.
    const say = abilityFor({ action: adminAct })?.say;
    return {
      intent: 'manage', label: say || describeAction(adminAct), color: 'var(--ember,#FF6A00)',
      // ── **والوسمُ يُقال بالعربيّة كما يُقال العنوان** ────────────────
      //   السطرُ أعلاه يقرأ الاسمَ الإنسانيَّ من الكتالوج، والسطرُ الذي
      //   كان هنا يركّب `${verb}/${object}` من المُعرِّفات الخامّة. فطبقةُ
      //   التسمية تُنادى لحقلٍ وتُتجاوَز للحقل الملاصق له.
      //   والنتيجةُ على شاشة صاحب المشروع: **«فعل → update/phone»** و
      //   **«فعل → view/orders»** — لاتينيّةٌ في وجه من يكتب بالدارجة،
      //   وخرقٌ صريحٌ للقانون العاشر. و`describeAction` تعرف الاسمَين منذ
      //   كُتبت: «نبدّل رقم الهاتف» · «نوريك الطلبات».
      tags: [`فعل → ${describeAction(adminAct)}`],
      next: 'نمشيو مباشرةً للمكان اللي كيتدار فيه هادشي.',
    };
  }

  // 9.7) عرفنا الاتّجاه ولم نعرف المجال. الاتّجاه وحده يستحقّ سؤالًا داخل مساره،
  //      لا سؤالًا عامًّا يعيد المستخدم إلى الصفر. «بغيت شي واحد يقاد ليا الضو»
  //      طلبٌ مؤكّد، و«أنا كندير الحلويات» عرضٌ مؤكّد — كلاهما كان يسقط في «unknown».
  if (stance === 'seek') {
    return {
      intent: urgent ? 'urgent' : 'find_pro', label: 'طلب',
      color: urgent ? 'var(--red,#F5484A)' : 'var(--info,#3B82F6)', tags: ['اتّجاه → طلب'],
      open: 'فهمت أنّك كتقلّب على شي حدّ 👍 نحدّدو المجال ونوصّلوك.',
      steps: [domainStep()],
      next: 'سؤالٌ واحد ونوصّلوك — ما غاديش نرجّعوك للبداية.',
    };
  }
  if (stance === 'offer') {
    // ── **ومَن سمّى نوعَ ما يعرضه لا يُسأل عنه** ────────────────
    //
    //     «عندي سلعة البيع» ⇒ «شنو كتعرض؟ … **📦 سلعة / منتج للبيع**»
    //
    //   من شاشة صاحب المشروع: قال «سلعة»، فعُرضت عليه «سلعة» خيارًا. وهو
    //   نفسُ عطبِ «عندي مشكل فالتلفازة» في سؤالٍ آخر — والسؤالان بُنيا
    //   ليكتشفا ما قيل فيهما سلفًا.
    //
    //   والكلماتُ تُقرأ من **خيارات السؤال نفسِه** لا من قائمةٍ جديدة: مَن
    //   ذكر «سلعة» أو «منتوج» أجاب `product`، ومن ذكر «محلّ» أجاب `store`.
    //   فلا تتباعد قائمتان، ويوم يُضاف خيارٌ تُضاف كلمتُه معه.
    const OFFER_KIND: { id: string; page: Page; words: string[] }[] = [
      { id: 'store',   page: 'settings', words: ['محل', 'المحل', 'متجر', 'المتجر', 'حانوت', 'الحانوت'] },
      { id: 'product', page: 'publish',  words: ['سلعه', 'السلعه', 'منتوج', 'المنتوج', 'منتج', 'بضاعه'] },
      { id: 'service', page: 'publish',  words: ['خدمه', 'الخدمه', 'حرفه', 'الحرفه'] },
    ];
    const kindSaid = OFFER_KIND.find(k => has(t, k.words));
    if (kindSaid) {
      return {
        intent: kindSaid.id === 'store' ? 'create_store' : kindSaid.id === 'product' ? 'sell' : 'create_service',
        label: kindSaid.id === 'store' ? 'إنشاء متجر' : kindSaid.id === 'product' ? 'بيع' : 'تعريف',
        color: 'var(--mint,#12A150)', tags: ['اتّجاه → عرض'],
        page: kindSaid.page,
        next: 'نبنيو ليك الصفحة المناسبة من جملتك مباشرة.',
      };
    }
    return {
      intent: 'create_service', label: 'عرض', color: 'var(--mint,#12A150)', tags: ['اتّجاه → عرض'],
      open: 'فهمت أنّك كتعرض شي حاجة 👋 نعرّفو بيك مزيان.',
      steps: [{ q: 'شنو كتعرض؟', clarifyId: 'offer_kind', options: [
        { id: 'service', label: '🧰 خدمة / حرفة كنقدّمها', page: 'publish', next: 'ننشئ صفحة الخدمة ديالك من جملة.' },
        { id: 'store', label: '🏪 عندي محلّ / متجر', page: 'settings', next: 'نجهّزو المتجر ديالك وننشروه.' },
        { id: 'product', label: '📦 سلعة / منتج للبيع', page: 'publish', next: 'نبنيو الإعلان من وصفٍ ولا تصويرة.' },
        { id: 'realestate', label: '🏠 عقار (كراء، بيع، رهن…)', page: 'publish', next: 'نبنيو إعلان العقار مباشرة.' },
      ] }],
      next: 'نحدّدو نوع العرض باش نبنيو ليك الصفحة المناسبة.',
    };
  }

  // 10) لم نلتقط نيّةً محدّدة → لا نتوقّف ولا نعتذر: نسأل عن **الناقص**.
  //
  //     كان السؤالُ هنا نصًّا ثابتًا مكتوبًا في هذا الفرع. صار يأتي من محرّك
  //     الاستيضاح، فيوم يصير مصدرُ التحليل صورةً أو صوتًا أو نموذجًا لغويًّا،
  //     لا يتغيّر حرفٌ هنا — يتغيّر المحلّل وحدَه. والمحرّكُ لا يعرف وجهةً ولا
  //     صفحة: الوجهاتُ تُلصَق هنا، حيث تُعرَف.
  return clarifyStep(nextClarification({ confidence: 0 }), t);
}

// ── جسرُ الاستيضاح ⇄ الوجهات ────────────────────────────────────────────────
//
//   محرّكُ الاستيضاح يُنتج **معنى** (هويّة سؤالٍ وهويّاتِ أجوبة)؛ وهذا الجدول
//   يُلبسه **وجهةً**. الفصلُ مقصود: المعنى يبقى حين تتبدّل الخريطة، والخريطة

import { hitsWord, normLoose } from './normalize';
import type { Understanding } from './akg/kb';

// ============================================================
// **الدليل — هل فهمنا فعلًا، أم رجعت النيّةُ من المصرف؟**
//
//   ── العطبُ الذي وُلدت منه، مقيسًا سطرًا بسطر ──
//
//   `needEngine.ts:684` تُرجع `find_pro` **حين لا تجد شيئًا** — مصرفًا
//   افتراضيًّا. و`journey.ts:234` تسجّل «ما لم نفهمه» بشرطٍ واحد:
//
//       if (intent === 'unknown') { … reportUnknown(t); }
//
//   و`unknown` **لا تقع أبدًا**، لأنّ المصرفَ سبقها. فالنتيجةُ المقيسة:
//   من اثنتَي عشرة جملةً كتبها صاحبُ المشروع سقطت سبع، و`learning_unknowns`
//   بقيت **فارغةً تمامًا**. القناةُ مبنيّةٌ من طرفَيها ولا يمرّ فيها شيء.
//
//   ── ولماذا هذا أخطرُ من عطبِ واجهة ──
//   لأنّ التطبيقَ **لا يعرف أنّه لم يفهم**. يظنّ أنّه فهم «بحثًا عن حرفيّ»،
//   فيجيب بثقةٍ خاطئة، **ولا يسجّل شيئًا**. وصاحبُ المشروع في طورِ جمعِ
//   «أين يتوقّف وأين يخطئ» — فمصرفٌ صامتٌ يجعل مجموعتَه **فارغةً حيث يجب
//   أن تمتلئ**، ويجعله يقرّر على بياناتٍ تقول إنّ كلَّ شيءٍ بخير.
//
//   ── وحدُّ هذه الطبقة ──
//   **لا تُغيّر `parseNeed` ولا تنازعها.** تقرأ ما أعادته وتسأل سؤالًا واحدًا:
//   **على أيّ دليلٍ؟** فلو حُذفت لبقي التوجيهُ كما هو — تسقط الصراحةُ وحدَها.
//   وهذا شرطُ ألّا تصير طبقةً سادسةً تنازع الخمسَ القائمة.
// ============================================================

/**
 * **أرضيّةُ الفهم** — على أيّ شيءٍ يقف هذا الجواب.
 *
 *   وترتيبُها ليس ذوقًا: `about_self` و`stuck` **قراءتان صريحتان** يجب أن
 *   تسبقا `echo`، لأنّ «شكون نتا» ليست «لم نفهم» — نحن نعرف بالضبط ما سأل.
 *   ومَن خلط الاثنَين سجّل سؤالًا معروفًا في خانة المجهول، فأفسد العدّاد
 *   الذي يُبنى عليه القرار.
 */
export type Ground =
  /** فهمٌ له دليلٌ في الجملة: مفهومٌ أو فعلٌ أو نيّةٌ لا تُقال بالصدفة. */
  | 'grounded'
  /** سؤالٌ عن التطبيق نفسِه: مَن أنت · ما هذا · فيمَ تنفعني. */
  | 'about_self'
  /** الإنسانُ واقفٌ: «مافهمتش» · «كيفاش» عاريةً · «أشنو». */
  | 'stuck'
  /** النيّةُ رجعت من المصرف بلا دليل — وهذه هي التي يجب أن تُسجَّل. */
  | 'echo';

export interface Reading {
  ground: Ground;
  /** لماذا حُكم هكذا — يُكتب في السجلّ، فيُقرأ بعد شهرٍ بلا فتح الكود. */
  why: string;
}

/**
 * **السؤالُ عن التطبيق نفسِه.**
 *
 *   وهي أوّلُ ثلاثةِ أسئلةٍ يسألها أيُّ مغربيٍّ يفتح تطبيقًا لأوّل مرّة:
 *   «شكون نتا؟» · «شنو هادشي؟» · «فاش غادي تنفعني؟». وجوابُها اليومَ —
 *   مقيسًا — **«شنو محتاج بالضبط؟»**. أي أنّ أوّلَ ثلاثِ لحظاتٍ في حياة
 *   المستخدم الجديد كلُّها إخفاق.
 *
 *   ── ولماذا الأنماطُ مُركَّبةٌ لا كلماتٍ مفردة ──
 *   «شكون» وحدَها تقع في «شكون هاد المعلّم؟» — سؤالٌ عن حرفيٍّ لا عن التطبيق.
 *   فالشرطُ **ضميرُ المخاطَبِ معها**: «شكون **نتا**». وهذا هو الفرقُ بين
 *   قاعدةٍ تعمل وقاعدةٍ تبتلع (نمطٌ يُطارَد في هذا المستودع منذ «شق» في «شقة»).
 */
const SELF_YOU = ['نتا', 'نتي', 'انت', 'انتي', 'انتا'];
const SELF_WHO = ['شكون', 'شكونك', 'شكونكم', 'من'];
/** اسمُ التطبيق بكلّ ما يكتبه به الناس — والاسمُ وحدَه في سؤالٍ يكفي. */
const SELF_NAME = ['امانزين', 'أمانزين', 'امانزين', 'amanzine', 'اماanzine'];
/** «فيمَ تنفعني» — طلبُ القدرات، وهو سؤالٌ عن التطبيق لا عن السوق. */
const SELF_HELP = [
  'فاش غادي تعاوني', 'فاش تعاوني', 'فاش غادي تنفعني', 'فاش تنفعني',
  'شنو كتدير', 'شنو تقدر دير', 'شنو كتقدر دير', 'اش كتدير',
  'شنو تقدر تدير', 'واش تقدر تعاوني', 'كتخدم بشنو', 'شنو الخدمات ديالك',
  // من عقل المعرفة، كتبها إنسانٌ حقيقيّ: «واش ممكن تعاونّي؟». والشدّةُ تُزال
  //   في التطبيع، والناقصُ كان الصيغةَ نفسَها لا الحرف.
  'واش ممكن تعاوني', 'ممكن تعاوني', 'واش تقدر تعاونني', 'كيفاش تقدر تعاوني',
];

/**
 * **الإنسانُ واقف.**
 *
 *   «مافهمتش» ليست سؤالًا عن شيء — هي إعلانُ توقّف. ومن ردّ عليها بمعلومةٍ
 *   جديدةٍ زاد الطينَ بلّة. الجوابُ الصحيحُ أن يُعاد عرضُ **ما فُهم من كلامه
 *   السابق** ليُصحِّح موضعَ الخطأ بيده.
 *
 *   و«كيفاش» و«أشنو» عاريتَين — بلا موضوع — من نفس الباب: صدى حَيرة.
 */
const STUCK_PHRASES = [
  'مافهمتش', 'ما فهمتش', 'مفهمتش', 'ما فهمت', 'مافهمت',
  'ما فهمتكش', 'مافهمتكش', 'ما فهمتش والو', 'ضعت', 'تلفت',
];
/** كلماتُ حَيرةٍ **عاريةٌ فقط** — بموضوعٍ تصير سؤالًا مشروعًا. */
const STUCK_BARE = ['كيفاش', 'اشنو', 'أشنو', 'شنو', 'علاش', 'فين'];

/**
 * يقرأ أرضيّةَ الفهم من الجملة وما استُخرج منها.
 *
 * @param raw   كلامُ الإنسان كما كتبه — يُقرأ منه ما ليس في الحقول.
 * @param u     ما فهمته المعرفة.
 * @param intent النيّةُ التي أعادها `parseNeed`.
 */
export function readGround(raw: string, u: Understanding | null | undefined, intent?: string): Reading {
  const t = normLoose(raw || '');
  if (!t) return { ground: 'echo', why: 'جملةٌ فارغة' };

  // **والسؤالُ عن التطبيق يُكتَب بالحروف اللاتينيّة كذلك.** قِيس من عقل
  //   المعرفة: «chekoun neta» كتبها إنسانٌ حقيقيٌّ فسقطت في المصرف — وهي
  //   نفسُ «شكون نتا» التي تُقرأ صحيحةً بالعربيّة. ومَن كتب بحروفٍ لاتينيّةٍ
  //   ليس مستخدمًا من الدرجة الثانية.
  const lat = String(raw || '').toLowerCase();
  if (/\b(ch|sh|ck)ekoun\s+(nta|neta|nti)\b|\bchkoun\s+(nta|neta)\b/.test(lat)
    || /\bamanzine\b/.test(lat)) {
    return { ground: 'about_self', why: 'سؤالٌ عن التطبيق بالحروف اللاتينيّة' };
  }

  // ① **السؤالُ عن التطبيق يسبق كلَّ شيء** — لأنّ جوابَه معروفٌ تمامًا،
  //    وتركُه للمصرف يسجّله «مجهولًا» فيفسد العدّاد بسؤالٍ نعرفه.
  const hasYou = SELF_YOU.some(w => hitsWord(normLoose(w), t));
  const hasWho = SELF_WHO.some(w => hitsWord(normLoose(w), t));
  if (hasWho && hasYou) return { ground: 'about_self', why: 'شكون + ضميرُ المخاطَب' };
  if (SELF_NAME.some(w => hitsWord(normLoose(w), t))) {
    return { ground: 'about_self', why: 'اسمُ التطبيق في السؤال' };
  }
  if (SELF_HELP.some(p => t.includes(normLoose(p)))) {
    return { ground: 'about_self', why: 'طلبُ القدرات' };
  }

  // ② **ثمّ الحَيرةُ المُعلَنة.** وتسبق الدليلَ لأنّ «مافهمتش الثمن» توقّفٌ
  //    لا سؤالٌ عن ثمن.
  if (STUCK_PHRASES.some(p => t.includes(normLoose(p)))) {
    return { ground: 'stuck', why: 'قالها صراحةً: مافهمتش' };
  }
  // كلماتُ الحَيرة **عاريةً**: الجملةُ كلُّها منها ومن الفواصل، ولا شيءَ آخر.
  const words = t.split(/[\s،,.؛:!؟]+/).filter(Boolean);
  if (words.length > 0 && words.length <= 4
    && words.every(w => STUCK_BARE.some(s => normLoose(s) === w))) {
    return { ground: 'stuck', why: 'كلماتُ حَيرةٍ بلا موضوع' };
  }

  // ③ **وأخيرًا: هل للنيّة دليل؟**
  //
  //   `find_pro` هي وحدَها المصرف. وكلُّ نيّةٍ سواها تحتاج كلماتٍ صريحةً
  //   لتُقال (`buy` · `sell` · `book` · `create_store`…)، فوجودُها **هو**
  //   دليلُها. أمّا `find_pro` فتقع بالصدفة، ولا تُصدَّق إلّا بشاهد:
  //   مفهومٌ مقروءٌ، أو مهنةٌ، أو مشكلةٌ، أو فعلٌ واثق.
  //   **و`unknown` مصرفٌ كذلك** — بل هي المصرفُ الصريح. كُتب هذا الشرطُ
  //   أوّلًا `intent === 'find_pro'` وحدَها، فصار كلُّ ما تُرجعه `parseNeed`
  //   بـ`unknown` يُعَدّ «نيّةً صريحة». وقياسٌ على ١٠٦ عباراتٍ حقيقيّةٍ من
  //   عقل المعرفة أعلن ٨٣٪ فهمًا — والحقيقةُ أقلُّ بكثير: «أحتاج من يصلح»
  //   (٦٩ مرّة) و«توصيل» و«salam» كلُّها `unknown` وعُدّت مفهومة.
  //
  //   وهو نفسُ العطب الذي وُلدت هذه الطبقةُ لتكشفه — وقعتُ فيه داخلها.
  const sink = !intent || intent === 'find_pro' || intent === 'unknown';
  if (!sink) return { ground: 'grounded', why: `نيّةٌ صريحة: ${intent}` };

  const witness =
    (u?.service && 'مفهوم') ||
    (u?.services?.length && 'خدمات') ||
    (u?.profession && 'مهنة') ||
    (u?.problem && 'مشكلة') ||
    (u?.concepts?.length && 'مفاهيم') ||
    null;
  if (witness) return { ground: 'grounded', why: `شاهد: ${witness}` };

  // **والمدينةُ وحدَها ليست شاهدًا.** «أنا فالدار البيضاء» تُقرأ فيها مدينةٌ
  //   ولا حاجةَ فيها. ومَن عدّها دليلًا أعاد بناءَ المصرف بشكلٍ آخر.
  return { ground: 'echo', why: 'find_pro بلا شاهد — مصرف' };
}

/**
 * **هل يجب أن تُسجَّل هذه الجملةُ في قناة «ما لم نفهمه»؟**
 *
 *   `echo` وحدَها. و`about_self` و`stuck` **معروفتان** فتُسجَّلان في قناةٍ
 *   أخرى (طلبُ قدرة)، لا في المجهول — وإلّا امتلأ المجهولُ بأسئلةٍ نعرفها
 *   وضاع فيه ما لا نعرفه حقًّا.
 */
export function isUnread(g: Ground): boolean {
  return g === 'echo';
}

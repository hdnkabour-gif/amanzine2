// ── حكمُ «الرفض»: حُذف ثمّ عاد على أساسٍ صادق ──────────────────
//
//   حُذف أوّلًا بحقّ. بابُه كان `if (!canDo)`، و`canDo(verb, entity)` تسأل
//   «هل في الكتالوج قدرةٌ بهذا الفعل والكيان؟» — وهي تُستدعى على قدرةٍ
//   أُخِذت من الكتالوج نفسِه: جوابُها `true` بحكم البناء لا بحكم القياس.
//
//   والبديلُ المرشَّح («لا قدرةَ مطابِقة ⇒ ما نقدرش») قِيس فسقط: ٤٢ زوجًا
//   من ١٠٢ لا يغطّيها الكتالوج، وفيها `view:product` و`delete:customer` —
//   أبوابٌ تعمل ولها مساراتٌ وصفحات. فذاك يقيس **نقصَ كتالوجنا** ويقول
//   «ما نقدرش» عمّا نقدر عليه، وهو أسوأُ من الصمت.
//
//   وعاد الآن على `abilities.ENTITY_VERBS`: إعلانٌ عن **المجال** — أيّ
//   أفعالٍ يقبلها كلُّ كيانٍ أصلًا. «احذف اللغة» و«أنشئ هاتفًا» لا يفعلهما
//   أحدٌ في أيّ تطبيق، فقولُ «ما نقدرش» فيهما صدقٌ لا اعتذار. وثغرةُ
//   الكتالوج تبقى ثغرةً تُسدّ ولا يُحاسَب عليها الإنسان.
//
//   ولا يقع الرفضُ إلّا حين يكون الفعلُ **صريحًا** (فعلٌ + هدفٌ مقروءان من
//   `actions.ts`). فالنيّةُ الخشنةُ أو المجهولةُ تُسأل ولا تُرفَض: الجهلُ
//   عندنا ليس عجزًا عندنا.
export type Verdict =
  | 'execute'   // نفّذ الآن
  | 'confirm'   // اعرض ما فهمتَ واطلب «واخّا»
  | 'ask'       // ينقص شيء — سؤالٌ واحد
  | 'explain'   // ليس طلبًا أصلًا — اشرح ولا تفعل
  | 'refuse'    // لا يقبل هذا الكيانُ هذا الفعلَ أصلًا
  // **فُهم تمامًا، ولا بابَ له بعد.** غيرُ `refuse`: ذاك عبثٌ لا يُفعَل
  //   («أنشئ إعدادات»)، وهذا طلبٌ مشروعٌ لم نبنِه — والفرقُ بينهما هو الفرقُ
  //   بين «هادشي ما كايتديرش» و«مازال ما زدناهش». الأولى تُغلق، والثانية تَعِد.
  | 'soon';

export interface Decision {
  verdict: Verdict;
  /** حين يكون الحكمُ `soon`: ما فُهم وأيُّ مجالٍ بلا باب — ليُسجَّل الطلب. */
  boundary?: Boundary;
  /** ما يُقال للإنسان بالدارجة. */
  say: string;
  /** أثرُ القرار — أيُّ طبقةٍ حسمت ولماذا. يُعرَض عند الشكوى ويُصحَّح به. */
  trace: string[];
  /**
   * **أين يُساق** — حين يكون للقدرة بابٌ معلومٌ ولا يجوز غيرُه.
   *
   *   الوجهةُ كانت تُقرَّر في `parseNeed` وحدَها، من `intent` التي **تخلط
   *   محورَين**: `sell`/`buy`/`find_pro` اتّجاهُ سوق، و`create_store`/
   *   `manage` فعلٌ في التطبيق. فقِيس هذا حرفيًّا:
   *
   *     «بغيت نبدل رقم الهاتف ديالي» ⇒ intent=create_service ⇒ **publish**
   *     «بغيت نشوف الزبناء ديالي»    ⇒ intent=create_service ⇒ **publish**
   *     «بغيت نبدل الثمن ديال القميص» ⇒ intent=buy           ⇒ صفحةُ السوق
   *
   *   أي أنّ صاحبَ الحساب يُدير متجرَه فيُساق إلى السوق ليتصفّح أو ينشر.
   *   والكتالوجُ يعرف البابَ الصحيح (`profile` · `customers` · `products`)
   *   ولم يكن أحدٌ يسأله.
   *
   *   وحدُّها معلَن: تُملأ **للفعل الإداريّ وحدَه**. أمّا الباحثُ فوجهتُه
   *   صفحةُ السوق بالاستعلام، وهي أنفعُ من `home` المكتوبة في الكتالوج — لأنّ الحقلَ
   *   هناك يقول «أين تعيش القدرة» لا «أين يُساق الآن».
   */
  dest?: {
    page: Page;
    /**
     * **ما يُفتَح بالضبط** — لا الصفحةَ كاملةً.
     *
     *   طلبُ صاحب المشروع نصًّا: «نافذة منبثقة تفتح فقط الشيء الذي يطلبه
     *   المستخدم — مثلًا رقم الهاتف تفتح فقط خانة لكتابة رقم الهاتف، ليس
     *   صفحة الإعدادات بالكامل».
     *
     *   والعطبُ الذي يُغلقه مقيس: «بدّل اسم المحلّ» و«بدّل العنوان» و«بدّل
     *   اللغة» ثلاثةُ أفعالٍ لها **بابٌ واحد** (`settings`) فيه خمسون حقلًا.
     *   فمن طلب حقلًا واحدًا يُلقى في صفحةٍ ويُترَك يبحث — وهو أوّلُ ما
     *   يجعل الإنسانَ يظنّ أنّ التطبيق لم يفهمه، وقد فهمه تمامًا.
     *
     *   ومصدرُه **هدفُ الفعل المقروء** (`u.action.object`) لا شيءٌ جديد:
     *   الطبقةُ التي تقرأ «رقم الهاتف» من الجملة هي نفسُها التي تسمّي
     *   الحقلَ المطلوب. فلا قائمةَ ثانيةً تتباعد.
     *
     *   وغيابُه ليس عطبًا: نيّةٌ خشنةٌ («بغيت نبيع») تفتح الصفحةَ كاملةً
     *   لأنّها لم تسمِّ حقلًا — وذاك صوابٌ لا نقص.
     */
    focus?: ActionObject;
  };
}

/** أفعالٌ لا تُسترجَع — تُؤكَّد دائمًا مهما بلغت الثقة. */
const DESTRUCTIVE = new Set(['delete']);

/**
 * **حدُّ التصديق: دون هذا لا يُبنى على القراءة شيء.**
 *
 *   كان مكتوبًا داخلَ فرعٍ واحدٍ من الحكم فطُبِّق هناك وحدَه، ونُسي في
 *   الحقل (`focus`) — فمنعت القراءةُ الضعيفةُ من أن تُنتج سؤالًا وسُمح لها
 *   أن تُنتج حقلًا. وحدٌّ يُكتَب في موضعٍ يُنسى في الباقي: هذا سببُ رفعه
 *   إلى الملفّ.
 */
const READ_ENOUGH = 0.5;

/**
 * **القائمتان تُقرآن معًا، أو تكذب إحداهما.**
 *
 *   النقصُ مُعلَنٌ في مكانَين: قائمةٌ **مُصنَّفة** (`unmetNeeds` بمفاتيح
 *   `price`/`product`…) وقائمةٌ **نصٌّ حرّ** (`u.action.needs` = `['بشحال؟']`).
 *   والمصنَّفةُ تحترم `u.amount` عبر `price: said` — **والحرّةُ لا تعرفه**.
 *
 *   فقيس في المتصفّح: «بدّل الثمن ديال هاد المنتوج» ⇒ تظهر خانةُ «بشحال؟»،
 *   يكتب الإنسانُ **179**، فيصير `amount = 179` — والحَكَمُ ما زال يقول
 *   «ينقص من الفعل: بشحال؟» ⇒ `ask` ⇒ `clarify` ⇒ `fillSlot` يخرج صامتًا.
 *   **الثمنُ لا يتبدّل، ولا رسالةَ فشلٍ تُقال.** طلبنا معلومةً، أعطاها، فاختفت.
 *
 *   والطرحُ هنا نفسُ الطرح القائم فوقه سطرًا: كما تُطرَح حاجةُ «أيّ منتج؟»
 *   حين حلّتها الإشارةُ، تُطرَح حاجةُ «بشحال؟» حين حلّها رقمٌ مقروء.
 *   ولا تُبنى قائمةٌ ثالثة — القائمتان هما العطب، وثالثةٌ تزيده.
 */
function amountAnswers(need: string, u: Understanding): boolean {
  return u.amount != null && /شحال|ثمن|كمي|عدد|بكم/.test(need);
}

/**
 * الحكمُ الواحد.
 *
 * @param u ما فهمته الطبقات
 * @param impossible هل يرفض **المجالُ** هذا الفعلَ على هذا الكيان؟ تُحسَب
 *                   في `LivingHome` من `entityAccepts`، ولا تُشتقّ من غياب
 *                   القدرة — ذاك نقصُنا لا عجزُنا.
 * @param match القدرةُ المطابِقة إن عُرفت. وجودُها يُبدّل **العتبة**: العرضُ
 *              والبحثُ ينفّذان بثقةٍ أقلّ، والحذفُ لا ينفّذ مهما بلغت.
 *              وغيابُها لا يمنع شيئًا — يُحكَم بالعتبة العامّة ويُسأل.
 * @param ctx   ما يملكه المُنادي ولا تملكه اللغة: أيُّ منتوجٍ تشير إليه
 *              «هاد» و«آخر». اختياريٌّ عمدًا — بلا سياقٍ يبقى الحكمُ كما كان،
 *              فلا ينكسر مُنادٍ لم يُحدَّث بعد.
 */
export function decideExecution(
  u: Understanding,
  match?: Ability,
  impossible = false,
  ctx?: {
    lastProduct?: { id: string; name: string };
    /**
     * نصُّ الجملة كما كتبها صاحبُها. تحتاجه طبقةُ الحدّ الصادق وحدَها:
     * `Understanding` لا يحمل الأصل، وأنماطُ «مجالٍ بلا باب» تُقرأ من الكلام
     * لا من الحقول — عمدًا، كي لا تدخل فهرسَ المفاهيم فتبتلع كلمةً عامّة.
     */
    raw?: string;
  },
): Decision {
  const trace: string[] = [];
  // **الفعلُ الإداريُّ له بابٌ واحدٌ لا غير.** يُحسَب مرّةً ويُرفَق بكلّ حكم،
  // فلا يُساق صاحبُ الحساب إلى السوق مهما قالت النيّةُ المخلوطة.
  //
  //   ── **والنيّةُ بابٌ كالفعل** ─────────────────────────────────
  //   كان الشرطُ `u.action && match?.page`: لا وجهةَ إلّا بفعلٍ إداريٍّ صريح.
  //   وقياسٌ على جملِ الناس أظهر أثرَه: خمسُ جملٍ مفهومةٌ تمامًا وبلا باب —
  //
  //     «بغيت نبيع»            ⇒ SELL_PRODUCT     ووجهة `—`
  //     «عندي محل»             ⇒ OFFER_SERVICE    ووجهة `—`
  //     «بغيت ليه جلابة»       ⇒ BUY_PRODUCT      ⇒ **نفّذ** ووجهة `—`
  //     «عندي محل ديال لافاج»  ⇒ CREATE_WORKSPACE ⇒ **نفّذ** ووجهة `—`
  //
  //   واثنتان منها يُحكَم فيهما بـ`execute` — أي أنّ التطبيق قرّر أن يفعل
  //   ثمّ لم يجد أين. فهمٌ تامٌّ ينتهي إلى لا شيء.
  //
  //   والقدرةُ تحمل بابَها في الكتالوج سواءٌ جاءت من فعلٍ أو من نيّة. فمصدرُ
  //   المطابقة لا يُبدّل البابَ الذي تفتحه — والشرطُ كان يسأل عن المصدر لا
  //   عن الباب.
  //
  //   ── **وحدُّه: `home` ليست وجهة** ─────────────────────────────
  //   حارسٌ قائمٌ كان يمنع هذا كلَّه، وله في نصفه حقّ: قدراتُ البحث
  //   (`BUY_PRODUCT` · `FIND_PROVIDER`) صفحتُها `home`، وهي **حيث تعيش
  //   القدرة** لا «أين يُساق الآن». فمن يبحث يقف على `home` أصلًا، وسَوقُه
  //   إليها ينتزعه من نتائجه إلى صفحةٍ فارغة.
  //
  //   والفرقُ مكانيكيٌّ يُقرأ من الكتالوج: `page === 'home'` ⇒ لا نقلَ.
  //   وما عداها بابٌ حقيقيّ — `publish` لمن قال «بغيت نبيع»، و`settings`
  //   لمن قال «عندي محل». وهذا ما طلبه صاحبُ المشروع نصًّا: مَن فُهم أنّه
  //   يريد بيعَ منتوجٍ تُفتَح له **نافذةُ إضافة منتوج**، لا لا شيء.
  //   و`focus` يُرفَق حين يسمّي الإنسانُ حقلًا بعينه: هدفُ الفعل المقروء هو
  //   اسمُ الحقل، فلا قائمةَ ثانية. ويُسقَط مع صفحة `home` كما تُسقَط الوجهة.
  //
  //   ── **والحقلُ لا يُؤخَذ من قراءةٍ لا تكفي** (عطبٌ قِيس) ────────
  //
  //     «بغيت نبيع شي حاجة جديدة» ⇒ وجهة `publish` وحقل **`settings`**
  //
  //   و«جديد» في هذه الجملة صفةُ سلعةٍ لا أمرَ إنشاء، فتُقرأ فعلًا بلا هدفٍ
  //   ويسقط على `settings` بثقة **٠٫٣٥**. والصفحةُ صحيحةٌ (`SELL_PRODUCT`
  //   من النيّة) والحقلُ خاطئ — فتُفتَح خانةُ إعداداتٍ لمن يريد أن يبيع.
  //
  //   وشرطان يمنعانه، وكلاهما مكتوبٌ في هذا الملفّ أصلًا:
  //
  //   ① **الحدُّ نفسُه** (`READ_ENOUGH`): قراءةٌ دون ٠٫٥ لا تُنتج «ما نقدرش»
  //      ولا سؤالًا — ولا يصحّ أن تُنتج حقلًا. كان الحدُّ مطبَّقًا في موضعَين
  //      ومنسيًّا في الثالث.
  //   ② **اتّفاقُ المصدرَين**: البابُ من القدرة، فليكن الحقلُ من القراءة
  //      التي **أنتجت** تلك القدرة. `abilityFor` تجرّب الفعلَ ثمّ النيّة،
  //      فإن جاءت القدرةُ من النيّة كان هدفُ الفعل شيئًا آخرَ تمامًا —
  //      وحقلٌ من قراءةٍ وبابٌ من أخرى تركيبٌ لا أحدَ قاله.
  //
  //   ولا يمسّ هذا البابَ المقصود: «بدّل اسم المحلّ» هدفُها `shop_name`
  //   وكيانُها `workspace` وقدرتُها `UPDATE_WORKSPACE` — اتّفقا، فيبقى
  //   الحقلُ أخصَّ من الصفحة كما وُضع.
  const object = u.action?.object;
  const focusOk = !!object
    && (u.action?.confidence ?? 0) >= READ_ENOUGH
    && !!match && OBJECT_MAP[object] === match.entity;
  const dest = match?.page && match.page !== 'home'
    ? { page: match.page, ...(focusOk ? { focus: object } : {}) }
    : undefined;

  // ① صيغةُ الكلام تسبق كلَّ شيء: من يحكي عن غيره لا يُنفَّذ له فعلٌ ولو
  //    كانت جملتُه واضحة. **الوضوحُ ليس إذنًا.**
  if (u.mood && !u.mood.executable) {
    trace.push(`صيغة: ${u.mood.mood} (${u.mood.reason})`);
    return { verdict: 'explain', say: u.mood.say, trace, dest };
  }

  // ② النفي: أبطل الاتّجاه، فلا نُخمّن ما يريده.
  if (u.negated) {
    trace.push('نفيٌ صريح');
    return { verdict: 'ask', say: 'فهمتُ أنّك ما بغيتيش هادشي — قول ليا شنو بغيتي.', trace, dest };
  }

  // ③ عجزٌ حقيقيّ: المجالُ نفسُه لا يقبل هذا الفعلَ على هذا الكيان.
  //    يسبق الغموضَ والنقص: لا معنى لأن نستوضح تفاصيلَ فعلٍ لا يُفعَل.
  if (impossible) {
    trace.push('المجالُ لا يقبل هذا الفعلَ على هذا الكيان');
    return { verdict: 'refuse', say: 'هادشي ما كايتديرش أصلًا — قول ليا شنو بغيتي ندير ونعاونك.', trace };
  }

  // ④ غموضٌ معجميّ: كلمةٌ لمعنيَين بلا قرينة.
  if (u.ambiguity) {
    trace.push(`غموض: «${u.ambiguity.term}»`);
    return { verdict: 'ask', say: u.ambiguity.ask, trace, dest };
  }

  // ⑤ نقصٌ معلوم — **بعد طرح ما عرفناه**.
  //
  //    كانت `needs` تُقرأ كما هي، فيُسأل الخضّارُ «شنو نوع النشاط؟» بعد أن
  //    قال «عندي محل ديال الخضرة». وهو «موتُ السحر»: يعرف ثمّ يسأل.
  // **الإشارةُ تُحَلّ هنا — حيث يوجد الكتالوج، لا في المعجم.**
  //
  //   «مسح **هاد** المنتوج» و«بدّل ليا ثمن **آخر** منتوج» كلامٌ يعيّن
  //   المقصودَ بغير اسمِه، وكان يُقابَل بـ«أيّ منتوج؟» — سؤالٌ عمّا قيل
  //   للتوّ، وهو أسوأُ من السؤال عمّا لم يُقَل: يُشعر الإنسانَ أنّه لم يُسمَع.
  //
  //   وحدُّه صريح: **لا يُحَلّ إلّا إذا كان عند المُنادي جواب**. بلا سياقٍ
  //   يبقى السؤالُ قائمًا — والسؤالُ الصادقُ خيرٌ من تخمينِ منتوجٍ يُحذَف.
  const pointed = u.action?.ref && ctx?.lastProduct ? ctx.lastProduct : undefined;
  if (pointed) trace.push(`الإشارة «${u.action!.ref}» ⇒ «${pointed.name}»`);

  if (match) {
    //   **والثمنُ المذكورُ يُطرَح كما يُطرَح المفهوم.** «بغيت نبيع كسوة…
    //   بثمن مناسب ٥٠ درهم» ⇒ «بشحال؟» — والرقمُ مقروءٌ في `u.amount`.
    //   وطرحُ ما عُرف هو كلُّ فائدة هذه الخطوة؛ فحقلٌ يُقرأ ولا يُطرَح يجعلها
    //   استمارةً تسأل عمّا قيل لها.
    const said = u.amount != null ? String(u.amount) : undefined;
    const missing = unmetNeeds(match, {
      trade: u.service || u.profession?.id,
      product: u.service || pointed?.id, subject: u.service || u.problem?.id,
      price: said,
    });
    if (missing.length) {
      trace.push(`ينقص: ${missing[0]}`);
      // **وحين تُعرَف الغايةُ فسؤالُها أنفع.** «بنتي داخلة للمدرسة» ⇒
      // «شنو محتاج بالضبط؟» سؤالٌ صحيحٌ وبارد، وقد قال الإنسانُ حالَه للتوّ.
      // وسؤالُ الغاية يعترف بما قال ويعرض عليه ما يليق: «مبروك 👏 شنو
      // خاصّها دابا — حوايج، أدوات القراية، ولا نقل مدرسيّ؟».
      //   وحدُّه: الغايةُ تجيب عن **ما المطلوب** وحدَه. لا تعرف ثمنًا ولا
      //   نمرةً ولا طلبًا — فلا تُقحَم في سؤالٍ لا تملك جوابَه.
      // ── **والسؤالُ الذي لا جوابَ له يُستبدَل بصدق** ────────────────
      //   هنا بالضبط كانت تُولَد الحلقةُ التي لا تنتهي: «بغيت نمشي لطنجة»
      //   تُطابِق `FIND_PROVIDER` بنيّةٍ خشنة، فينقص «ما المطلوب» ⇒ «شنو
      //   محتاج بالضبط؟». وقد قال ما يحتاج بالضبط. وأيُّ جوابٍ يعطيه لا
      //   يجد بابًا، فيُسأل ثانيةً وثالثة.
      //
      //   والموضعُ مقصود: لا يُنطَق بالحدّ إلّا حيث كنّا سنسأل سؤالًا عاجزًا،
      //   فلا يمكنه أن يُسكت مسارًا يعمل. ولو وُضع أعلى لَسبق أبوابًا مفتوحة.
      const edge = ctx?.raw ? boundaryFor(ctx.raw, u, false) : null;
      if (edge) {
        trace.push(`حدٌّ صادق: ${edge.id} — فُهم ولا باب`);
        return { verdict: 'soon', say: edge.say, trace, boundary: edge };
      }
      const say = missing[0] === 'subject' && u.goal ? u.goal.ask : NEED_ASK[missing[0]];
      if (u.goal && missing[0] === 'subject') trace.push(`سؤالُ الغاية: ${u.goal.id}`);
      return { verdict: 'ask', say, trace, dest };
    }
    // **ونقصُ الفعل يُقرأ أيضًا — كان يُهمَل كلَّما طابقت قدرة.**
    //
    //   قائمتان للنقص: واحدةٌ في القدرة (`UPDATE_PRODUCT.needs = ['product']`)
    //   وواحدةٌ في الفعل المقروء (`price` ⇒ «بشحال؟»). وكانت الثانيةُ تُقرأ
    //   في `else` وحدَه — أي حين **لا** تُطابَق قدرة. فمتى طابقت سقطت.
    //   وظهر الأثرُ حين حُلَّت الإشارةُ: «بدّل ليا ثمن آخر منتوج» ⇒ **نفِّذ**
    //   تبديلَ ثمنٍ بلا ثمن. القائمتان تُقرآن معًا أو تكذب إحداهما.
    //
    //   ── **ولا تُقرأ من قراءةٍ ضعيفة** ──
    //   قِيس فسقطت جملةٌ صحيحة: «كنصايب الحلويات» يُقرأ فيها «صايب» فعلَ
    //   إنشاءٍ بلا هدف، فتسقط على `settings` بثقة **٠٫٣٥** وتُعلن «شنو بغيتي
    //   تزيد؟». والقدرةُ مطابِقةٌ تمامًا (يعرف حرفتَه: حلويات) — فيُسأل مَن
    //   قال حرفتَه سؤالًا وُلد من سوء قراءة. ونفسُ الحدّ (٠٫٥) الذي يمنع
    //   القراءةَ الضعيفة أن تُنتج «ما نقدرش» يمنعها أن تُنتج سؤالًا.
    const heard = (u.action?.confidence ?? 0) >= READ_ENOUGH ? (u.action?.needs || []) : [];
    const extra = heard.find(n => !/^تأكيد/.test(n) && !(pointed && /منتج|منتوج/.test(n)) && !amountAnswers(n, u));
    if (extra) {
      trace.push(`ينقص من الفعل: ${extra}`);
      return { verdict: 'ask', say: extra, trace, dest };
    }
  } else if (u.action?.needs?.length) {
    // ونقصُ الفعل يُطرَح منه ما حلّته الإشارةُ كذلك: «صايب تصويرة لهاد
    // المنتوج» تُعلن `أيّ منتج؟` وقد أشار إليه في الجملة نفسِها.
    const need = u.action.needs.find(n => !/^تأكيد/.test(n) && !(pointed && /منتج|منتوج/.test(n)) && !amountAnswers(n, u));
    if (need) {
      trace.push(`ينقص: ${need}`);
      return { verdict: 'ask', say: need, trace, dest };
    }
  }

  // ⑥ ما لا يُسترجَع يُؤكَّد — **بعد** اكتمال الفهم لا قبله، وإلّا سألنا
  //    التأكيدَ على فعلٍ لم نفهمه بعد.
  if ((u.action && DESTRUCTIVE.has(u.action.verb)) || match?.risk === 'high') {
    trace.push(match ? `فعلٌ خطِر: ${match.id}` : 'فعلٌ لا يُسترجَع');
    // **والتأكيدُ يسمّي ما سيُحذَف.** «واش متأكّد باغي تحيّد منتوج؟» تأكيدٌ
    // على المجهول: يوافق الإنسانُ وهو لا يعرف أيَّ واحدٍ سيذهب. وحين تُحَلّ
    // الإشارةُ يُذكَر الاسمُ — وهو **كلُّ ما يحتاجه ليقرّر**، فلا تُفتَح له
    // صفحةُ المنتجات ليبحث عمّا عيّنه بنفسه.
    const say = pointed && match
      ? `واش متأكّد باغي ${match.say.split(' (')[0]} «${pointed.name}»؟`
      : match ? `واش متأكّد باغي ${match.say}؟` : 'واش متأكّد؟ هادشي ما كيرجعش.';
    return { verdict: 'confirm', say, trace, dest };
  }

  // ⑦ الثقة — آخرَ ما يُنظَر فيه.
  //
  //    **والعتبةُ تتبع الخطورةَ لا العكس.** كانت واحدةً (٠٫٩٠) لكلّ شيء،
  //    وسقفُ الفهم الواقعيّ ٠٫٦٠ — فصار «نفّذ» بابًا لا يُفتَح: ٣٢ من ٣٦
  //    جملةً تُقابَل بسؤال. ومَن يسأل دائمًا يبدو استمارةً لا مساعدًا.
  //
  //    والخفضُ العامُّ ليس حلًّا: يُحذَف متجرٌ بثقةٍ ضعيفة. فالصواب أن يُنفَّذ
  //    العرضُ والبحثُ بما يليق بهما، ويبقى الحذفُ مغلقًا مهما بلغ اليقين.
  //    ── **والثقةُ تتبع ما قُرئ فعلًا** ──────────────────────────
  //
  //    كان يُقرأ `u.confidence` وحدَه — وهو ثقةُ **المفهوم**: «أيُّ شيءٍ في
  //    الدنيا يتكلّم عنه؟». وللفعل الإداريّ لا مفهومَ أصلًا، فالقياس:
  //
  //      «بغيت نشوف الكوموند ديالي فين وصلات»
  //         مفهوم ٠٫٢٠ · فعل `view/orders` ٠٫٨٥ · قدرة `VIEW_ORDERS`
  //         ⇒ «ما فهمتش مزيان — تقدر توضّح ليا بجملة أخرى؟»
  //
  //    قرأ الفعلَ قراءةً تامّةً، وطابق قدرةً في الكتالوج، وعرف البابَ الذي
  //    يفتحه — ثمّ اعتذر عن عدم الفهم. **«موتُ السحر» بعينه**: يعرف ثمّ يسأل.
  //
  //    ولا يُوسَّع البابُ بهذا: الشرطُ أن تكون **قدرةٌ مطابقةً** جاءت من فعلٍ
  //    مقروء. فلا ترتفع ثقةُ جملةٍ لم يُقرأ فيها فعلٌ ولا طابقت شيئًا. وعتبةُ
  //    الخطورة تبقى فوقَها كما هي — الحذفُ لا يُنفَّذ مهما بلغ اليقين.
  const actionConfidence = match && u.action ? (u.action.confidence ?? 0) : 0;
  const c = Math.max(u.confidence ?? 0, actionConfidence);
  const act = match ? RISK_THRESHOLD[match.risk] : CONFIDENCE.ACT;
  const why = match ? ` (${match.risk})` : '';
  if (c >= act) {
    trace.push(`يقين ${Math.round(c * 100)}٪ ≥ ${Math.round(act * 100)}٪${why}`);
    return { verdict: 'execute', say: '', trace, dest };
  }
  if (c >= CONFIDENCE.CONFIRM) {
    trace.push(`يقين ${Math.round(c * 100)}٪ — دون حدّ التنفيذ${why}`);
    return { verdict: 'confirm', say: 'فهمت. واش هادشي هو اللي بغيتي؟', trace, dest };
  }
  trace.push(`يقين ${Math.round(c * 100)}٪ — ضعيف`);
  return { verdict: 'ask', say: 'ما فهمتش مزيان — تقدر توضّح ليا بجملة أخرى؟', trace, dest };
}

/** سطرٌ واحدٌ يشرح القرار — يُعرَض حين يشتكي الإنسانُ من الفهم. */
export function explainDecision(d: Decision): string {
  return `${d.verdict} ← ${d.trace.join(' · ')}`;
}

// ============================================================
// المالُ كما يكتبه المغربيّ — **قارئٌ واحد**.
//
//   ── ما كشفه القياس ──
//   الميزانيّةُ كانت تُقرأ في موضعَين بتعبيرَين متقاربَين لا متطابقَين
//   (`needEngine.buildNeedObject` و`inference.baseInfer`)، وكلاهما:
//
//       ① يشترط الرقمَ **لاتينيًّا**: «بغيت سباط ب ٢٠٠ درهم» ⇒ لا ميزانيّة.
//          والأرقامُ الهنديّةُ لوحةُ مفاتيحَ عربيّةٌ شائعة، لا حالةٌ نادرة.
//       ② لا يفرّق بين **سقفٍ** وبين **ثمنٍ مطلوب**. والفرقُ ليس لغويًّا:
//          «بغيت سباط بأقلّ من ٢٠٠» سقفٌ يُصفّى به المعروض،
//          و«نبيع سباط ب ٥٠٠» ثمنٌ **يُعرَض**، وتصفيةُ بحثِه به ظلم.
//
//   ── ولماذا هذا الملفّ لا سطرٌ ثالث ──
//   الميزانيّةُ كانت تُستخرَج ولا تُستعمَل: `/api/search` يقبل `priceMax`،
//   و`applyFilters` يطبّقه — ولا شيءَ يوصله. النصفُ الأوّلُ قائمٌ والثاني لا.
//   فوصلُه يحتاج **رقمًا**، والموجودُ نصٌّ للعرض («٢٠٠ درهم»). ولو كتبتُ
//   المحوّلَ في `searchIntent` لصار القارئُ الثالث، وثلاثةٌ تنحرف.
// ============================================================

import { stripDiacritics, unifyLetters } from './normalize';

/** ٠١٢٣٤٥٦٧٨٩ ⇒ 0123456789. الأرقامُ الهنديّةُ كانت غيرَ مرئيّةٍ لكلّ قارئ. */
export function toAsciiDigits(s: string): string {
  return (s || '').replace(/[٠-٩]/g, d => String(d.charCodeAt(0) - 0x0660))
                  .replace(/[۰-۹]/g, d => String(d.charCodeAt(0) - 0x06f0));
}

/** ما يُكتب به الدرهمُ في المغرب. */
const CUR = '(?:درهم(?:ا|ات)?|دراهم|dhs?|mad|د\\s*\\.?\\s*م)';

/**
 * عباراتُ **السقف** — «لا أكثرَ من هذا».
 *
 *   «متفوتش» أشيعُها في الدارجة، وتُكتب بألفٍ وبدونها وبفراغ.
 *   ولا تُدرَج «ب» وحدَها هنا: «ب ٢٠١٥» موديلُ سيّارةٍ لا سقفُ ثمن —
 *   ولذلك تشترط صيغةُ «ب» عملةً صريحةً أدناه.
 */
const CEIL = [
  'ب?اقل\\s*من', 'قل\\s*من',
  'ما?\\s*ت?فوتش?(?:\\s*علي)?', 'ما?\\s*يفوتش?',
  'ما?\\s*كثرش?\\s*من', 'ما?\\s*كترش?\\s*من',
  'ف?ي?\\s*حدود', 'حتي\\s*ل?',
  'ماكس', 'max(?:imum)?', 'moins\\s*de', 'jusqu.?a',
].join('|');

/**
 * عرضٌ لا طلب: الرقمُ فيه **ثمنٌ يُطلَب** لا ميزانيّةٌ تُصفّى بها النتائج.
 *
 *   قُصرت على ما لا يحتمل وجهَين. و«نكري» متروكةٌ عمدًا: بالدارجة تصلح
 *   للطرفَين («نكري شقة» = أكتري · وأيضًا أُكري)، وحارسٌ يخطئ في نصف
 *   الحالات أسوأُ من غيابه.
 */
const OFFERS = /(للبيع|للكراء|ن?بيعو?|كنبيع|بغيت\s*نبيع|à\s*vendre|a\s*vendre)/;

/** حدودُ العقل: أقلُّ من درهمٍ أو أكثرُ من مئة مليونٍ ليس ميزانيّة. */
const sane = (n: number) => Number.isFinite(n) && n >= 1 && n <= 100_000_000;

/**
 * التهيئة: أرقامٌ لاتينيّة · بلا تشكيل · حروفٌ موحّدة · فراغٌ مطويّ.
 *
 *   والتشكيلُ ليس ترفًا: «بأقلّ من ٢٠٠ درهم» — بشدّةٍ على اللام — كانت
 *   تُقرأ **بلا سقف** في أوّل قياس. وهي الصيغةُ المكتوبةُ في التسليم نفسِه.
 *
 *   والتوحيدُ يُقرأ من `normalize` ولا يُكتَب هنا: كتبتُ أوّلًا توحيدَ همزةٍ
 *   محلّيًّا في هذا الملفّ، فأمسكه حارسُ «المصدرِ الواحد» — وهو محقّ.
 *   ولذلك تُكتَب عباراتُ السقف أدناه **بصيغتها بعد التوحيد**
 *   («اقل» لا «أقلّ» · «حتي» لا «حتّى»): من يقرأ نصًّا موحَّدًا يطابقه موحَّدًا.
 */
const prep = (raw: string) => squash(
  unifyLetters(stripDiacritics(toAsciiDigits(String(raw || '')))).toLowerCase(),
);

const squash = (s: string) => s.replace(/\s+/g, ' ').trim();

/** الرقمُ كما يُكتب: «10.000» · «10,000» · «10 000» ⇒ 10000. */
function num(s: string): number {
  return Number(String(s).replace(/[.,\s]/g, ''));
}

/**
 * أوّلُ مبلغٍ مذكورٍ بعملةٍ صريحة — «بغيت سباط ب ٢٠٠ درهم» ⇒ `200`.
 * تُعيد `undefined` إن لم تُذكر عملة: الرقمُ المجرّدُ قد يكون سنةً أو مقاسًا.
 */
export function readAmount(raw: string): number | undefined {
  const t = prep(raw);
  const m = t.match(new RegExp(`(\\d[\\d.,\\s]{0,11}\\d|\\d)\\s*${CUR}`));
  if (!m) return undefined;
  const n = num(m[1]);
  return sane(n) ? n : undefined;
}

/**
 * **سقفُ الثمن** — الرقمُ الذي لا يريد الإنسانُ تجاوزَه.
 *
 *   طريقان لا ثالث:
 *     ① عبارةُ سقفٍ صريحةٌ يليها رقم — والعملةُ اختياريّةٌ هنا،
 *        لأنّ «بأقلّ من ٢٠٠» لا تحتمل غيرَ المال.
 *     ② حرفُ الجرّ «ب» + رقم + **عملةٌ صريحة** — «ب ١٠٠ درهم».
 *        بلا العملةِ يصير «موديل ب ٢٠١٥» سقفًا، وهو موديل.
 *
 *   وتصمت أمام العرض: من يبيع لا يُصفّى له بحثٌ بثمنِ سلعته.
 */
export function priceCeiling(raw: string): number | undefined {
  const t = prep(raw);
  if (OFFERS.test(t)) return undefined;

  // ① عبارةُ سقفٍ صريحة — الرقمُ يجب أن **يليها**، فلا تلتقط «موديل 2015».
  const explicit = t.match(new RegExp(`(?:${CEIL})\\s*(?:ب\\s*)?(\\d[\\d.,\\s]{0,11}\\d|\\d)`));
  if (explicit) {
    const n = num(explicit[1]);
    if (sane(n)) return n;
  }

  // ② «ب ١٠٠ درهم» — العملةُ شرطٌ.
  const withCur = t.match(new RegExp(`(?:^|\\s)ب\\s*(\\d[\\d.,\\s]{0,11}\\d|\\d)\\s*${CUR}`));
  if (withCur) {
    const n = num(withCur[1]);
    if (sane(n)) return n;
  }
  return undefined;
}

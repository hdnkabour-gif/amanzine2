import { normLoose, hitsWord } from './normalize';
import { cityInText } from './akg/kb/geo';

// ============================================================
// **حالُ السلعة: جديدةٌ أم مستعملة؟**
//
//   قِيس على جملتَين من صاحب المشروع:
//     «بغيت نشري شي فران يكون **جديد** ومايفوتش ٨٠٠ درهم»
//     «عندي واحد الماكينة **قديمه** باغي نبيعها»
//   وكلاهما يذكر حالَ السلعة صراحةً — ولا شيءَ في التطبيق يقرؤه. وهو
//   **أوّلُ ما يسأل عنه المشتري** بعد الثمن، وأوّلُ ما يقوله البائع.
//
//   ── قارئٌ واحدٌ لا اثنان ──
//   يقرؤه المشتري (فيُضيَّق البحث) والبائعُ (فيُوسَم إعلانُه). ولو كُتب
//   في الموضعَين لتباعدا: يُضاف «شبه جديد» عند أحدهما دون الآخر، فيُنشَر
//   إعلانٌ بحالٍ لا يجده مَن يبحث عنه.
//
//   ── وحدُّه: لا يُخمَّن ──
//   بلا كلمةٍ صريحةٍ يبقى `undefined`. وسلعةٌ لم يُقَل حالُها ليست جديدةً
//   ولا مستعملة — والتخمينُ هنا يصنع وعدًا لا يُوفى في أوّل صفقة.
// ============================================================

export type Condition = 'new' | 'used';

const NEW_WORDS = ['جديد', 'جديده', 'جديدة', 'ججديد', 'نيف', 'neuf', 'neuve', 'new', 'zero'];
const USED_WORDS = [
  'قديم', 'قديمه', 'قديمة', 'مستعمل', 'مستعمله', 'مستعملة',
  'مستخدم', 'خدام', 'دوكازيون', 'اوكازيون', 'occasion', 'used',
];

/**
 * حالُ السلعة كما قالها صاحبُها — أو `undefined` إن لم يقلها.
 *
 *   والنفيُ يُقلَب هنا وحدَه لأنّه لا يُبطِل بل يعيّن: «**ماشي جديد**»
 *   تعني مستعملةً بلا لبس، بخلاف «ماشي بغيت نبيع» التي تُبطِل الاتّجاه
 *   ولا تقول ماذا يريد. وهما نفيان مختلفان: نفيُ **صفةٍ من اثنتَين**
 *   يحسم الثانية، ونفيُ **فعلٍ من كثير** لا يحسم شيئًا.
 */
export function readCondition(raw: string): Condition | undefined {
  const t = normLoose(raw || '');
  if (!t) return undefined;
  const hit = (ws: string[]) => ws.some(w => hitsWord(normLoose(w), t));
  const negNew = /ما\s*شي\s*جديد|ماشي\s*جديد|ماشيش\s*جديد/.test(t);
  if (negNew) return 'used';
  if (hit(USED_WORDS)) return 'used';

  // ── **و«الجديدة» مدينةٌ لا حالُ سلعة** ────────────────────────
  //
  //   `hitsWord` تسمح بسابقة «ال» بحقّ («الماكينة **الجديدة**»). لكنّ
  //   «**الجديدة**» اسمُ مدينةٍ مغربيّةٍ كذلك، فـ«أنا من الجديدة» كانت
  //   تُقرأ سلعةً **جديدة** — ويُضيَّق بحثُ مَن لم يطلب جديدًا أصلًا.
  //
  //   والسؤالُ يُوجَّه إلى **مصدر المدن نفسِه** لا إلى استثناءٍ مكتوبٍ هنا:
  //   قائمةٌ ثانيةٌ لأسماء المدن تتباعد عن الأولى بأوّل مدينةٍ تُضاف.
  //   ولا يقع الإقصاءُ إلّا حين تكون المدينةُ **هي الكلمةَ المطابِقة**:
  //   «عندي فران جديد ف الجديدة» تبقى `new` — فالمطابِقُ «جديد» لا اسمُ
  //   المدينة، والمدينةُ مذكورةٌ في موضعٍ آخر من الجملة.
  const newHit = NEW_WORDS.find(w => hitsWord(normLoose(w), t));
  if (!newHit) return undefined;
  //   والمقارنةُ بعد نزع «ال»: المدينةُ مكتوبةٌ «الجديدة» والكلمةُ المطابِقة
  //   «جديده» — طابقت داخلها بسابقة «ال» التي يسمح بها حدُّ الكلمة بحقّ.
  const bare = (w: string) => normLoose(w).replace(/^ال/, '');
  const city = cityInText(raw);
  if (city && bare(city) === bare(newHit)) return undefined;
  return 'new';
}

/** ما يُقال للإنسان — لا مُعرِّفٌ تقنيّ (القانون ١٠). */
export const CONDITION_LABEL: Record<Condition, string> = {
  new: 'جديد',
  used: 'مستعمل',
};

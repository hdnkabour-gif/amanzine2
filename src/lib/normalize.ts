// ============================================================
// التطبيع — **مصدرٌ واحد**. كان اثني عشر.
//
//   ── ما كشفه القياس ──
//   ظننتُها اثنتي عشرةَ نسخةً متطابقة. وهي ليست كذلك: **خمسةُ مستوياتٍ**
//   مختلفة، أضعفُها في `needEngine` و`humanIntent` — أي في الطريق الموصول
//   بالشاشة. اختبارٌ تفاضليٌّ على ٧٤ حالة (نفسُ الجملة بصيغٍ لا يفرّق بينها
//   إنسان) أعطى **١١ اختلافًا**:
//
//       عندييي محل ديال الخضرة   ⇒ create_store  صارت create_service
//       عندي مشڭل ف الضو          ⇒ find_pro      صارت create_service
//       شحااال الثمن              ⇒ find_pro      صارت unknown
//
//   والثانيةُ أخطرُها: صاحبُ عطلٍ كهربائيٍّ يُقرأ **عارضَ خدمة**. وسببُها
//   حرفٌ واحد: «ڭ» بدل «ك» — وهي لوحةُ مفاتيحَ مغربيّةٌ شائعة. وتكرارُ
//   الحروف («عندييي» · «شحااال») طريقةُ كتابةٍ يوميّة، لا خطأً نادرًا.
//
//   و`understand()` لم يتغيّر في أيٍّ من الـ٧٤ — لأنّه وحدَه يستعمل المطبِّعَ
//   الكامل. فالعطبُ ليس في اللغة بل في **أيِّ نسخةٍ صادفتها الجملة**.
//
//   ── لماذا طبقاتٌ لا دالّةٌ واحدة ──
//   الفرقُ الوحيدُ المشروعُ بين المواضع هو **حذفُ غير العربيّ**: فهرسُ
//   المفاهيم يريد عربيّةً صافية، و`needEngine` يتعامل مع الفرنسيّة وأسماء
//   المدن فيموت لو حُذف غيرُ العربيّ. فالطبقاتُ تحفظ هذا الفرق وتُلغي ما
//   عداه — بدل أن يكون كلُّ ملفٍّ حرًّا في اختراع تطبيعه.
// ============================================================

/** تشكيلٌ وتطويل. `ٰ` و`ـ` كانتا تفوتان النسخَ الضعيفة. */
const AR_DIAC = /[ً-ْٰـ]/g;

export function stripDiacritics(s: string): string {
  return (s || '').replace(AR_DIAC, '');
}

/**
 * توحيدُ الحروف: صيغُ الهمزة · ة→ه · ى→ي · ؤ→و · ئ→ي · والحروفُ الفارسيّة
 * التي تكتب بها لوحاتُ المفاتيح المغربيّة (گ ڭ ⇒ ك · ڤ ⇒ ف · پ ⇒ ب).
 */
export function unifyLetters(s: string): string {
  return (s || '')
    .replace(/[أإآٱ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و').replace(/ئ/g, 'ي')
    .replace(/[گﮒ]/g, 'ك').replace(/ڭ/g, 'ك').replace(/ڤ/g, 'ف').replace(/پ/g, 'ب');
}

/** «حلااااق» ⇒ «حلاق». ثلاثةٌ فأكثر — فلا تُمَسّ «مدّ» العربيّة الشرعيّة. */
export function collapseRepeats(s: string): string {
  return (s || '').replace(/(.)\1{2,}/g, '$1');
}

const squash = (s: string) => s.replace(/\s+/g, ' ').trim();

/**
 * **علاماتُ الترقيم فاصلٌ لا حرف.**
 *
 *   قِيس: من ١٥١٦ مصطلحًا في الفهرس **١١٠٥** لا تُطابَق في «عندي مشكل،سباك»
 *   وتُطابَق كلُّها في «الطوموبيل خربانة.ميكانيك». والفرقُ ليس في المطابِق:
 *
 *     `normArabic` تُفرّغ كلَّ ما هو **خارج** نطاق العربيّة إلى مسافة. و«،»
 *     و«؟» و«؛» **داخل** نطاق العربيّة في يونيكود (U+060C · U+061F · U+061B)
 *     — فتنجو وتلتصق بالكلمة كأنّها حرفٌ منها. والنقطةُ لاتينيّةٌ فتُفرَّغ.
 *
 *   والمغاربةُ يكتبون «بغيت سباك،كهربائي» بلا مسافة. فكلمةٌ بعد فاصلةٍ
 *   عربيّةٍ كانت لا تُقرأ أبدًا، وبعد نقطةٍ لاتينيّةٍ تُقرأ — سلوكان لرمزَين
 *   يفعلان الشيءَ نفسَه.
 *
 *   وموضعُ الإصلاح **هنا** لا في `hitsArabic`: المطابِقُ واحدٌ من خمسةِ
 *   مستهلكين (الفهرس · الـArabizi · المطابقةُ بالكلمات · المدن · `normLoose`
 *   الذي يقرؤه `needEngine` والاتّجاهُ والحقائق). إصلاحُه وحدَه يُبقي الأربعةَ
 *   الأخرى تقرأ «مشكل،سباك» كلمةً واحدة.
 */
const AR_PUNCT = /[،؍؛؞؟٪٫٬٭۔]/g;
const spacePunct = (s: string) => (s || '').replace(AR_PUNCT, ' ');

/**
 * **التطبيعُ الكامل مع حذف غير العربيّ.** لفهرس المفاهيم: يريد عربيّةً
 * صافيةً فلا تُصادَف مصطلحاتٌ داخل رموزٍ أو لاتينيّة.
 */
export function normArabic(input: string): string {
  let s = collapseRepeats(unifyLetters(stripDiacritics((input || '').toLowerCase())));
  s = spacePunct(s).replace(/[^؀-ۿ0-9\s]/g, ' ');
  return squash(s);
}

/**
 * **التطبيعُ الكامل مع إبقاء غير العربيّ.** لمن يقرأ نصًّا مختلطًا:
 * `needEngine` و`humanIntent` يتعاملان مع الفرنسيّة وأسماء المدن، فحذفُ
 * اللاتينيّة يعميهما. وهذا هو الفرقُ **الوحيدُ المشروع** بين المطبِّعَين.
 */
export function normLoose(input: string): string {
  return squash(spacePunct(collapseRepeats(unifyLetters(stripDiacritics((input || '').toLowerCase())))));
}

/** اللاتينيّة: حروفٌ صغيرة · إزالةُ النبرات (é⇒e) · طيُّ التكرار · رموز. */
export function normLatin(input: string): string {
  let s = (input || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
  s = collapseRepeats(s).replace(/[^a-z0-9\s]/g, ' ');
  return squash(s);
}

// الوعاءُ والمحتوى — «حانوت ديال الحوت» ليس بقّالة.
//
//   قياسٌ على ٤٦ جملةً من شكل «عندي حانوت ديال ⟨بضاعة⟩» أرجع `grocer` في
//   ٤٣ منها. بائعُ السمك، وبائعُ الذهب، وصاحبُ المكتبة — كلُّهم بقّالون.
//   والسببُ سطرٌ واحد: «حانوت» و«دكان» متغيّران لـ`grocer` في البيانات،
//   والفهرسُ يفوز فيه الأطول، و«حانوت» أطولُ من أغلب أسماء البضائع.
//
//   وهذا **أسوأُ من الصمت**. الصامتُ يُسأل فيُصحَّح؛ وهذا يسجّل الرجلَ في
//   بابٍ لا يبيع فيه، فلا يجده مَن يطلب سمكًا، ويجده مَن يطلب سكّرًا.
//   وهو لا يعلم — لأنّ التطبيق لم يسأله شيئًا.
//
//   ── نصفان لعطبٍ واحد ──
//   ① **الوعاءُ يُؤجَّل ولا يُلغى.** في «⟨وعاء⟩ ديال X» يحسم X لا الوعاء.
//      ولا يُرمى الوعاءُ: من قال «عندي حانوت» بلا إضافةٍ فهو بقّال حقًّا،
//      ومن قال «حانوت ديال المواد الغذائيّة» يبقى بقّالًا لأنّ شيئًا آخر
//      لم يُطابِق. فالتأجيلُ يُصلح الخطأ بلا أن يُحدِث صمتًا جديدًا.
//
//   ② **البضاعةُ تدلّ على الحرفة.** المغربيُّ يقول ما **يبيع** لا ما
//      **يُسمّى**: «عندي محل ديال الخضرة» — ولا يقول «أنا خضّار» أبدًا.
//      وقاعدةُ المعرفة تعرف الحرفَ وحدَها، فتصمت أمام كلام أصحابها.
//
//   ── حدُّ هذا الملفّ ──
//   لا يدخله إلّا اسمُ بضاعةٍ **تدلّ على حرفةٍ واحدة**. «الطاجين» بضاعةُ
//   فخّارٍ وطبقُ مطعمٍ معًا — فلا تدخل. والقاعدةُ نفسُها التي أسقطت «بيع»
//   و«واش كاين» من المتغيّرات: الكلمةُ العامّةُ مصرفٌ يبتلع بابًا كاملًا.
//
//   وما يعرفه الفهرسُ أصلًا لا يُكرَّر هنا («الخبز» ⇒ مخبزة تعمل اليوم).
//   التكرارُ يخلق مصدرَي حقيقةٍ يفترقان بصمت.
// ============================================================

/**
 * أوعيةُ التجارة: كلماتٌ تصف **مكانَ** البيع لا **نوعَه**. تصلح وحدَها
 * («عندي حانوت») ولا تصلح حاكمًا حين يُذكَر المحتوى.
 */
export const CONTAINER_WORDS = new Set([
  'حانوت', 'دكان', 'دكانه', 'محل', 'متجر', 'مغازه', 'بوتيك', 'كشك', 'مغازة',
]);

/** أدواتُ الإضافة الدارجة: «ديال» · «د» · «تاع». */
const OF = '(?:ديال|دال|د|تاع|متاع)';

/**
 * هل هذا المصطلحُ وعاءٌ **ذُكِر محتواه**؟
 *
 *   شرطان: أن يكون المصطلحُ وعاءً بتمامه، وأن يتبعه في النصّ محتوًى.
 *
 *   والثاني وحدَه يكفي عمليًّا اليوم: «حانوت ديال الحوايج» متغيّرٌ كاملٌ
 *   للملابس في البيانات، ولا يتبعه «ديال X» ثانيةً فلا يُردّ. سبرتُ إسقاطَ
 *   الشرط الأوّل فلم يتغيّر شيءٌ في القياس ولا سقط اختبار. أُبقيَ لأنّه يقول
 *   المعنى صراحةً («هذه كلمةُ مكان») ويسبق بناءَ التعبير — لا لأنّه يحرس
 *   حالةً قائمة. وكتابةُ ذلك أصدقُ من ترك سطرٍ يبدو حارسًا وليس به.
 */
export function isContainerWithContents(term: string, ...texts: string[]): boolean {
  if (!CONTAINER_WORDS.has(term)) return false;
  const re = new RegExp(`${term}\\s+${OF}\\s+\\S`);
  return texts.some(t => t && re.test(t));
}


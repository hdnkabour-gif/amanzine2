// الأطولُ أوّلًا — نفسُ قاعدة الفهرس: «الخضره والفواكه» تسبق «الخضره».
const FLAT = MERCHANDISE
  .flatMap(r => r.terms.map(term => ({ term, id: r.id })))
  .sort((a, b) => b.term.length - a.term.length);

/**
 * تُطابِق **كلمةً كاملة** دائمًا، ولو طال المصطلح.
 *
 *   أسماءُ الحرف نادرةُ الوقوع داخل كلامٍ آخر؛ وأسماءُ البضائع أسماءُ جنسٍ
 *   شائعة، فمطابقتُها بالاحتواء تُصيب مصادفةً. حدُّ الكلمة يمنع ذلك، مع
 *   السماح بـ«ال» و«ل» و«ب» و«ف» — سوابقُ العربيّة تلتصق.
 */
function hitsWord(term: string, text: string): boolean {
  const esc = term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(^|\\s)(ال|ل|ب|ف|و)?${esc}(\\s|$)`).test(text);
}

/**
 * @param texts نصوصٌ **مطبَّعةٌ سلفًا** بمطبِّع `knowledge.ts` — مطبِّعٌ واحدٌ
 *              للمشروع كلِّه، وإلّا اختلف عقلان على نفس الجملة.
 */
export function resolveMerchandise(...texts: string[]): { id: string; term: string } | null {
  for (const { term, id } of FLAT) {
    if (texts.some(t => t && hitsWord(term, t))) return { id, term };
  }
  return null;
}

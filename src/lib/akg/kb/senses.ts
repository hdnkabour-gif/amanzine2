/** أدنى طولٍ لمُكمِّل — ما دونه يقع داخل كلماتٍ أخرى بلا معنى. */
export const MIN_CUE = 3;

export interface Sense {
  /** هويّةٌ ثابتة — هي ما يُسجَّل ويُقاس، لا نصُّ الزرّ. */
  id: string;
  /** نصُّ الخيار كما يراه الإنسان. */
  label: string;
  /** المفهومُ الذي تعنيه هذه الحاسّة، أو `null` = مجالٌ لا يملكه التطبيقُ بعد. */
  concept: string | null;
  /** ما يُكمل المعنى في الجملة. فارغةٌ = حاسّةٌ لا تُحسَم إلّا بسؤال. */
  cues: string[];
}

export interface SharedWord {
  /** اللفظُ المشترك كما يُكتَب (يُطبَّع عند المطابقة). */
  term: string;
  /** صيغٌ أخرى لنفس اللفظ المشترك. */
  also?: string[];
  /** السؤالُ الخاصُّ بهذا اللفظ — لا سؤالٌ عامّ. */
  question: string;
  senses: Sense[];
}


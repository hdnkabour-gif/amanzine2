export interface SenseReading {
  word: SharedWord;
  /** الحاسّةُ المحسومةُ بمُكمِّل، أو `null` ⇒ يجب أن يُسأل. */
  decided: Sense | null;
  /** المُكمِّلُ الذي حسم — للأثر والشرح. */
  cue?: string;
  /** اللفظُ المشترك الذي أصاب (قد يكون من `also`). */
  hit: string;
}

const lower = (s: string) => normLoose(s);

/** كلُّ صيغِ اللفظ المشترك، مطبَّعةً، الأطولُ أوّلًا (الأخصُّ يسبق). */
function formsOf(w: SharedWord): string[] {
  return [w.term, ...(w.also || [])]
    .map(lower).filter(Boolean)
    .sort((a, b) => b.length - a.length);
}

/**
 * **هل في النصِّ لفظٌ مشترك؟ وهل أكملته الجملة؟**
 *
 *   يُعيد `null` إن لم يكن فيه لفظٌ مشترك إطلاقًا — وهو الغالب، فلا كلفةَ
 *   على الجمل العاديّة.
 *
 *   والمُكمِّلُ **الأطولُ يفوز**: «سكانير ديال الطوموبيل فالمستشفى» جملةٌ
 *   متضاربةٌ نادرة، ولا يصحّ أن يحكمها ترتيبُ الصفوف. والأطولُ أخصّ.
 */
export function readSense(text: string): SenseReading | null {
  const t = lower(text);
  if (!t) return null;

  for (const w of SHARED_WORDS) {
    let hit: string | null = null;
    for (const f of formsOf(w)) { if (matchWord(f, t)) { hit = f; break; } }
    if (!hit) continue;

    let best: { sense: Sense; cue: string } | null = null;
    for (const s of w.senses) {
      for (const raw of s.cues) {
        const cue = lower(raw);
        if (cue.length < MIN_CUE) continue;      // حارسٌ مزدوج: الجدولُ يُفحَص أيضًا
        if (!matchWord(cue, t)) continue;
        if (!best || cue.length > lower(best.cue).length) best = { sense: s, cue: raw };
      }
    }
    return best
      ? { word: w, decided: best.sense, cue: best.cue, hit }
      : { word: w, decided: null, hit };
  }
  return null;
}

/** المفهومُ الذي حسمته الجملة، أو `null` (لم تُحسَم، أو حاسّةٌ بلا مفهوم). */
export function senseConcept(text: string): { id: string; sense: Sense; cue: string } | null {
  const r = readSense(text);
  if (!r?.decided?.concept || !r.cue) return null;
  return { id: r.decided.concept, sense: r.decided, cue: r.cue };
}

/**
 * **حاسّةٌ فُهِمت ولا مفهومَ لها.**
 *
 *   أمسكه حارسٌ كتبتُه لحظةَ العمل: «سكانير ديال التحاليل» كانت تُقرأ
 *   طبّيّةً **صحيحةً** ثمّ يُجيب الفهرسُ `car_diagnostics` — لأنّ الفهمَ
 *   وقع ولم يتصرّف به أحد. فهمٌ لا يُغيّر الجوابَ هو فهمٌ ميّت، وهو أسوأُ
 *   من ألّا يُفهَم: يُوهم أنّ المعرفةَ أُضيفت.
 *
 *   فمن أصابته حاسّةٌ بلا مفهوم **لا يُجاب بمفهومٍ آخر**: يُقال الصدقُ
 *   ويُسجَّل للتعلّم.
 */
export function senseGap(text: string): { word: SharedWord; sense: Sense; cue: string } | null {
  const r = readSense(text);
  if (!r?.decided || r.decided.concept !== null || !r.cue) return null;
  if (r.decided.id === 'other') return null;      // المخرجُ ليس حاسّةً مفهومة
  return { word: r.word, sense: r.decided, cue: r.cue };
}


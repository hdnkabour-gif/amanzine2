// **مفاتيحُ المعنى — اللفظُ المشترك لا يُحسَم إلّا بتمامِ الجملة.**
//
//   الدارجةُ تحمل ألفاظًا تعني أشياءَ عدّة، ويتحدّد معناها حين تكتمل الجملة:
//     «سكانير»      — ديال الوراق؟ ديال التحاليل؟ ديال الطوموبيل؟
//     «كنبدل الثوب» — ثوبُ سيّارةٍ أم ثوبُ صالون؟
//     «حمام»        — بلديٌّ أم رومي؟
//
//   ── ما كان يقع، مقيسًا لا متخيَّلًا ──
//
//     «سكانير ديال الوراق»        ⇒ `car_diagnostics` بيقين ٠٨٦ وبلا سؤال
//     «سكانير ديال التحاليل»      ⇒ `car_diagnostics` بيقين ٠٨٦ وبلا سؤال
//     «بغيت ندير سكانير فالمستشفى» ⇒ `car_diagnostics` بيقين ٠٨٦ وبلا سؤال
//     «كنبدل الثوب»               ⇒ `car_upholstery` بيقين **٠٩٠** — وهي فوق
//                                    عتبةِ التنفيذ، فيُنفَّذ بلا سؤالٍ ولا تأكيد
//
//   أي أنّ تمامَ الجملة **موجودٌ في النصِّ ويُهمَل تمامًا**: الخمسُ جملٍ
//   الأولى تُعطي الجوابَ نفسَه. والأقبح: «بغيت نبدل الثوب ديال الطوموبيل»
//   كانت تُجيب `car` — فالجملةُ **الأدقُّ** تُجيب أسوأ، لأنّ الفهرسَ يختار
//   أطولَ لفظٍ يعرفه («طوموبيل») لا أدقَّ معنًى.
//
//   ── القوانينُ الثلاثة ──
//
//   ① **مُكمِّلٌ أصاب ⇒ المعنى حُسِم، واليقينُ يرتفع.** الجملةُ اكتملت،
//      فلا سؤال. وهذا هو الكسبُ الأكبر: جوابٌ صحيحٌ حيث كان خاطئًا.
//
//   ② **لا مُكمِّل ⇒ لا جواب.** يُطرَح سؤالٌ **خاصٌّ باللفظ** («سكانير ديال
//      شنو؟») لا سؤالًا عامًّا. واليقينُ ينزل تلقائيًّا إلى ٠٥٠ لأنّ
//      `confidenceOf` تقرأ وجودَ سؤال — فتعمل سكّةُ `clarify` القائمةُ بلا
//      طبقةٍ جديدة. وهذا **قلبٌ** للسلوك: اللفظُ المشترك كان يرفع اليقينَ،
//      وصار يُنزله — لأنّه مشترك.
//
//   ③ **حاسّةٌ بلا مفهوم تذهب للتعلّم لا للتخمين.** `medical_imaging` لا
//      وجودَ له في المعرفة. فحاسّةُ «سكانير ديال التحاليل» مفهومُها `null`:
//      يُفهَم المعنى ويُقال «ما عندناش هاد المجال بعد» — ولا يُرسَل صاحبُه
//      إلى ميكانيكيّ. وهذه قاعدةُ صاحب المشروع نفسُها: ما لم يُتحقَّق منه
//      لا يدخل التطبيقَ، لكنّ **الفهمَ يُلتقَط**.
//
//   ── ولا نسخةَ سادسةً لحدِّ الكلمة ──
//   المطابقةُ بـ`matchWord` و`normLoose` من `normalize` — وهي النسخةُ
//   الموحَّدةُ التي تعرف تراكبَ السوابق («فالحمام» · «وال…» · «لل…»).
//   والاحتواءُ المجرّد ممنوعٌ هنا قطعًا: `COMPOSITE` في `knowledge.ts`
//   تُطابق بـ`blob.includes` من حرفين، ولو مرَّت مُكمِّلاتُنا عليها لصار
//   «دم» يُصيب داخل «قدم» و«خدمة» و«مدمج».
// ============================================================


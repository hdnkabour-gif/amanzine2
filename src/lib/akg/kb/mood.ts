// ============================================================
// صيغةُ الكلام — هل هذه الجملةُ **التزامٌ يُنفَّذ**، أم شيءٌ آخر؟
//
//   قياسٌ كشف أنّ سبعَ صيغٍ مختلفةٍ تُقرأ كلُّها «يريد أن يبيع»:
//
//       بغيت نبيع قميص              ← التزام   ✅
//       قال ليا الزبون بغيت نرجع     ← نقلٌ عن غيره
//       يمكن نبيع القميص            ← تردّد
//       إلى كان الثمن مناسب غادي نبيع ← شرط
//       كيفاش نبيع قميص             ← يتعلّم
//       واش نقدر نبيع قميص          ← يستفسر عن إمكان
//       بعت قميص البارح             ← انتهى
//
//   والفرقُ ليس لغويًّا بل **عمليّ**: مَن يروي كلامَ زبونٍ لا يريد أن نبدأ
//   إرجاعًا، ومَن يسأل «كيفاش نبيع» يريد شرحًا لا نموذجَ نشر. التنفيذُ على
//   هذه الصيغ فعلٌ **لم يطلبه أحد** — وهو أسوأُ صنفٍ من الخطأ، لأنّ الإنسان
//   يجد أثرَه ولم يفعله.
//
//   ── حدُّ هذا الملفّ ──
//   بُني منه ما يمنع **فعلًا خاطئًا** فقط. أمّا المقارنة («نبيع ولا نكري؟»)
//   وترتيبُ الأوامر وتعدّدُ النيّات فلغةٌ صحيحةٌ لا فعلَ لها عندنا اليوم —
//   وفهمُ ما لا نملك له فعلًا وعدٌ لا يُوفى.
//
//   القاعدة: **الفهمُ يُقاس بما يستطيع التطبيقُ فعلَه، لا بما تحمله اللغة.**
// ============================================================

import { deArabizi } from './arabizi';
import { normLoose } from '../../normalize';

export type Mood =
  | 'commit'       // يُنفَّذ
  | 'reported'     // ينقل كلامَ غيره
  | 'conditional'  // مشروط
  | 'howto'        // يسأل كيف
  | 'capability'   // يسأل هل يمكن
  | 'tentative'    // متردّد
  | 'past';        // وقع وانتهى

export interface MoodRead {
  mood: Mood;
  /** هل يجوز التنفيذُ بلا سؤال؟ */
  executable: boolean;
  /** ما يُقال للإنسان حين لا يُنفَّذ — لا صمتَ ولا فعلَ مفاجئ. */
  say: string;
  reason: string;
}

const norm = normLoose;   // كان نسخةً محلّيّةً أضعف

// الترتيبُ من الأشمل إلى الأضيق — **جزءٌ من المعنى**: «قال ليا الزبون يمكن
// نبيع» نقلٌ قبل أن تكون ترّددًا، لأنّ النقلَ يُحيط بالجملة كلِّها.
const RULES: { mood: Mood; terms: string[]; say: string }[] = [
  {
    mood: 'reported',
    // ضميرُ الغائب هو المفتاح: «الزبون بغا» · «قال ليا» · «كيقول».
    terms: ['قال ليا', 'قالت ليا', 'قال لي', 'كيقول', 'كتقول', 'قاليا',
      'الزبون بغا', 'الزبون بغى', 'الزبونه بغات', 'واحد بغا', 'شي واحد قال',
      'صاحبي بغا', 'خويا بغا'],
    say: 'فهمتُ أنّك كتحكي على شي حد — ما غاديش ندير شي حاجة. قول ليا إلى بغيتي تدير شي حاجة نتا.',
  },
  {
    mood: 'conditional',
    terms: ['الى كان', 'إلى كان', 'ايلا كان', 'اذا كان', 'إذا كان', 'لوكان', 'لو كان', 'حتى يكون'],
    say: 'هادي حالة مشروطة — نتسنّى حتّى تتأكّد، ومن بعد نديروها.',
  },
  {
    mood: 'howto',
    terms: ['كيفاش', 'كيف نقدر', 'شنو خاصني ندير', 'شنو كندير باش', 'comment'],
    say: 'نشرح ليك كيفاش — وإلى بغيتي نديروها معًا قول ليا.',
  },
  {
    mood: 'capability',
    terms: ['واش نقدر', 'واش ممكن', 'واش كاين شي طريقه', 'واش يمكن ليا'],
    say: 'نجاوبك واش ممكن — وما ندير والو حتّى تقول ليا.',
  },
  {
    mood: 'tentative',
    terms: ['يمكن ن', 'يمكن ما', 'واخا نشوف', 'غانشوف', 'مازال كنفكر', 'ربما', 'possible'],
    say: 'باقي ما قرّرتيش — ما غاديش نبدا. قول ليا منين تكون واجد.',
  },
  {
    mood: 'past',
    // ماضٍ منتهٍ: «بعت» · «شريت» · «صيفطت». يُخبِر لا يطلب.
    terms: ['بعت', 'شريت', 'صيفطت', 'خلصت', 'دوزت', 'وصلات ليا', 'تسلمت'],
    say: 'فهمتُ أنّها وقعات من قبل — قول ليا إلى بغيتي تسجّلها.',
  },
];

/**
 * يقرأ صيغةَ الكلام. `commit` هي الافتراضيّ — أغلبُ الجمل التزامٌ حقيقيّ،
 * ولا يصحّ أن نعطّل التطبيقَ خوفًا من حالاتٍ نادرة.
 */
export function readMood(raw: string): MoodRead {
  const t = norm(deArabizi(raw || ''));
  if (!t) return { mood: 'commit', executable: true, say: '', reason: 'فارغ' };

  for (const r of RULES) {
    const hit = r.terms.find(w => t.includes(norm(w)));
    if (hit) {
      return { mood: r.mood, executable: false, say: r.say, reason: `«${hit}»` };
    }
  }
  return { mood: 'commit', executable: true, say: '', reason: 'صيغةُ التزام' };
}

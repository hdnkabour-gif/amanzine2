// يُرجع الغموضَ **فقط** إن ذُكر المصطلحُ ولم تُوجد قرينةٌ لأيّ خيار.
// وإن أصابت قرينتان معًا فالنصُّ ليس غامضًا بل مركَّب — نتركه للفهم العاديّ.
export function detectAmbiguity(text: string): Ambiguity | null {
  const t = norm(text);
  if (!t) return null;
  for (const a of AMBIGUOUS) {
    // **بحدِّ الكلمة لا بالاحتواء.** كان `t.includes(term)` — وهو نفسُ مصرف
    //   الكلمة العامّة الذي هُدم في `symptomGraph` و`merchandise`. وظهر أثرُه
    //   عند إضافة «فران»: **«زعفران» تحتوي «فران»**، فيُسأل مَن يطلب توابلَ
    //   «فران ديال الخبز ولا ماكينة؟».
    //   والسؤالُ في غير موضعه أسوأُ من الصمت: يُعلَّم الإنسانُ أنّ التطبيق
    //   يسأل بلا سبب، فيتوقّف عن قراءة أسئلته.
    if (![a.term, ...(a.forms || [])].some(w => hitsWord(norm(w), t))) continue;
    const hit = a.options.filter(o => o.cues.some(c => t.includes(norm(c))));
    if (hit.length === 1) return null;      // القرينةُ حسمت
    return a;                                // لا قرينة (أو قرينتان) ⇒ اسأل
  }
  return null;
}

/**
 * **مَن حسمت له القرينة** — والحسمُ كان يُرمى.
 *
 *   `detectAmbiguity` تُرجع `null` حين تحسم القرينةُ، فيُفهَم أنّ الجملةَ
 *   ليست غامضة — ولا يعرف أحدٌ **أيَّ معنًى** فازت به. فبقي فهمُ المفهوم
 *   على ما كان: «بغيت **نشري** شي فران **جديد** ب٨٠٠ درهم» ⇒ `bakery`،
 *   والقرينتان («نشري» و«جديد») تقولان إنّها آلةٌ تُشترى.
 *
 *   أي أنّ الملفَّ كان يعرف الجوابَ ويصمت عنه: يمنع السؤالَ ولا يُصلح
 *   الفهم. وهذا نصفُ عمل — والنصفُ الصامتُ أخطرُ لأنّه يبدو تامًّا.
 */
export function resolveAmbiguity(text: string): { term: string; id: string } | null {
  const t = norm(text);
  if (!t) return null;
  for (const a of AMBIGUOUS) {
    if (![a.term, ...(a.forms || [])].some(w => hitsWord(norm(w), t))) continue;
    const hit = a.options.filter(o => o.cues.some(c => t.includes(norm(c))));
    if (hit.length === 1) return { term: a.term, id: hit[0].id };
    return null;
  }
  return null;
}

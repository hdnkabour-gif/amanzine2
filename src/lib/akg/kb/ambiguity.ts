// الغموضُ المعجميّ — كلمةٌ واحدةٌ لمعنيَين، ولا سبيلَ إلى الحسم من النصّ.
//
//   من زيارةٍ ميدانيّة: سألتُ صاحبَ المحلّ عن «موطور»، فأجاب:
//     «يمكن ان يكون دراجة نارية، موطور ديال الطوموبيل محرك السيارة»
//   أي أنّ الغموضَ **في اللغة نفسها**، لا في قاموسنا. وكان المحرّك يُخمّن:
//   «بغيت نغسل الموطور» ⇒ تنظيف محرّك — وقد يكون صاحبُها يريد غسل درّاجته.
//
//   والتخمينُ هنا أسوأُ من الصمت: يمرّ بلا أثرٍ ويأخذ الإنسانَ إلى المكان
//   الخطأ. أمّا السؤالُ فيُنهي الغموضَ في ثانية، ويُشعر الإنسانَ أنّه مفهوم.
//
//   القاعدة: **إن وُجدت قرينةٌ حاسمة ⇒ احسم. وإلّا ⇒ اسأل، ولا تُخمّن.**
//
//   هذه ليست حالةً خاصّةً بالسيّارات. الغموضُ صنفٌ متكرّر في الدارجة:
//   «صباغة» (شعر/جدار/سيّارة) · «ماكينة» (خياطة/حلاقة/قهوة) · «طابلو»…
//   ولذلك سجلٌّ مفتوحٌ لا شرطٌ متناثرٌ في الكود.
// ============================================================

import { normLoose } from '../../normalize';
export interface AmbiguityOption {
  id: string;        // المفهوم إن اختير
  label: string;     // كما يُعرَض للإنسان
  cues: string[];    // قرائنُ تحسم لصالحه
}
export interface Ambiguity {
  term: string;
  ask: string;                 // السؤالُ كما يُطرَح بالدارجة
  options: AmbiguityOption[];
}

const norm = normLoose;   // كان نسخةً محلّيّةً أضعف


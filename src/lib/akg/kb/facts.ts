//
//   من زيارةٍ ميدانيّةٍ لبائعةٍ تبيع الملابس من بيتها. أرَتني رسائلَ الواتساب،
//   فإذا أغلبُها ستُّ جملٍ تتكرّر كلَّ يومٍ عشراتِ المرّات:
//     «سلام ختي فين كاينة» · «مزال عندك كساوي» · «وريني كساوي اللي عندك»
//     «شحال القياس» · «واش كاين التوصيل» · «بشحال التوصيل»
//     «انا ف طنجة امتا توصلني» · «واش هاد الثمن معاه التوصيل»
//
//   ولا واحدةٌ منها تسأل عن **مفهوم**. كلُّها تسأل عن **واقعةٍ عن نسخة**:
//   الموقع، التوفّر، المقاس، الثمن، التوصيل، الدفع. وهذا نصُّ القاعدة ① في
//   `docs/KNOWLEDGE_CONTRACT.md` حرفيًّا: «المفهومُ نوعُ شيء؛ والتوفّرُ والثمنُ
//   والموقعُ وقائعُ عن نسخةٍ منه».
//
//   فالعطبُ لم يكن جهلًا بالجواب، بل بحثًا في البابِ الخطأ: يفتّش المحرّكُ عن
//   مهنةٍ في جملةٍ لا مهنةَ فيها فيصمت — أو أسوأ، يُصيب «مطعمًا» من «واش كاين».
//   اثنتا عشرةَ جملةً من أربع عشرةَ رجعت فارغةً في أوّل قياس.
//
//   ولاحظ أنّ الحقلَ لا يقول «سؤال» بل «واقعة»: فنفسُ الواقعة تُذكَر من
//   الجهتين. «كاين التوصيل لجميع المدن» و«واش كاين التوصيل» كلتاهما عن
//   `delivery` — والاتّجاهُ (stance) هو الذي يفرّق بين مَن يُخبر ومَن يسأل.
//   فتنفع الطبقةُ الواحدةُ في قراءة إعلان البائعة وفي قراءة سؤال الزبونة معًا.
// ============================================================

import { normLoose } from '../../normalize';
export type FactTopic =
  | 'location'                // فين كاينة؟
  | 'availability'            // مزال عندك؟
  | 'catalog'                 // وريني اللي عندك
  | 'size'                    // شحال القياس؟
  | 'price'                   // بشحال؟
  | 'delivery'                // واش كاين التوصيل؟
  | 'delivery_price'          // بشحال التوصيل؟
  | 'delivery_time'           // امتا توصلني؟
  | 'price_includes_delivery' // واش هاد الثمن معاه التوصيل؟
  | 'payment';                // كيفاش نخلّص؟

const norm = normLoose;   // كان نسخةً محلّيّةً أضعف

const DELIVERY = ['التوصيل', 'توصيل', 'توصلني', 'توصلو', 'يوصل', 'نوصل', 'ليفريزو', 'الليفريزو',
  'غاماسور', 'كوسيور', 'livraison', 'livrer', 'delivery'];
const PRICE = ['بشحال', 'شحال', 'الثمن', 'ثمن', 'التمن', 'تمن', 'سوم', 'السوم', 'prix', 'price'];
const SIZE = ['قياس', 'القياس', 'مقاس', 'المقاس', 'طايل', 'taille', 'size', 'pointure'];
const TIME_Q = ['امتا', 'اماتا', 'فوقاش', 'وقتاش', 'شحال من نهار', 'شحال ديال الوقت', 'quand'];
const INCLUDED = ['معاه', 'فيه', 'شامل', 'بحالو', 'مع التوصيل'];
// «كاينه» أُسقطت: «فين كاينة» سؤالٌ عن **المكان** لا عن التوفّر، فكانت
// تُخرِج واقعتَين إحداهما زائفة. أداةُ الاستفهام قبلها هي التي تحسم.
const STILL = ['مزال', 'مازال', 'باقي', 'بقا', 'مابقاش', 'ما بقاش', 'متوفر'];
const HAVE_Q = ['عندك', 'عندكم', 'كاين', 'توجد'];
const SHOW = ['وريني', 'وريهم', 'ورينا', 'وريها', 'ورّيني', 'بين ليا', 'بيّن ليا', 'صيفط ليا',
  'صيفطي ليا', 'شوف ليا', 'عندك شنو', 'شنو عندك', 'شنو كاين', 'صور', 'تصاور', 'كاطالوك'];
const WHERE = ['فين كاين', 'فين كاينه', 'فين نلقا', 'فين نلقاك', 'فين المحل', 'فينك',
  'فين انت', 'فين انتي', 'شمن مدينه', 'اشمن مدينه', 'ou es tu', 'adresse'];
const PAY = ['الدفع', 'ندفع', 'نخلص', 'كنخلص', 'الخلاص', 'كاش', 'عند التسليم', 'paiement', 'cash'];

// القاعدةُ تُصيب إن أصابت **كلُّ** مجموعاتها. و`covers` تُسقط العامَّ حين يُصيب
// الأخصُّ: «بشحال التوصيل» ثمنُ توصيلٍ واحد، لا «توصيلٌ» و«ثمنٌ» منفصلان.
// الترتيبُ من الأخصّ إلى الأعمّ — وهو **جزءٌ من المعنى** لا تفصيلُ كتابة.
const RULES: { topic: FactTopic; all: string[][]; covers?: FactTopic[] }[] = [
  { topic: 'price_includes_delivery', all: [PRICE, DELIVERY, INCLUDED], covers: ['price', 'delivery', 'delivery_price'] },
  { topic: 'delivery_time',  all: [DELIVERY, TIME_Q], covers: ['delivery'] },
  { topic: 'delivery_price', all: [DELIVERY, PRICE],  covers: ['delivery', 'price'] },
  { topic: 'delivery',       all: [DELIVERY] },
  { topic: 'size',           all: [SIZE],   covers: ['price'] },   // «شحال القياس» مقاسٌ لا ثمن
  { topic: 'availability',   all: [STILL, HAVE_Q] },
  { topic: 'catalog',        all: [SHOW] },
  { topic: 'location',       all: [WHERE] },
  { topic: 'payment',        all: [PAY] },
  { topic: 'price',          all: [PRICE] },
];

// كلُّ الوقائع المذكورة في النصّ، بترتيب الأخصّ أوّلًا وبلا تكرار.
// جملةٌ واحدةٌ قد تحمل اثنتين («واش كاين التوصيل وبشحال») — فنُرجع الاثنتين.
export function detectFacts(text: string): FactTopic[] {
  const t = norm(text);
  if (!t) return [];
  const hits = (terms: string[]) => terms.some(w => t.includes(norm(w)));
  const found: FactTopic[] = [];
  const covered = new Set<FactTopic>();
  for (const r of RULES) {
    if (!r.all.every(hits)) continue;
    found.push(r.topic);
    for (const c of r.covers || []) covered.add(c);
  }
  return found.filter(f => !covered.has(f));
}


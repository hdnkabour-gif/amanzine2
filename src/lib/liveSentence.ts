// ============================================================
// **الجملةُ الحيّة — طبقةُ عرضٍ لا عقلٌ سادس.**
//
//   ── الفكرة ──
//   لا نافذةَ تنبثق ولا صفحةَ تُفتَح. **كلامُ الإنسان نفسُه هو الواجهة**:
//   ما فُهم يظهر قطعةً مُثبَتة، وما نقص يظهر **فراغًا في جملته هو**.
//
//       بغيت نبدل الثمن ديال ⟨👗 كسوة · ١٨٩ درهم⟩ ل [ ____ ] درهم
//
//   ── ولماذا هذا أهمُّ من كونه جميلًا ──
//   العطبُ الذي طاردناه أسبوعًا اسمُه «يعرف ثمّ يسأل»: يُقرأ المنتوجُ ثمّ
//   يُسأل «أيّ منتوج؟». وهذه الطبقةُ تقتله **بنيويًّا** لا بقاعدةٍ أخرى:
//   لا يمكن أن يُسأل عن شيءٍ **مرئيٍّ مملوءٍ أمام صاحبه**، والسؤالُ لم يعد
//   جملةً منفصلةً بل **الفراغَ نفسَه**.
//
//   ── وحدُّها الصارم: لا تفهم شيئًا ──
//   لا نيّةَ جديدة · لا محرّكَ جديد · لا عقدَ ثانيًا · لا مساسَ بـ
//   `Understanding` ولا بمطابقة القدرات. تأخذ ما قرأته الطبقاتُ وتُعيد
//   **شكلًا**. فإن حُذف هذا الملفُّ كلُّه بقي التطبيقُ يفهم كما كان.
//
//   ── والفراغاتُ تُشتقّ ولا تُكتَب ──
//   من `unmetNeeds` و`NEED_ASK` — وهما مصدرُ السؤال أصلًا. فيومَ تُضاف
//   حاجةٌ جديدةٌ لقدرةٍ يظهر فراغُها بلا سطرٍ هنا. وقائمةٌ ثانيةٌ مكتوبةٌ
//   بيدٍ كانت ستتباعد عن الأولى في أوّل إضافة.
// ============================================================

import { unmetNeeds, NEED_ASK, type Ability, type NeedKey } from './abilities';
import type { Understanding } from './akg/kb';
import { readAmount } from './money';

/** ما وقع عليه الفعل — يُعرَض قطعةً تُلمَس، لا يُسأل عنه. */
export interface Subject {
  id: string;
  name: string;
  /** ما يُطمئن الإنسانَ أنّه هو المقصود: الثمنُ الحاليُّ مثلًا. */
  note?: string;
  icon?: string;
}

/** فراغٌ في الجملة — سؤالٌ صار مكانًا يُملأ. */
export interface Slot {
  need: NeedKey;
  /** السؤالُ كما هو في `NEED_ASK` — يُعرَض تلميحًا داخل الفراغ. */
  ask: string;
  /** وحدةٌ تُكتَب بعد الفراغ فيبقى الكلامُ جملةً: «ل [ ___ ] **درهم**». */
  unit?: string;
  /** ما مُلئ فيه بعدُ. */
  value?: string;
}

export interface LiveSentence {
  /** كلامُه كما كتبه — لا يُعاد صوغُه ولا يُترجَم. */
  raw: string;
  /** الحقلُ المقصود («الثمن») — من `u.action.object` لا من قائمةٍ جديدة. */
  field?: string;
  subject?: Subject;
  slots: Slot[];
}

/** أسماءٌ دارجيّةٌ للحقول — ما يُقال للإنسان (القانون ١٠). */
const FIELD_SAY: Record<string, string> = {
  price: 'الثمن', stock: 'الستوك', photo: 'التصويرة', content: 'الوصف',
  phone: 'النمرة', address: 'العنوان', shop_name: 'اسم المحلّ',
  shop_hours: 'وقت الخدمة', language: 'اللغة',
};

/** وحدةُ كلّ حاجةٍ حين تُكتَب في جملة — فراغٌ بلا وحدةٍ يبدو استمارة. */
const UNIT: Partial<Record<NeedKey, string>> = { price: 'درهم', amount: 'درهم' };

/**
 * **الحقولُ التي تُملأ داخل الجملة** — وحدُّها معلَنٌ ومقصود.
 *
 *   لا يدخل هنا ما يحتاج مساحةً أو اختيارًا مركّبًا (صورةٌ تُرفَع · وصفٌ
 *   طويلٌ يُحرَّر). تلك بطاقةٌ أو صفحة — و«الجملةُ للإدخال، الكيانُ للعرض،
 *   والصفحةُ للعالَم».
 */
export const INLINE_NEEDS: NeedKey[] = ['price', 'amount', 'stock' as NeedKey, 'phone', 'address'];

/**
 * يبني الجملةَ الحيّة — أو `null` حين لا تصلح.
 *
 *   `null` هي الجوابُ الصحيحُ في أغلب الجمل: من قال «وريني الطلبات» يريد
 *   صفحةً، ومن قال «بغيت نبيع» لم يسمِّ حقلًا. والطبقةُ تصمت حيث لا تنفع.
 */
export function liveSentenceFor(
  raw: string,
  u: Understanding,
  match: Ability | null | undefined,
  ctx?: { subject?: Subject },
): LiveSentence | null {
  const field = u.action?.object;
  // شرطٌ أوّل: **حقلٌ مسمًّى صراحةً**. بلا حقلٍ لا جملةَ حيّة — النيّةُ
  //   الخشنةُ تفتح صفحةً كما كانت، وذاك صوابٌ لا نقص.
  if (!field || !match) return null;

  // شرطٌ ثانٍ: **قراءةٌ يُوثَق بها**. ٠٫٣٥ تعني فعلًا بلا هدفٍ سقط على
  //   `settings` — ولو بُنيت عليها جملةٌ حيّةٌ لعرضنا حقلًا لم يطلبه أحد.
  if ((u.action?.confidence ?? 0) < 0.5) return null;

  const known = {
    trade: u.service, product: ctx?.subject?.id || u.service,
    subject: u.service, price: readAmount(raw),
  };
  const missing = new Set<NeedKey>(unmetNeeds(match, known));

  // ── **والنقصُ مُعلَنٌ في قائمتَين لا واحدة** (وجدتُه بالقياس) ────
  //
  //     UPDATE_PRODUCT.needs = ['product']       ← مفاتيحُ مصنَّفة
  //     actions.ts:378 → needs.push('بشحال؟')     ← **نصٌّ حرّ**
  //
  //   فمن قال «بدّل الثمن ديال الكسوة» ينقصه ثمنٌ، والنقصُ مكتوبٌ جملةً
  //   لا مفتاحًا — فلا تراه طبقةٌ تقرأ المفاتيح. وهو نفسُ نمطِ «قائمتان
  //   لكلمةٍ واحدة» الذي تكرّر في هذا المشروع.
  //
  //   ولا أُنشئ قائمةً ثالثة: **الحقلُ نفسُه هو الحاجة**. من سمّى «الثمن»
  //   ولم يقل رقمًا ينقصه ثمن — وهو حرفيًّا شرطُ `actions.ts` نفسُه، مقروءًا
  //   من نوعٍ بدل نصّ. وإصلاحُ القائمتَين في مكانهما عملٌ آخرُ أُبلغ به ولا
  //   أخلطه بهذا.
  const FIELD_NEED: Partial<Record<string, NeedKey>> = { price: 'price', stock: 'amount' };
  const own = FIELD_NEED[field];
  if (own && readAmount(raw) === undefined) missing.add(own);

  const slots: Slot[] = [...missing]
    .filter(n => INLINE_NEEDS.includes(n))
    .map(n => ({ need: n, ask: NEED_ASK[n], unit: UNIT[n] }));

  // شرطٌ ثالث: **فراغٌ واحدٌ على الأقلّ يُملأ هنا**. لو كان الناقصُ صورةً
  //   أو وصفًا لَما نفعت الجملةُ — تلك بطاقة.
  if (!slots.length) return null;

  return { raw, field: FIELD_SAY[field] || field, subject: ctx?.subject, slots };
}

/**
 * **هل تملأ هذه الرسالةُ الفراغَ المعلَّق؟**
 *
 *   ── ولماذا هنا لا في `money.ts` ──
 *   قِيس: `readAmount('179')` تُرجع `undefined`، و«١٧٩ درهم» تُقرأ. وهذا
 *   **صوابٌ في قارئٍ عامّ**: «عندي ٣ ديال المحلات» يجب ألّا تُقرأ ثلاثةَ
 *   دراهم، وتوسيعُه ليقرأ كلَّ رقمٍ مجرّدٍ يُفسد جملًا كثيرة.
 *
 *   والفرقُ أنّ **الفراغَ المعلَّق يمنح الرقمَ معناه**: من سُئل «بشحال؟»
 *   وأجاب «179» أجاب بلا لبس. فالسياقُ هو الذي يرخّص، لا القارئ — ولذلك
 *   تعيش القاعدةُ حيث يعيش السياق.
 */
export function fillsSlot(slot: Slot, raw: string): string | null {
  const t = (raw || '').trim();
  if (!t) return null;

  if (slot.need === 'price' || slot.need === 'amount' || (slot.need as string) === 'stock') {
    // بالعملةِ مذكورةً: القارئُ العامُّ يكفي ويُحترَم.
    const said = readAmount(t);
    if (said !== undefined) return String(said);
    // ومجرّدًا: يُقبَل **رقمًا وحدَه** لا رقمًا داخل كلام. «179» جوابٌ،
    //   و«179 حاجة أخرى» ليست جوابًا — فلا نخمّن على كلامٍ لم يُقصَد به الملء.
    const bare = t.replace(/[٠-٩]/g, d => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)));
    return /^\d{1,9}([.,]\d{1,2})?$/.test(bare) ? bare.replace(',', '.') : null;
  }
  return null;
}

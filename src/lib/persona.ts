// شخصيّة AMANZINE — «مرشدٌ مغربيّ ذكيّ». صوتٌ واحدٌ ثابتٌ عبر كلّ الرسائل:
//   دافئ، واثق، يقود خطوة بخطوة. ليس ChatGPT ولا Google — بل مرشدك الذي يقول
//   «جي معايا، غادي نوصّلك». مركزيّةٌ كي لا تتناثر الصياغات وتضيع الشخصيّة.
// ============================================================

export const PERSONA = {
  name: 'AMANZINE',
  role: 'مرشدك',                                  // من هو: مرشد، لا محرّك بحث
  tagline: 'جي معايا — غادي نوصّلك خطوة بخطوة.',    // وعدُه الثابت
  reassure: 'ما تحتاجش تعرف تستعمل التطبيق — غير كتب بالدارجة، وأنا نفهمك.',
} as const;

// تحيّةٌ حسب الوقت + الاسم — مصدرٌ واحد كي لا تتكرّر بصياغاتٍ مختلفة عبر الواجهات.
export function personaGreeting(hour: number = new Date().getHours(), name = ''): string {
  const g = hour < 12 ? 'صباح الخير' : hour < 18 ? 'مرحبا' : 'مساء الخير';
  const n = (name || '').split(' ')[0];
  return n ? `${g} ${n} 👋` : `${g} 👋`;
}

// جملةُ الاستقبال — تتطوّر: أوّل مرّة يُعرّف AMANZINE نفسه ويبني الثقة؛ العائد
// يُستقبَل بألفةٍ أخفّ (لا نُعيد التعريف على من يعرفنا). شخصيّةٌ حيّة لا ثابتة.
export function personaWelcome(name = '', returning = false): string {
  const n = (name || '').split(' ')[0];
  if (returning) {
    return n ? `مرحبا بعودتك أ${n} 👋 شنو محتاج اليوم؟` : 'مرحبا بعودتك 👋 كنّا هنا — شنو محتاج اليوم؟';
  }
  const who = n ? `أنا ${PERSONA.name}، ${PERSONA.role} أ${n}.` : `أنا ${PERSONA.name}، ${PERSONA.role}.`;
  return `${who} ${PERSONA.reassure}`;
}

// **صنفُ النشاط — يُشتقُّ من المعرفة، ولا يُسأل عنه.**
//
//   ── القيدُ الذي وُلد منه ──
//   صاحبُ المشروع نصًّا: «صاحبُ محلٍّ أو تاجرٌ أو حرفيٌّ لا يمكن أن تأخذ
//   نصفَ ساعةٍ من وقته وهو يشتغل». فكلُّ سؤالٍ يُطرَح يجب أن يُدفَع ثمنُه —
//   وسؤالُ «واش نتا محلّ ولا حرفيّ؟» **ثمنُه بلا مقابل**: الجوابُ مقروءٌ
//   سلفًا من جملته.
//
//   ── ولماذا الأصنافُ ثلاثة ──
//   لا لأنّها تبدو مرتّبة، بل لأنّ **ما يشتريه الإنسانُ يختلف**:
//
//     محلّ    يشتري **سلعة**  ⇒ يقرّر بالثمن والتوفّر   ⇒ «بشحال؟»
//     حرفيّ   يشتري **تدخّلًا** ⇒ يقرّر بالثقة والسرعة   ⇒ «واش تقدر دابا؟»
//     خدمة    يشتري **موعدًا** ⇒ يقرّر بالتخصّص والوقت  ⇒ «إمتا؟»
//
//   فمن عرض سبّاكًا بشبكةِ منتجاتٍ أخفى ما يُقرِّر، ومن عرض بقّالًا بسيرةٍ
//   ذاتيّةٍ أخفى ما يُقرِّر. والصنفُ يحدّد **الأسئلةَ والصفحةَ معًا**.
//
//   ── ومن أين يُقرأ ──
//   `catalog.categoryForConcept` تعرف سلفًا أنّ مفهومًا خدمةٌ أم سلعة
//   (`kind`)، و`CONCEPTS` تحمل خدماتِ كلّ مفهوم. فلا قائمةَ ثانيةً تُكتَب
//   هنا: يُقرأ ما هو مكتوبٌ ويُصنَّف. ويومَ يُضاف مفهومٌ يُصنَّف بلا سطر.
// ============================================================

import { categoryForConcept } from './catalog';
import { CONCEPTS } from './akg/kb/concepts';
import { hitsWord, normLoose } from './normalize';

export type VisitKind = 'shop' | 'craft' | 'service';

export const KIND_SAY: Record<VisitKind, string> = {
  shop: 'محلّ كيبيع',
  craft: 'حرفيّ كيصلّح',
  service: 'مقدّم خدمة',
};

/**
 * **الحرفةُ تدخّلٌ على شيءٍ يملكه الإنسانُ سلفًا** — وهذا حدُّها.
 *
 *   السبّاكُ لا يبيعك ماءً، يُصلح ما عندك. والكوافيرُ لا يبيعك شعرًا، يخدمك
 *   في موعد. والفرقُ بين الاثنَين أنّ الأوّلَ **يأتيك حين يقع عطبٌ** والثاني
 *   **تأتيه حين تختار**. ولذلك تُقرأ الحرفةُ من أفعالِ الإصلاح لا من اسمها.
 */
const REPAIR = ['تصليح', 'إصلاح', 'صيانة', 'تركيب', 'يصلح', 'كيصلح', 'ديباناج', 'تسريب', 'عطل'];

/**
 * يقرأ صنفَ النشاط من مفهومٍ محلول — أو `null` إن لم يُحسَم.
 *
 *   `null` جوابٌ مشروع: يومَها يُسأل الزائرُ سؤالًا واحدًا، ولا يُخمَّن.
 *   والتخمينُ هنا يُنتج صفحةً تُخفي ما يُقرِّر — أسوأُ من سؤالٍ واحد.
 */
export function kindOfConcept(conceptId: string | null | undefined): VisitKind | null {
  if (!conceptId) return null;
  const c = (CONCEPTS as any[]).find(x => x.id === conceptId);
  if (!c) return null;

  const text = normLoose([
    c.concept?.ar, c.concept?.darija, ...(c.services || []),
  ].filter(Boolean).join(' · '));

  // ① إصلاحٌ صريحٌ ⇒ حرفة. يسبق الفئةَ لأنّ «تصليح التلفاز» تُصنَّف خدمةً
  //    في الكتالوج، وهو صحيحٌ في التصنيف وخاطئٌ في **ما يُعرَض**.
  if (REPAIR.some(w => hitsWord(normLoose(w), text))) return 'craft';

  // ② ثمّ **مَن يبيع سلعةً** — ويسبق الكتالوجَ لسببٍ مقيس.
  //
  //   `categoryForConcept` تختار **قالبَ الاستمارة** (حقولُ سلعةٍ أم خدمة)
  //   بقاعدةٍ مكتوبةٍ فيها: «مَن تعرف قاعدةُ المعرفة ما يفعله ⇒ خدمة». وهي
  //   صحيحةٌ لسؤالها، خاطئةٌ لسؤالنا: قِيس فصُنِّف **البقّالُ والمخبزةُ
  //   والمطعمُ** «خدمة» — وكلُّهم يبيعون سلعةً يقرّر فيها الثمنُ والتوفّر.
  //
  //   وهي ثالثُ مرّةٍ أستعمل فيها هذه الدالّةَ لسؤالٍ ليس سؤالَها. نيابةُ
  //   سؤالٍ عن سؤالٍ تعمل حتّى تكفّ عن العمل بلا صوت.
  //   و«**محل**» ليست فيها: كلمةٌ تعني **مكانًا** لا تجارة، وتقع في «محل
  //   لافاج» و«محل حلاقة» و«محل تصليح». قِيست فصار غاسلُ السيّارات «محلًّا
  //   كيبيع» — وهو يبيع **فعلًا على سيّارتك** لا سلعةً على رفّ. والكلماتُ
  //   هنا **صريحةٌ في البيع** وحدَها.
  const SELLS = ['بائع', 'بيع', 'مطعم', 'مقهى', 'مخبز', 'مخبزه', 'حانوت', 'بقال', 'دكان', 'متجر'];
  if (SELLS.some(w => hitsWord(normLoose(w), text))) return 'shop';

  // ③ وأخيرًا الكتالوج: ما بقي وصنّفته خدمةً فهو خدمةٌ بموعد.
  const kind = categoryForConcept(conceptId)?.kind;
  if (kind === 'service') return 'service';
  if (kind) return 'shop';
  return null;
}

/** سؤالٌ يُطرَح في الزيارة — نصُّه ونوعُ جوابه. */
export interface VisitAsk {
  id: string;
  q: string;
  /** تلميحٌ يُعرَض داخل الخانة — مثالٌ من كلام الناس لا وصفٌ تقنيّ. */
  hint?: string;
  kind: 'text' | 'lines' | 'money' | 'yesno' | 'hours';
  /** هل يمنع الحفظَ إن نقص؟ **الحدُّ الأدنى الذي تعمل به الصفحة**. */
  required?: boolean;
}


/** ما ينقص قبل الحفظ — يُحسَب ولا يُكتَب في الواجهة مرّةً ثانية. */
export function missingFor(kind: VisitKind, answers: Record<string, unknown>): string[] {
  return ASKS[kind].filter(a => a.required && !filled(answers[a.id])).map(a => a.q);
}

function filled(v: unknown): boolean {
  if (Array.isArray(v)) return v.length > 0;
  if (typeof v === 'string') return v.trim().length > 0;
  return v !== undefined && v !== null && v !== '';
}

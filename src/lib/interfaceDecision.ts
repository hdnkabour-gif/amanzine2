// ============================================================
// طبقةُ الواجهة — «ما **شكلُ** الواجهة؟» لا «هل نفعل؟».
//
//   ── الانقسامُ الذي أُصلح ──
//   كانت هنا نسخةٌ ثانيةٌ من الحكم: تقرأ `confidence` وتقارنها بـ
//   `CONFIDENCE.ACT` و`CONFIDENCE.CONFIRM` وتقرّر direct/confirm/clarify.
//   وفي `executionPolicy` نسخةٌ أولى تقرأ نفسَ الرقم وتقارنه بعتبةٍ **تتبع
//   خطورةَ القدرة**. فعلى جملةٍ واحدةٍ قالت الأولى «نفّذ» والثانية «أكّد»،
//   لأنّ الثانيةَ لا تعرف الخطورةَ أصلًا. وقِيس على الكود: من الأحكام
//   الخمسة التي تُخرجها `decideExecution` كانت الواجهةُ تستهلك **حكمَين**
//   وتُهمل ثلاثة، وتبني ما تعرضه من حسابها الخاصّ.
//
//   ── القاعدة الآن ──
//   حَكَمٌ واحدٌ يقول «نفّذ أم أكّد أم اسأل» وهو `decideExecution`، وهذه
//   الطبقةُ **تترجم حكمَه إلى شكل**. ولا تقرأ `confidence` إطلاقًا — ولذلك
//   حُذف استيرادُ `CONFIDENCE` من هنا: عتبةٌ في مكانَين تتباعد بصمت.
//
//   ── وما بقي لها وحدَها ──
//   ثلاثةُ أسئلةٍ لا يعرفها الحَكَم: هل كتب الإنسانُ شيئًا أصلًا (welcome)؟
//   وهل عندنا سؤالٌ موجّهٌ جاهز (guided)؟ وكم سألنا حتّى الآن (escalate)؟
//   تُقرَّر خطوةٌ واحدة، ثمّ يُعاد القرار بعد كلّ جواب.
// ============================================================

import { MAX_CLARIFICATIONS } from './clarify';
import type { Verdict } from './executionPolicy';

// `clarify` = عندنا سؤالُ استيضاحٍ مبنيٌّ على **الناقص** (HU-2).
// `escalate` = سألنا ما يكفي بلا ارتفاعٍ في الفهم ⇒ إنسان (ADR-0006).
// و`welcome` تقلّصت لمعناها الحقيقيّ: **لا مُدخلَ أصلًا**. كانت تبتلع كلَّ
// ثقةٍ منخفضة، وهذا هو «ما فهمناش» بلباسٍ مهذَّب.
// `explain` = ليس طلبًا أصلًا (نقلُ كلامِ غيره، سؤالٌ عن التطبيق) — يُقال
// ولا يُفعَل. كان الحكمُ يصدر ولا شكلَ له، فيُعرَض نصُّه بلا وضعٍ يحكمه.
// `refuse` = المجالُ لا يقبل هذا الفعلَ أصلًا. شكلٌ مستقلٌّ عن `explain`:
// ذاك «ما طلبتَ شيئًا» وهذا «طلبتَ ما لا يُفعَل» — ولا يُخلَط الاعتذارُ بالشرح.
export type InterfaceMode = 'direct' | 'guided' | 'confirm' | 'clarify' | 'escalate' | 'welcome' | 'explain' | 'refuse' | 'soon';

export interface DecisionInput {
  intent: string;
  steps?: unknown[];
  url?: string;
  page?: string;
  /** هل كتب المستخدمُ شيئًا أصلًا؟ الفارقُ بين «لا نفهم» و«لا مُدخل». */
  hasInput?: boolean;
  /** كم استيضاحًا سُئل في هذه الجلسة — يقرّر متى ننتقل لإنسان. */
  askedCount?: number;
}

export interface InterfaceDecision {
  mode: InterfaceMode;
  reason: string;   // شرحٌ إنسانيّ — «كلّ شيء قابل للشرح»
}

/**
 * @param need ما يعرفه المشهدُ: وجهةٌ جاهزة؟ سؤالٌ موجّه؟ كم سألنا؟
 * @param verdict حكمُ `decideExecution` — **مُلزِم**. جُعل مطلوبًا عمدًا:
 *                لو بقي اختياريًّا لعادت النسخةُ الثانيةُ من الحكم مسارًا
 *                احتياطيًّا يعمل بصمتٍ في كلّ نداءٍ نسي تمريرَه.
 */
export function decideInterface(need: DecisionInput, verdict: Verdict): InterfaceDecision {
  const hasDest = !!(need.url || need.page);

  // لا مُدخلَ أصلًا → ترحيب. هذه وحدَها حالةُ الترحيب: أن يدخل الإنسانُ ولم
  // يقل شيئًا بعد. أمّا أن يقول ولا نفهم، فذاك سؤالٌ لا ترحيب.
  if (need.hasInput === false) {
    return { mode: 'welcome', reason: 'لا مُدخلَ بعد — نرحّب ونقترح مداخل' };
  }
  // ليس طلبًا أصلًا → قُل ولا تفعل. يسبق «السؤالَ الموجّه»: من نقل كلامَ
  // زبونٍ لا يُسأل «شنو نوع الخدمة؟» — ما طلب شيئًا حتّى يُستوضَح.
  if (verdict === 'explain') {
    return { mode: 'explain', reason: 'ليس طلبًا — نشرح ولا نفعل' };
  }
  // العجزُ يسبق السؤالَ الموجّه: لا يُستوضَح تفصيلُ فعلٍ لا يُفعَل.
  if (verdict === 'refuse') {
    return { mode: 'refuse', reason: 'المجالُ لا يقبل هذا الفعلَ — نقولها ولا نعتذر مرّتين' };
  }
  // **الحدُّ الصادقُ يسبق السؤالَ الموجّه.** وهذا موضعُه بالضبط: لو وُضع
  //   بعده لَابتلعته `steps` — فالنيّةُ الخشنةُ تُنتج خطواتٍ دائمًا، وتلك
  //   الخطواتُ هي عينُها حلقةُ الأسئلة التي لا تنتهي.
  if (verdict === 'soon') {
    return { mode: 'soon', reason: 'فُهم الطلبُ ولا بابَ له — نقولها ونسجّلها ولا نسأل سؤالًا بلا جواب' };
  }
  // يوجد سؤالٌ موجّه أصلًا → اسأل سؤالًا واحدًا (المحادثة القصيرة).
  if (need.steps && need.steps.length) {
    return { mode: 'guided', reason: 'النيّة تحتاج توضيحًا — سؤالٌ واحدٌ يحسم' };
  }
  // «نفّذ» + وجهةٌ جاهزة → لا تسأل، وصّل مباشرة.
  if (verdict === 'execute' && hasDest) {
    return { mode: 'direct', reason: 'الحكمُ تنفيذٌ ووجهةٌ واضحة — نتيجة مباشرة بلا أسئلة' };
  }
  // «نفّذ» بلا وجهة لا يُوصِّل أحدًا: لا هدفَ نمشي إليه. فيبقى التأكيدُ
  // أقربَ صدقًا — نعرض ما فهمنا بدل أن نصمت.
  if (verdict === 'confirm' || verdict === 'execute') {
    return { mode: 'confirm', reason: verdict === 'execute' ? 'حكمُ تنفيذٍ بلا وجهة — نؤكّد الفهم' : 'دون حدّ التنفيذ — نؤكّد الفهم قبل أن نمشي' };
  }
  // «اسأل»: نسأل ولا نعتذر. وبعد استيضاحين بلا ارتفاع ⇒ إنسان.
  //
  //   ومكتوبٌ صراحةً لا سقوطًا في النهاية: حكمٌ بلا `verdict === '…'` يبدو
  //   للحارس ㉒ حكمًا مُهمَلًا، وهو محقٌّ — فالسقوطُ الصامت هو بالضبط الطريقةُ
  //   التي ضاعت بها ثلاثةُ أحكامٍ قبل هذا الإصلاح.
  if (verdict === 'ask') {
    return (need.askedCount ?? 0) >= MAX_CLARIFICATIONS
      ? { mode: 'escalate', reason: 'سألنا ما يكفي بلا ارتفاعٍ في الفهم — إنسانٌ خيرٌ من سؤالٍ ثالث' }
      : { mode: 'clarify', reason: 'ما فهمنا كفايةً — نسأل عن الناقص بدل أن نعتذر' };
  }
  // حكمٌ أُضيف إلى الاتّحاد ولم يُعطَ شكلًا. لا يقع اليوم (يحرسه ㉒)، ويبقى
  // سؤالًا لا صمتًا لو وقع غدًا.
  return { mode: 'clarify', reason: 'حكمٌ بلا شكلٍ معروف — نسأل بدل أن نُخمّن' };
}

// نصّ التأكيد بصوت الشخصيّة — يُعرَض في وضع confirm.
export function confirmPrompt(label: string): string {
  return `فهمت أنّك باغي ${label} — صح؟`;
}

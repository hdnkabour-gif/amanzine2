// ============================================================
// Human Intent Layer — «ماذا يحاول هذا الإنسان أن يفعل الآن؟»
// طبقةٌ تسبق تحديد المهنة/المنتج (needEngine). لا قاموس ضخم — أنماطٌ قليلة تُجيب
// أوّلًا عن نيّة الإنسان، ثم يأتي المحرّك ليحدّد التفاصيل. تُصحّح الأخطاء التي
// كشفها الاستعمال الحقيقيّ:
//   • «عندي مشكل فالدار»  → مساعدة (لا «عقار للبيع»).
//   • «أنا تقني متخصّص» / «أنا حرفي» → تعريفٌ بالنفس (لا «أنشئ إعلانًا»).
//   • «أنا كنبيع» / «بغيت نبيع» → يريد البيع → نسأل «شنو باغي تبيع؟» (لا قفزٌ لنموذج).
//   • «واش ممكن تعاوني؟» / «أشنو ندير؟» → سؤالٌ عامّ → نرحّب ونقود.
// كلّ قراءة تحمل سببًا (reason) — «كلّ شيء قابل للشرح».
// ============================================================

import { deArabizi } from './akg/kb/arabizi';

import { normLoose } from './normalize';

export type HumanIntent = 'SELF' | 'HELP' | 'SELL' | 'BUY' | 'QUESTION' | 'EXPLORE' | 'NONE';

export interface HumanRead {
  intent: HumanIntent;
  confidence: number;   // 0..1
  reason: string;       // لماذا صُنّفت هكذا (شرحٌ إنسانيّ)
}

// تطبيع خفيف مستقلّ (لا يعتمد على needEngine — طبقة مكتفية بذاتها).
function norm(s: string): string {
  // كانت نسخةً محلّيّةً أضعفَ من نسخة الفهرس — والقياسُ أظهر أنّ «عندييي محل»
  // تُسقط `SELF` إلى `NONE`، أي أنّ من يعرّف بنفسه لا يُعرَف.
  return normLoose(s);
}

const has = (t: string, words: string[]) => words.some(w => t.includes(w));

// ── الأنماط (لا كلماتٌ معزولة بل إشاراتٌ على النيّة) ──────────
// مشكلٌ/عطبٌ موصوفٌ بكلمةٍ عامّة (لا عَرَض محدّد — ذاك يتكفّل به المحرّك مباشرةً).
const HELP = ['مشكل', 'مشكله', 'عطل', 'خربان', 'معطل', 'خاسر', 'ماخدامش', 'ما خدام', 'ماخدماش', 'واقف', 'بلوكي', 'تعطل', 'حبس', 'ماكيخدمش'];
// طلبُ إرشادٍ/مساعدةٍ في الاستعمال (سؤالٌ عامّ، لا مشكلٌ تقنيّ).
const QUESTION = ['واش ممكن', 'ممكن تعاون', 'تعاوني', 'عاوني', 'ساعدني', 'اشنو ندير', 'شنو ندير', 'اش ندير', 'اشنو نكتب', 'شنو نكتب', 'كيفاش نبدا', 'كيفاش نستعمل', 'كيفاش نخدم', 'بغيت نفهم', 'ماشي فاهم', 'اول مره', 'شنو هاد', 'اش هاد التطبيق'];
// أفعالُ العَرض (بيع/نشر).
const SELL_V = ['نبيع', 'للبيع', 'بيعان', 'نسوق', 'نعلن', 'ننشر'];
// أفعالُ الطلب (شراء/بحث).
const BUY_V = ['نشري', 'نقلب على', 'كنقلب على', 'فين نلقي', 'وين نلقي', 'نقلب شي', 'نقلب على شي'];
// تعريفٌ بالنفس عامّ (مزوّد/حرفيّ/محلّ) — الحالات المبهمة التي كان يخطئ فيها المحرّك.
// المهن المحدّدة (كوّافير/صبّاغ…) تبقى للمحرّك الذي يبني صفحة الخدمة مباشرةً.
const SELF_ID = ['حرفي', 'حرايفي', 'صنايعي', 'تقني', 'مهني', 'مزود خدمه', 'مزوّد خدمه', 'مزود', 'كنخدم', 'كنقدم خدمه', 'خدام حر', 'عندي حرفه', 'عندي مهنه', 'عندي خدمه', 'عندي محل', 'عندي محال', 'عندي حانوت', 'عندي مطعم', 'عندي كافي', 'عندي سناك', 'عندي بقاله', 'عندي تجربه ف'];
// كلماتُ الطلب — تميّز «بغيت حرفي» (يطلب) عن «أنا حرفي» (يعرّف نفسه).
const WANT = ['بغيت', 'باغي', 'نحتاج', 'خصني', 'محتاج'];
// تصفّحٌ بلا هدفٍ محدّد — «غير جيت نشوف» (كثيرٌ جدًّا في أوّل دخول) ⇒ رحلةٌ مختلفة.
const EXPLORE = ['غير كنشوف', 'غير نشوف', 'غير كنجرب', 'كنتفرج', 'نتفرج', 'كنكتاشف', 'غير كنكتاشف', 'غير جيت نشوف', 'جيت نتفرج', 'شنو كاين', 'واش كاين شي جديد', 'غير باش نشوف', 'نشوف اللي كاين'];

// عدد الكلمات بعد إسقاط ضمير البداية (انا/احنا) — لقياس «الإبهام»:
// «انا كنبيع» و«بغيت نشري» جملٌ قصيرةٌ بلا سلعةٍ محدّدة ⇒ نسأل. «بغيت نشري صباط» ⇒ للمحرّك.
function contentWords(t: string): number {
  return t.replace(/^(انا|احنا|انت|حنا)\s+/, '').split(' ').filter(Boolean).length;
}

/**
 * readHuman — يقرأ نيّة الإنسان قبل أيّ تصنيفٍ للمهنة أو المنتج.
 * يرجع NONE للطلبات المحدّدة (عَرَضٌ موصوف، سلعةٌ باسمها، مهنةٌ مذكورة) لتُمرَّر
 * للمحرّك الذي يفهمها بدقّةٍ أعلى.
 */
export function readHuman(raw: string): HumanRead {
  const t = norm(deArabizi(raw));   // اللاتينيّة أوّلًا: «ana 7rayfi» → «أنا حرايفي»
  if (!t) return { intent: 'NONE', confidence: 0, reason: 'فارغ' };
  const cw = contentWords(t);

  // 1) مساعدة — أعلى أولويّة: تمنع فخّ «عندي مشكل فالدار» → عقار.
  if (has(t, HELP)) {
    return { intent: 'HELP', confidence: 0.82, reason: 'كلمةٌ تدلّ على مشكلٍ/عطبٍ يحتاج مساعدة' };
  }

  // 2) سؤالٌ عامّ عن الاستعمال («واش ممكن تعاوني؟» «أشنو نكتب؟»).
  if (has(t, QUESTION)) {
    return { intent: 'QUESTION', confidence: 0.6, reason: 'سؤالٌ عامّ عن كيفيّة الاستعمال أو طلبُ إرشاد' };
  }

  // 2.5) تصفّحٌ بلا هدف — «غير جيت نشوف» ⇒ استقبالٌ دافئ ورحلةُ اكتشاف.
  if (has(t, EXPLORE)) {
    return { intent: 'EXPLORE', confidence: 0.6, reason: 'المستخدم يتصفّح بلا هدفٍ محدّد — نعطيه رحلةَ اكتشاف' };
  }

  // 3) بيعٌ مبهم — فعلُ بيعٍ في جملةٍ قصيرةٍ بلا سلعةٍ محدّدة ⇒ نسأل «شنو باغي تبيع؟».
  if (has(t, SELL_V) && cw <= 2) {
    return { intent: 'SELL', confidence: 0.75, reason: 'نيّةُ بيعٍ دون تحديد السلعة — نسأل ماذا' };
  }

  // 4) شراءٌ مبهم — فعلُ شراءٍ في جملةٍ قصيرةٍ بلا سلعة ⇒ نسأل «شنو باغي تشري؟».
  if (has(t, BUY_V) && cw <= 2) {
    return { intent: 'BUY', confidence: 0.7, reason: 'نيّةُ شراءٍ دون تحديد السلعة — نسأل ماذا' };
  }

  // 5) تعريفٌ بالنفس — إشارةُ هويّةٍ (حرفيّ/مزوّد/محلّ) بلا طلبٍ ولا بيعٍ ولا شراء.
  // «عندي محل **للكراء**» ليست تعريفًا بالنفس بل إعلانًا. الكلمةُ الحاسمة
  // هي ما بعد المحلّ لا المحلُّ نفسُه — و«عندي محل» في `SELF_ID`، فكان صاحبُ
  // المحلّ الذي يريد كراءه يُساق إلى إنشاء صفحةِ نشاط. وهذه الطبقةُ تسبق
  // المحرّكَ كلَّه، فلا تنفع معالجتُها في القواعد الأدنى.
  const LISTING_V = ['للكراء', 'للبيع', 'للايجار', 'للإيجار', 'للتفويت', 'للتبديل'];
  if (has(t, SELF_ID) && !has(t, LISTING_V) && !has(t, WANT) && !has(t, SELL_V) && !has(t, BUY_V)) {
    return { intent: 'SELF', confidence: 0.72, reason: 'المستخدم يُعرّف نفسه (مزوّد/حرفيّ/صاحب محلّ) لا يطلب شيئًا' };
  }

  return { intent: 'NONE', confidence: 0, reason: 'طلبٌ محدّد — يُمرَّر لمحرّك النيّة' };
}

// ============================================================
// **الحدُّ الصادق: «فهمتُك، وهادشي مازال ما كايناش».**
//
//   قِيس على جملةٍ من جملِ القبول: «بغيت نمشي لطنجة» ⇒ الشاشةُ تقول
//   **«شنو محتاج بالضبط؟»**. والرجلُ قال ما يحتاج بالضبط: يريد أن يمشي
//   لطنجة. فالسؤالُ ليس استيضاحًا بل **إخفاءُ عجزٍ في ثوب سؤال** — يدخل
//   الإنسانُ حلقةً لا تنتهي، لأنّ أيَّ جوابٍ يعطيه لا يوجد له باب.
//
//   وهذا يختلف عن الجهل اختلافًا كاملًا:
//
//       لم نفهم        ⇒ «ما فهمتش مزيان» + نسأل        (`learning_unknowns`)
//       فهمنا غلطًا     ⇒ يردّه صاحبُه                    (`learning_misreads`)
//       **فهمنا تمامًا ولا باب** ⇒ **هنا**
//
//   والثالثةُ أنفعُ الثلاث ولم تكن لها قناةٌ أصلًا: هي **خارطةُ الطريق يكتبها
//   الناسُ بأنفسهم**. فمن قال «بغيت نمشي لطنجة» لم يُخطئ ولم نُخطئ — طلب
//   شيئًا لم نبنِه بعد، وهذا خبرٌ يستحقّ أن يُحفَظ لا أن يُبتلَع في سؤال.
//
//   ── حدَّان يمنعان هذا من أن يصير اختراعًا ──
//   ①  **لا يُنشئ قدرةً ولا مفهومًا.** هذه الطبقةُ معزولةٌ عن فهرس المفاهيم
//      تمامًا: لا تُغذّي `service` ولا بحثًا ولا `abilityFor`. ولو دخلت
//      «نمشي» فهرسَ المفاهيم لَصارت ثامنَ مصارف الكلمة العامّة.
//   ②  **لا تنطق إلّا حيث لا باب.** تُسأل بعد أن يعجز الكتالوجُ كلُّه، فمن
//      قال «بغيت نمشي نشري كسوة» يُقرأ له `clothing` ⇒ باب ⇒ ولا حدَّ يُقال.
// ============================================================

import type { Understanding } from './akg/kb';
import { unifyLetters, stripDiacritics } from './normalize';

export interface Boundary {
  /** مجالٌ معروفٌ بلا باب — `transport` اليوم. */
  id: string;
  /** ما فهمناه، بلسان الإنسان لا بلسان الكود: «تمشي لطنجة». */
  what: string;
  /** الجملةُ كاملةً كما تُقال. */
  say: string;
}

const NZ = (s: string) => unifyLetters(stripDiacritics(String(s || ''))).toLowerCase()
  .replace(/\s+/g, ' ').trim();

/**
 * **مجالٌ يُعرَف ولا يُخدَم.**
 *
 *   جدولٌ لا كود: إضافةُ مجالٍ سطرٌ واحد. و`deny` ليست زينة — «التوصيل»
 *   مخدومٌ فعلًا (`VIEW_DELIVERY_PROVIDERS`)، فلو ابتلعته أنماطُ النقل
 *   لَقلنا «مازال ما كايناش» عن بابٍ يعمل. وهذا أسوأُ من الصمت.
 */
interface Domain {
  id: string;
  /** أنماطٌ تُقرأ بعد التطبيع — كلمتان فأكثر، فالكلمةُ الواحدةُ تبتلع. */
  cues: RegExp[];
  /** ما يُبطلها: مجالٌ مجاورٌ **مخدومٌ** يُشبهها في اللفظ. */
  deny: RegExp;
  /** اسمُ ما فهمناه، يُركَّب مع الوجهة إن وُجدت. */
  name: (u: Understanding) => string;
  /** تفاصيلُ قُرئت وتستحقّ أن تُذكَر — إثباتُ أنّنا سمعنا. */
  extra?: (u: Understanding) => string[];
}

const DOMAINS: Domain[] = [
  {
    // انتقالُ **إنسان** — لا انتقالُ طرد. والفرقُ بينهما بابٌ يعمل وبابٌ لا.
    id: 'transport',
    cues: [
      /(^| )(بغيت|باغي|باغيه|خاصني|بغينا|كنقلب على)\s*(ن|كن)(مشي|سافر|تنقل|روح)/,
      /(^| )(ن|كن)(مشي|سافر|تنقل)\s*(ل|لـ|فـ|ف)?\s*\S/,
      /(^| )(شي )?(طاكسي|طوبيس|كار|ترامواي|طرانسبور)( |$)/,
      /(^| )(نقل|توصيلة)\s*(ديال )?(الناس|البشر|شخص)( |$)/,
    ],
    // «التوصيل» و«الكوموند» و«الكولي» مخدومةٌ — طردٌ لا إنسان.
    deny: /(توصيل|كوموند|كولي|طرد|بارسيل|livraison|colis|وصلات)/,
    name: u => u.city ? `تمشي ل${u.city}` : 'تتنقّل',
    // **وما قُرئ يُقال.** «بغيت نمشي الحي عندي غير 10 دراهم» ⇒ الميزانيّةُ
    //   مقروءةٌ (١٠) وتُبتلَع، فيسمع الرجلُ «تتنقّل» ويظنّ أنّنا لم نقرأ نصفَ
    //   جملته. وأن نُثبت أنّنا سمعنا هو **كلُّ الفرق** بين حدٍّ صادقٍ واعتذار.
    extra: u => (u.amount != null ? [`وعندك ${u.amount} درهم`] : []),
  },
];

/**
 * **لا يُنطَق بالحدّ إلّا حيث لا باب.**
 *
 *   @param covered هل وجد الكتالوجُ قدرةً حقيقيّةً لهذه الجملة؟ يُمرَّر من
 *          الخارج لأنّ الكتالوجَ ليس شغلَ هذه الطبقة — وهي لا تعرف عنه شيئًا
 *          عمدًا، كي لا تصير حَكَمًا ثانيًا يخالف الأوّل.
 */
export function boundaryFor(raw: string, u: Understanding, covered: boolean): Boundary | null {
  if (covered) return null;
  // خدمةٌ مقروءةٌ تعني أنّ للجملة بابًا في مكانٍ ما — «بغيت نمشي نشري كسوة».
  if (u.service || u.profession || u.problem) return null;
  const t = ` ${NZ(raw)} `;
  for (const d of DOMAINS) {
    if (d.deny.test(t)) continue;
    if (!d.cues.some(c => c.test(t))) continue;
    const bits = [d.name(u), ...(d.extra?.(u) || [])];
    const what = bits.join(' ');
    return { id: d.id, what, say: phrase(raw, what) };
  }
  return null;
}

/**
 * **الصياغةُ تُقال مرّةً كما يقولها إنسان.**
 *
 *   ثلاثةُ أنفاسٍ لا واحد: **يعترف** بما فهم، ثمّ **يصدق** بأنّه لم يُبنَ بعد،
 *   ثمّ **يفتح بابًا** بدل أن يترك صاحبَه واقفًا. والاعترافُ أوّلًا عمدًا —
 *   من سمع «ما كايناش» قبل أن يسمع أنّه فُهم يظنّ أنّه لم يُفهَم.
 *
 *   والاختيارُ **بالنصّ لا بالصدفة**: نفسُ الجملة تُجيب نفسَ الجواب دائمًا
 *   (فلا يحتار من أعادها، ولا يتذبذب اختبار)، وجملتان مختلفتان تسمعان
 *   صياغتَين مختلفتَين — فتبقى حيّةً بلا أن تصير عشوائيّة.
 */
const SHAPES: ((what: string) => string)[] = [
  what => `فهمتك — باغي ${what} 🙂 هادشي مازال ما زدناهش لأمانزين، ولكن سجّلتها. غير قوليا إلا كان شي حاجة أخرى نعاونك فيها.`,
  what => `واضحة: باغي ${what}. ما نكذبش عليك — هاد الخدمة مازالة فطريق الإضافة. سجّلت طلبك، ونخبرك ملّي توجد. شنو زيد كنقدر ندير ليك؟`,
  what => `سمعتك مزيان — ${what}. هادشي مازال ما دخلش لأمانزين حتّى دابا، ولكن طلبك تسجّل. وإلا كنتي محتاج شي حاجة أخرى، أنا هنا.`,
];

/**
 * **الطلبُ يُحصى — لا لأنّه يُبنى، بل لأنّه يُعرَف.**
 *
 *   جملةٌ واحدةٌ رأيٌ، ومائةُ جملةٍ على نفس المجال قرارُ منتَج. وكان هذا
 *   يُبتلَع في «شنو محتاج بالضبط؟» فلا يبلغ أحدًا ولا يُحصى.
 *
 *   ولا يُنشئ شيئًا: يزيد عدّادًا بحالة `pending`. **لا تعلُّمَ ذاتيّ** —
 *   القدرةُ تُبنى بقرار إنسان، والعدّادُ يخبره أين ينظر لا ما يفعل.
 */
export function recordDemand(raw: string, b: Boundary, city?: string): void {
  try {
    if (typeof fetch === 'undefined') return;
    fetch('/api/ai/uncovered', {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, keepalive: true,
      body: JSON.stringify({ kind: b.id, text: raw.trim().slice(0, 200), city, understood: b.what }),
    }).catch(() => { /* بلا شبكة ⇒ يبقى الطلبُ بلا إحصاء، ولا يُكسَر على صاحبه شيء */ });
  } catch { /* noop */ }
}

function phrase(raw: string, what: string): string {
  let h = 0;
  for (const ch of NZ(raw)) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return SHAPES[h % SHAPES.length](what);
}

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { understand, stanceOf } from '../../src/lib/akg/kb';
import { parseNeed } from '../../src/lib/needEngine';
import { abilityFor, ABILITIES } from '../../src/lib/abilities';
import { decideExecution } from '../../src/lib/executionPolicy';

// ============================================================
// **الاتّجاهُ لا يُناقَض — والطالبُ لا يُساق إلى النشر.**
//
//   قِيس فسقطت ستٌّ من ستّ:
//
//       «كنقلب على دار للكراء»   اتّجاه seek  ⇒ PUBLISH_LISTING ⇒ publish
//       «عندي دار للكراء»        اتّجاه offer ⇒ PUBLISH_LISTING ⇒ publish
//
//   الباحثُ والعارضُ يُخرجان **نفسَ الشيء حرفيًّا**. فمن يبحث عن دارٍ ليسكنها
//   يُساق إلى صفحة نشرِ إعلان — والاتّجاهُ مقروءٌ صحيحًا ولا أحدَ يسأله.
//
//   ── وثلاثةُ أعطابٍ لا عطبٌ واحد ──
//   ①  **«شق» داخل «شقة»**: كلُّ شقّةٍ تُقرأ عطبًا ⇒ شكوى ⇒ طلب.
//   ②  عائلةُ البيع كاملةٌ ولا مقابلَ لها في الكراء: «باغي نبيعها» تعمل
//      و«باغي نكريها» لا. حرفٌ واحدٌ يفرّق بين تاجرَين.
//   ③  `INTENT_MAP` لا يعرف الاتّجاه أصلًا.
//   وإصلاحُ ③ وحدَه كان **ينقل** العطبَ لا يزيله: العارضُ يُساق إلى البحث.
// ============================================================

const judge = (s: string) => {
  const u = understand(s) as any;
  const r = parseNeed(s, {} as any) as any;
  const match = abilityFor({ action: u.action, intent: r?.intent, stance: u.stance });
  return { u, match, d: decideExecution(u, match || undefined, false) as any };
};

// ── ① «شق» داخل «شقة» — خامسُ مصارف الكلمة العامّة ────────────
test('**الشقّةُ ليست صدعًا** — وصاحبُها كان يُقرأ باحثًا عنها', () => {
  // `DEFECT` فيه «شق»، و«شقة» تحتويها. فكانت كلُّ جملةٍ فيها شقّةٌ شكوى،
  // والشكوى طلب. و«دار» تنجو لأنّ لا صدعَ في حروفها — ولذلك عاش العطبُ طويلًا.
  for (const s of ['عندي شقة للبيع', 'بغيت نبيع شقة', 'عندي شقة باغي نبيعها']) {
    assert.equal(stanceOf(s), 'offer', `«${s}» — العارضُ يُقرأ طالبًا`);
  }
  assert.equal(stanceOf('بغيت نشري شقة'), 'seek', 'انقلب الطالبُ عارضًا');
});

test('والصدعُ الحقيقيُّ يبقى عطبًا — الحدُّ ليس صممًا', () => {
  // نصفُ الحارس: تشديدُ المطابقة بلا هذا يُنتج الخطأَ المعاكس.
  for (const s of ['عندي شق فالحيط', 'كاين شق فالجدار', 'الحيط فيه شقوق']) {
    assert.equal(stanceOf(s), 'seek', `«${s}» — الصدعُ ما عاد يُقرأ عطبًا`);
  }
  // وأعطابٌ أخرى بلواحقها — العربيّةُ تلحق، فالحدُّ للقصير وحدَه.
  assert.equal(stanceOf('الثلاجة خربانة'), 'seek');
  assert.equal(stanceOf('الماكينة واقفة'), 'seek');
});

// ── ② الضميرُ يعود على المملوك ────────────────────────────────
test('«عندي شقة باغي **نكريها**» عرضٌ لا طلب', () => {
  // عائلةُ البيع مُعلَنةٌ كاملةً («نبيع» تُطابق «نبيعها») ولا مقابلَ لها في
  // الكراء. حرفٌ واحدٌ كان يفرّق بين من يبيع ومن يُكري.
  assert.equal(stanceOf('عندي شقة باغي نكريها'), 'offer');
  assert.equal(stanceOf('عندي محل باغي نكريه'), 'offer');
  assert.equal(stanceOf('كنكري شقق مفروشة'), 'offer');
  // **والشرطُ ملكيّةٌ + ضميرٌ معًا**: «بغيت نكري دار» بلا «عندي» تبقى طلبًا،
  // وهي الصواب — الدارجةُ تستعمل «نكري» للطرفَين، والمكتري أشيعُ.
  assert.equal(stanceOf('بغيت نكري دار'), 'seek', 'صار المكتري مُكريًا');
});

// ── ③ الاتّجاهُ يبلغ القدرة ───────────────────────────────────
test('**الطالبُ يُساق إلى البحث لا إلى النشر**', () => {
  for (const s of ['كنقلب على دار للكراء', 'بغيت شي دار نسكن فيها', 'بغيت شقة للكراء']) {
    const { match, d } = judge(s);
    assert.equal(match?.id, 'SEEK_LISTING', `«${s}» ⇒ ${match?.id}`);
    assert.notEqual(d.dest?.page, 'publish', `«${s}» سِيق إلى صفحة النشر`);
  }
});

test('والعارضُ يُساق إلى النشر — ولم يُنقَل العطبُ إلى الاتّجاه المعاكس', () => {
  // أخطرُ ما في هذا الإصلاح: من ربط الاتّجاه بالوجهة بلا إصلاح ①و② نقل
  // العطبَ — صاحبُ الشقّة يُساق إلى البحث. وسيبدو ناجحًا في خمسٍ من ستّ.
  for (const s of ['عندي دار للكراء', 'بغيت نكري دار ديالي', 'عندي شقة باغي نكريها']) {
    const { match, d } = judge(s);
    assert.equal(match?.id, 'PUBLISH_LISTING', `«${s}» ⇒ ${match?.id}`);
    assert.equal(d.dest?.page, 'publish');
  }
});

test('والقاعدةُ تُقرأ من الكتالوج — لا سطرٌ خاصٌّ بالكراء', () => {
  // إصلاحُ `rent` وحدَه يترك الجذر: أيُّ نيّةٍ تُخرج قدرةَ عرضٍ لمن يطلب
  // تفعل الشيءَ نفسَه. والمقابلُ يُبحَث عنه بنفس الكيان.
  const seekListing = ABILITIES.find(a => a.verb === 'seek' && a.entity === 'listing');
  assert.ok(seekListing, 'لا قدرةَ بحثٍ عن إعلان — والقاعدةُ تحتاج مقابلًا');
  // وحدُّها: **لا يُخترَع بابٌ غيرُ مبنيّ**. كيانٌ بلا مقابلٍ يبقى كما هو.
  const off = abilityFor({ intent: 'create_service', stance: 'seek' });
  assert.ok(off, 'سقطت القدرةُ كلَّها بدل أن تبقى');
});

test('وبلا اتّجاهٍ يبقى الحكمُ كما كان — لا ينكسر مُنادٍ لم يُحدَّث', () => {
  assert.equal(abilityFor({ intent: 'rent' })?.id, 'PUBLISH_LISTING');
  assert.equal(abilityFor({ intent: 'rent', stance: 'unknown' })?.id, 'PUBLISH_LISTING');
});

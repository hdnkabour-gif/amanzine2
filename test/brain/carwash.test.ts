// ============================================================
// من زيارةٍ ميدانيّةٍ لمحلّ غسلٍ في الدار البيضاء.
//
//   عدّد صاحبُ المحلّ خدماتِه: «غسل السيارات، تلميع، طولوري، صباغة،
//   غسل الزرابي، غسل كامل داخلي خارجي، المحرك». وأرجع المحرّكُ **مفهومًا
//   واحدًا** من سبعة. وأسوأ من ذلك، جوابُ الزبون كان **خاطئًا** لا صامتًا:
//
//     «صباغة السيارات»   ⇒ car                     (سيّارة! لا صباغة)
//     «الزربية موسخة»    ⇒ carpet_and_rug_seller   (بائعُ سجّاد لمن يريد غسله)
//     «عندي خدش»         ⇒ اتّجاه offer            (فيُرسَل لينشر إعلانًا)
//     «طولوري» «المحرك»  ⇒ لم يُفهَما أصلًا
//
//   الجوابُ الخاطئ أسوأُ من الصمت: الصمتُ يُسجَّل في search_misses فيُتعلَّم
//   منه، والخطأُ يمرّ صامتًا ويأخذ الإنسانَ إلى مكانٍ لا يريده.
//
//   هذه الحالاتُ مكتوبةٌ كما نطقها الحرفيّ والزبون، لا كما نكتبها نحن.
// ============================================================
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { resolveConcept, resolveConcepts, stanceOf } from '../../src/lib/akg/kb/index';

const id = (s: string) => resolveConcept(s)?.id ?? null;

test('محلٌّ واحدٌ يعدّد خدماتِه ⇒ كلُّها تُستخرَج، لا أوّلُها', () => {
  const OWNER = 'أنا الآن بمحل غسل السيارات وتلميع السيارات، طولوري، صباغة السيارات، '
    + 'غسل الزرابي، غسل كامل للسيارات داخلي خارجي، المحرك';
  assert.equal(stanceOf(OWNER), 'offer');
  const ids = resolveConcepts(OWNER).map(c => c.id);
  for (const want of ['car_wash', 'car_polishing', 'car_painting', 'carpet_cleaning', 'car_body_repair']) {
    assert.ok(ids.includes(want), `«${want}» ضاع من جملةٍ تذكره — الباقي: ${ids.join(', ')}`);
  }
  // مفهومٌ واحدٌ من سبعةٍ يعني ستَّ خدماتٍ لا يجدها أحد.
  assert.ok(ids.length >= 5, `استُخرج ${ids.length} فقط: ${ids.join(', ')}`);
});

test('كلُّ خدمةٍ منفردةً تُفهَم كما نطقها صاحبُها', () => {
  assert.equal(id('غسل السيارات'), 'car_wash');
  assert.equal(id('تلميع السيارات'), 'car_polishing');
  assert.equal(id('طولوري'), 'car_body_repair');       // tôlerie — «طولي» وحدها لا ينطقها أحد
  assert.equal(id('صباغة السيارات'), 'car_painting');  // كانت ⇒ car
  assert.equal(id('غسل الزرابي'), 'carpet_cleaning');  // لم يكن المفهومُ موجودًا
  assert.equal(id('تنظيف المحرك'), 'engine_cleaning'); // ولا هذا
});

test('جُملُ الزبون كما ينطقها — لا كما نكتبها نحن', () => {
  const cases: [string, string, string][] = [
    ['بغيت نغسل الطوموبيل',      'car_wash',        'seek'],
    ['بغيت البوليش',             'car_polishing',   'seek'],
    ['بغيت نلمّع الطوموبيل',     'car_polishing',   'seek'],   // الفعل لا المصدر
    ['بغيت نصبغ باب الطوموبيل',  'car_painting',    'seek'],
    ['المحرك عامر بالزيت',       'engine_cleaning', 'seek'],
    ['الزربية موسخة',            'carpet_cleaning', 'seek'],   // كانت ⇒ بائع سجّاد
    ['عندي خدش فالبارشوك',       'car_body_repair', 'seek'],   // كان الاتّجاه offer
    ['شي واحد يغسل ليا الزرابي', 'carpet_cleaning', 'seek'],
  ];
  for (const [s, want, st] of cases) {
    assert.equal(id(s), want, `«${s}» ⇒ ${id(s)} (المتوقَّع ${want})`);
    assert.equal(stanceOf(s), st, `«${s}» اتّجاهُه ${stanceOf(s)} (المتوقَّع ${st})`);
  }
});

test('«عندي» + عيبٌ شكوى لا عرض — وإلّا أُرسل صاحبُ العطب لينشر إعلانًا', () => {
  for (const s of ['عندي خدش فالبارشوك', 'عندي بوسة فالباب', 'عندي تسرب فالماء', 'عندي كسر فالزاج'])
    assert.equal(stanceOf(s), 'seek', `«${s}» قُرئ ${stanceOf(s)}`);
  // ولا نكسر العرضَ الحقيقيّ: «عندي محل» عرضٌ فعلًا.
  assert.equal(stanceOf('عندي محل ديال الحوايج'), 'offer');
  assert.equal(stanceOf('بغيت نبيع طوموبيل'), 'offer');   // الفعلُ يغلب الأداة
});

test('«شي واحد» طلبٌ — أكثرُ صيغِ الطلب نطقًا، ولم تكن معروفة', () => {
  for (const s of ['شي واحد يصايب ليا الثلاجة', 'شي حد يغسل ليا الزرابي', 'شي مول الطولوري قريب'])
    assert.equal(stanceOf(s), 'seek', `«${s}» قُرئ ${stanceOf(s)}`);
});

test('«سيارات» ليست مغسلة — الاسمُ العامّ يُسمّم كلَّ جملةٍ فيها سيّارة', () => {
  // كان «سيارات» مرادفًا لـcar_wash (بقيّةُ استيرادٍ)، فيُنازع `car` على كلّ
  // جملةٍ تذكر السيّارة، ويحجب المفهومَ الصحيح خلف مطابقةٍ عامّة.
  assert.notEqual(id('صباغة السيارات'), 'car_wash');
  assert.notEqual(id('صباغة السيارات'), 'car');
});

// ── الجردُ الثاني: مفرداتُ الورشة كما تُنطق ────────────────────
// «كاميو · شرطة · ضربة · بارشوك · ليزان · بوليساج · برييون · دريساج ·
//  الكوسانات · بلافون · الموكيط» — لا واحدةَ منها كانت مفهومة.

test('المركبةُ ليست سيّارةً فقط — الشاحنةُ تُغسَل وتُصبَغ أيضًا', () => {
  assert.equal(id('بغيت نغسل الكاميو'), 'car_wash');
  assert.equal(id('بغيت نصبغ الكاميو'), 'car_painting');
});

test('أسماءُ العيوب المنطوقة ⇒ شكوى، لا عرض', () => {
  // «شرطة» و«ضربة» و«طبعة» كانت تُقرأ عرضًا لأنّ «عندي» علامةُ عرض.
  for (const s of ['عندي شرطة', 'عندي ضربة', 'عندي خدشة', 'عندي طبعة فالكوسان'])
    assert.equal(stanceOf(s), 'seek', `«${s}» قُرئ ${stanceOf(s)}`);
  assert.equal(id('عندي شرطة فالباب القدامي ديال الطوموبيل'), 'car_body_repair');
  assert.equal(id('عندي طبعة فالكوسان'), 'car_interior_cleaning');
});

test('أسماءُ الحرفة الفرنسيّة المُدرَجة — بوليساج · برييون · دريساج', () => {
  assert.equal(id('بغيت بوليساج الطوموبيل'), 'car_polishing');       // كانت ⇒ car
  assert.equal(id('بغيت لبرييون للصباغة ديال طوموبيل'), 'car_painting');
  assert.equal(id('بغيت دريساج'), 'car_body_repair');
});

test('«لداخل» خدمةٌ أخرى بثمنٍ آخر — لا غسلًا عامًّا', () => {
  // الترتيبُ في COMPOSITE جزءٌ من المعنى: لو سبقت قاعدةُ الغسل العامّ
  // لابتلعت هذه الجمل، فيُباع للزبون غسلٌ كاملٌ وهو يريد الداخل وحده.
  assert.equal(id('بغيت نغسل غير لداخل'), 'car_interior_cleaning');
  assert.equal(id('بغيت نسبيري لداخل ديال طوموبيل'), 'car_interior_cleaning');
  assert.equal(id('لافاج غير لداخل'), 'car_interior_cleaning');
});

test('الوسخُ طلبُ غسلٍ — «طوموبيل عندي مسخة»', () => {
  assert.equal(id('طوموبيل عندي مسخة'), 'car_wash');
  assert.equal(stanceOf('طوموبيل عندي مسخة'), 'seek');
  assert.equal(id('بغيت نرش طوموبيل'), 'car_wash');   // كانت ⇒ car
});

test('«صباغة» العامّة لا يحتكرها أحد', () => {
  // كانت مرادفًا لـ«صالون حلاقة نسائيّ» و«مستلزمات منزليّة» معًا، فتخطف كلَّ
  // صبّاغِ سيّاراتٍ وجدار. الكلمةُ العامّة تبقى لمن يُقيّدها بمفعولها.
  assert.notEqual(id('صباغة السيارات'), 'women_s_hair_salon');
  assert.notEqual(id('صباغة السيارات'), 'hardware_household_supplies');
  assert.equal(id('صباغة السيارات'), 'car_painting');
});

// ── الغموضُ المعجميّ: كلمةٌ لمعنيَين ──────────────────────────
// سألتُ صاحبَ المحلّ عن «موطور» فأجاب: «يمكن ان يكون دراجة نارية، موطور
// ديال الطوموبيل محرك السيارة». أي أنّ الغموضَ في اللغة لا في قاموسنا —
// وكان المحرّكُ يُخمّن. التخمينُ يأخذ الإنسانَ للمكان الخطأ بلا أثرٍ يُراجَع.
import { understand } from '../../src/lib/akg/kb/index';
const asks = (s: string) => understand(s).ambiguity?.term ?? null;

test('«موطور» بلا قرينةٍ ⇒ سؤال، لا تخمين', () => {
  assert.equal(asks('موطور'), 'موطور');
  assert.equal(asks('بغيت نغسل الموطور'), 'موطور', 'خمّن بدل أن يسأل — قد يكون يريد غسل درّاجته');
  assert.match(understand('موطور').ambiguity!.ask, /درّاجة/);
});

test('القرينةُ تحسم ⇒ لا سؤال', () => {
  assert.equal(asks('الموطور عامر بالزيت'), null);            // زيت ⇒ محرّك
  assert.equal(asks('غسل الموطور ديال الدراجة النارية'), null); // ناريّة ⇒ درّاجة
  assert.equal(id('الموطور عامر بالزيت'), 'engine_cleaning');
});

test('«صباغة» ثلاثيّةُ المعنى — والمفعولُ يحسم', () => {
  assert.equal(asks('بغيت صباغة'), 'صباغه');
  assert.equal(asks('صباغة السيارات'), null);
  assert.equal(id('صباغة السيارات'), 'car_painting');
  assert.equal(id('بغيت نصبغ الدار'), 'painter');     // كانت ⇒ صباغة سيّارة
  assert.equal(id('صباغة الشعر'), 'women_s_hair_salon');
});

test('«نصبغ الباب» غامضةٌ — بابُ طوموبيل ولا بابُ دار؟', () => {
  // كانت تُحسَم تخمينًا لصالح السيّارة. واللفظُ واحدٌ والحرفيّان مختلفان،
  // فالجوابُ الصادقُ سؤالٌ لا نتيجة.
  assert.equal(asks('بغيت نصبغ الباب'), 'نصبغ');
  assert.equal(asks('بغيت نصبغ باب الطوموبيل'), null);
  assert.equal(asks('بغيت نصبغ باب الدار'), null);
});

test('ستيكاج — خدمةٌ ثالثةٌ كشفها جوابُ الحرفيّ عن «برودويات»', () => {
  assert.equal(id('ستيكاج'), 'car_wrapping');
  assert.equal(id('بغيت ستيكاج للطوموبيل'), 'car_wrapping');  // كانت ⇒ car
  assert.equal(id('سطيكاج'), 'car_wrapping');
});

test('الدرّاجةُ الناريّة مركبةٌ قائمة — لا مجرّدَ ميكانيكيّها', () => {
  assert.equal(id('بغيت نشري موطور ديال الدراجة النارية'), 'motorcycle');
});

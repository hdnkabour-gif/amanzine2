import { test } from 'node:test';
import assert from 'node:assert/strict';
import { understand } from '../../src/lib/akg/kb';
import { resolveConcepts } from '../../src/lib/akg/kb/knowledge';
import { matchWord, hitsWord, normArabic } from '../../src/lib/normalize';

// ============================================================
// **أبوابُ الكلمات** — المعرفةُ موجودةٌ والاسمُ الذي ينطقه الناسُ ليس فيها.
//
//   صنفُ عطبٍ يتكرّر: المهنةُ مبنيّةٌ والمشكلةُ مبنيّةٌ والحلُّ مبنيّ — ثمّ
//   لا يبلغها أحدٌ لأنّ الكلمةَ التي يقولها المغربيُّ فعلًا غيرُ مكتوبةٍ في
//   أيّ سطر. فالبناءُ كلُّه يقف خلف بابٍ بلا مقبض.
// ============================================================

const U = (s: string) => understand(s) as any;

test('① **«معلّم» صفةٌ عامّةٌ لا يملكها البنّاء** — وإلّا صار صاحبُ الثلّاجة عندَه', () => {
  // قِيس بجملةٍ كتبها صاحبُ المشروع. والمعرفةُ كانت **سليمةً تمامًا**:
  //   problem: fridge_not_cooling · profession: appliance_repair
  //   ثمّ قلبت كلمةُ «معلم» حقلَ `service` إلى `mason` وحدَه. حقلان في فهمٍ
  //   واحدٍ يتناقضان، والتوجيهُ يقرأ الخاطئَ منهما.
  const u = U('عندي مشكل فالثلاجة بغيت شي معلم');
  assert.equal(u.problem?.id, 'fridge_not_cooling');
  assert.equal(u.profession?.id, 'appliance_repair');
  assert.notEqual(u.service, 'mason', '«معلم» رجعات تقلب المفهومَ لبنّاء');
  // **والحقلان يتّفقان**: مفهومٌ يناقض المهنةَ المقروءةَ في نفس الجملة عطبٌ
  //   لا يظهر في أيّ شاشة — يظهر في وجهةِ إنسان.
  assert.equal(u.service, 'home_appliance_repair');
});

test('② **والبنّاءُ يبقى بنّاءً بأسمائه** — النزعُ لا يعمي', () => {
  // نزعُ الكلمة العامّة يجب ألّا يُحدث صممًا مكانَ الابتلاع — وهو الخطأ
  //   المعاكس الذي وقع سلفًا في حدّ الكلمة.
  //
  //   **ويُفحَص مسارُ المفهوم لا مسارُ المهنة.** كُتب هذا الحارسُ أوّلًا على
  //   `u.profession`، فنجح على حقنه: `professions.ts` قائمةٌ مستقلّةٌ لا
  //   يمسّها `DISOWNED` أصلًا — فكان يحرس بابًا لا يمرّ منه العطب. وقِيس
  //   أنّ «بناي» تصل عبر المهنة وحدَها بلا مفهوم، و«معلم البناء» و«بناء»
  //   تصلان عبر **الاثنَين**؛ فهاتان هما ما يُفحَص.
  for (const s of ['بغيت معلم البناء', 'بغيت بناء']) {
    assert.deepEqual(resolveConcepts(s, 3).map(c => c.id), ['mason'],
      `«${s}» ما بقاتش كتوصل لمفهوم البنّاء — النزعُ عمّى بدل ما يمنع`);
  }
  // وطريقُ المهنة يبقى قائمًا كذلك — بابان لا واحد.
  assert.equal(U('خاصني بنّاي').profession?.id, 'mason');
});

test('③ **الغسّالةُ كانت بلا بابٍ بالكامل** — صمتٌ تامّ', () => {
  // لا مشكلةَ ولا مهنةَ ولا مفهوم. و`appliance_repair` مبنيّةٌ وتُصلح
  //   الغسّالات — الحرفةُ موجودةٌ والاسمُ غيرُ مكتوب.
  for (const s of ['ماكينة الغسيل واقفة', 'الطياشة خربات', 'الغسالة ما كتخدمش']) {
    const u = U(s);
    assert.equal(u.problem?.id, 'washer_broken', `«${s}» بلا مشكلة`);
    assert.equal(u.profession?.id, 'appliance_repair', `«${s}» بلا مهنة`);
  }
});

test('④ **والمكيّفُ كذلك** — «المكيف» وحدَها كانت صامتة', () => {
  assert.equal(U('المكيف ما كيبردش').problem?.id, 'ac_broken');
  assert.equal(U('عندي مشكل فالمكيف').problem?.id, 'ac_broken');
});

test('⑤ **حدُّ الكلمة يبلغ `resolveConcepts`** — «الطوب» داخل «اللابطوب»', () => {
  // كانت تُطابق بـ`src.indexOf(term)` — احتواءً بلا حدّ — بينما `hitsWord`
  //   مبنيّةٌ لهذا منذ زمنٍ وتُستعمَل في مواضعَ أخرى. والقياس: «عندي مشكل
  //   فاللابطوب» ⇒ **بائعُ أقمشة**، لأنّ «الطوب» (القماش) تقع داخل الكلمة.
  const got = resolveConcepts('عندي مشكل فاللابطوب ديالي', 8).map(c => c.id);
  assert.ok(!got.includes('fabric_shop'),
    'رجع الابتلاع: «الطوب» كتنقرا جوّا «اللابطوب» — مطابقةٌ بلا حدّ');
});

test('⑥ **وحدُّ الكلمة يعيش في سطرٍ واحد** — `hitsWord` مبنيّةٌ على `matchWord`', () => {
  // نسختان للقاعدة تنحرفان بصمت. و`matchWord` وُلدت لأنّ `resolveConcepts`
  //   تحتاج **الموضعَ والطول** لتمنع التداخل، و`hitsWord` تُرجع نعم/لا —
  //   فوُسِّعت مرّةً واحدةً بدل أن تُنسَخ بصيغةٍ ثانية.
  const t = normArabic('فالطوموبيل ديالي');
  const m = matchWord(normArabic('طوموبيل'), t);
  assert.ok(m, 'السابقةُ «فال» منعت المطابقة');
  assert.equal(t.slice(m!.at, m!.at + m!.len), 'فالطوموبيل',
    'الطولُ ما كيشملش السابقة — كتبقا حرّةً فيطابقها مصطلحٌ آخر');
  // والنتيجتان لا تفترقان: واحدةٌ تُبنى على الأخرى.
  for (const [term, text] of [['ما', 'الماكلة'], ['ما', 'الما كيهرب'], ['طوب', 'اللابطوب'], ['طوب', 'الطوب ديال الخياطة']]) {
    assert.equal(hitsWord(normArabic(term), normArabic(text)), matchWord(normArabic(term), normArabic(text)) !== null,
      `«${term}» فـ«${text}»: الدالّتان افترقتا`);
  }
  // والابتلاعُ القديمُ يبقى ممنوعًا: «الما» داخل «الماكلة».
  assert.equal(matchWord(normArabic('ما'), normArabic('عندي محل ديال الماكلة')), null);
});

// ============================================================
// **من شاشة صاحب المشروع** — حرفٌ واحدٌ يقلب أبًا يشتري ثوبًا إلى سبّاك.
// ============================================================

test('⑦ **«كسوى» و«كسوة» كلمةٌ واحدة** — والتاءُ المربوطةُ تُكتَب بثلاثة أحرف', () => {
  // اللقطةُ: كتب «بغيت كسوى لبنتي» فأجابه «فهمت أنّك كتقلّب على شي حدّ»
  //   وعرض عليه **«الماء / السباكة»** و«الكهرباء / الضو». والمطبِّعُ يحوّل
  //   `ة⇒ه` و`ى⇒ي`، فصارت كلمتَين في نظر المحرّك وواحدةً في نظر من كتبها.
  const a = U('بغيت كسوى لبنتي'), b = U('بغيت كسوة لبنتي');
  assert.ok(a.service, '«كسوى» ما تقرّاتش — الأبُ غادي يتسّاق لسبّاك');
  assert.ok(/clothing/.test(String(a.service)), `«كسوى» ⇒ ${a.service}`);
  assert.ok(/clothing/.test(String(b.service)));
  assert.deepEqual(resolveConcepts('كسوى', 2).map(c => c.id), resolveConcepts('كسوة', 2).map(c => c.id),
    'الصيغتان تعطيان مفهومَين مختلفَين');
});

test('⑧ **ولا يُخمَّن في المطبِّع** — «عندى» ياءٌ لا تاءٌ مربوطة', () => {
  // جُرّب طيُّ «ى» الأخيرة إلى «ه» في `unifyLetters`، **فأسقطه حارسٌ قائمٌ
  //   فورًا**: «عندى» صارت «عنده» فانقلب «عندي محل ديال الخضرة» إلى `unknown`.
  //   فالقبولُ يعيش في **المطابِق** والمصطلحُ وحدَه يُعلنه؛ وكلامُ الإنسان
  //   لا يُمَسّ. وهذا الاختبارُ يحرس ألّا يعود التخمينُ إلى المطبِّع.
  assert.equal(normArabic('عندى'), normArabic('عندي'), 'المطبِّعُ فرّق ياءً عن ياء');
  assert.notEqual(normArabic('عندى'), normArabic('عنده'),
    '**رجع التخمينُ إلى المطبِّع** — «عندي» صارت «عنده»، وتنقلب جملُ الملكيّة');
  assert.ok(U('عندي محل ديال الخضرة').service, '«عندي محل ديال الخضرة» ما بقاتش تُقرأ');
});

test('⑨ **والمطابِقان يقبلان نفسَ الشيء** — لا نسختان تفترقان', () => {
  // حدُّ الكلمة يعيش في `matchWord` (لكلّ المشروع) وفي `hitsArabic` (بشرطٍ
  //   خاصٍّ بالمصطلح القصير). فالقبولُ مكتوبٌ مرّتَين عمدًا — ويُقاس هنا
  //   أنّهما لا يفترقان، وإلّا شُفي بابٌ وبقي الآخرُ مريضًا.
  for (const [term, text] of [['كسوه', 'بغيت كسوي'], ['كسوه', 'بغيت كسوه'],
    ['مغسله', 'شي مغسلي قريبة'], ['حلاقه', 'بغيت حلاقي']]) {
    assert.ok(hitsWord(term, text), `matchWord ما قبلش «${term}» فـ«${text}»`);
  }
  // ── **والقبولُ في اتّجاهٍ واحدٍ لا اتّجاهَين** ────────────────────
  //   ما ينتهي بـ«ه» يقبل «ي» — لأنّها تاءٌ مربوطةٌ كُتبت «ى». والعكسُ **لا**:
  //   ما ينتهي بـ«ي» ياءُ ملكيّةٍ أو نسبة («ديالي» · «مغربي»)، وقبولُها «ه»
  //   يقلب معناها. وقبولٌ متماثلٌ يبدو أنظفَ ويكسر جملَ الملكيّة كلَّها.
  assert.ok(!hitsWord('ديالي', 'المحل دياله'),
    '**القبولُ صار متماثلًا** — «ديالي» طابقت «دياله»، وتنقلب الملكيّة');
  assert.ok(!hitsWord('سباك', 'بغيت سباكي'), 'القبولُ توسّع لغير التاء المربوطة');
  // ولا يُبتلَع طرفُ الكلمة بأيّ حرف: «كسوه» لا تطابق «كسوا».
  assert.ok(!hitsWord('كسوه', 'بغيت كسوا'), 'القبولُ صار حرفًا حرًّا — يبتلع كلَّ نهاية');
});

test('⑩ **«بيكالة» تُعرَف** — ولا يُسأل عمّا سُمِّي للتوّ', () => {
  // اللقطةُ: «بغيت نبيع بيكالة ديالي» ⇒ «أيّ منتوج؟» — وقد سمّاه للتوّ.
  //   والفهرسُ يحمل «بيكالا» بالألف، والناسُ يكتبونها بالثلاثة. وقبولُ
  //   `[هي]` لا يبلغها: طرفُ المصطلح ألفٌ لا هاء — فالفجوةُ مفرداتٌ لا قاعدة.
  const u = U('بغيت نبيع بيكالة ديالي');
  assert.equal(u.service, 'bicycle', `«بيكالة» ⇒ ${u.service || 'لا شيء'} — غادي يتسّال «أيّ منتوج؟»`);
  assert.deepEqual(resolveConcepts('بيكالة', 2).map(c => c.id), ['bicycle']);
  assert.deepEqual(resolveConcepts('بيكالا', 2).map(c => c.id), ['bicycle'], 'الصيغةُ القديمةُ انكسرت');
});

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { stanceOf, understand } from '../../src/lib/akg/kb';
import { parseNeed } from '../../src/lib/needEngine';

// ============================================================
// المحوران: ماذا يفعل؟ وهل يَعرض أم يطلب؟
//
//   لاحظ المالكُ أدقَّ ملاحظةٍ لغويّةٍ في المشروع كلِّه:
//
//       «بغيت نكري دار»   ⇒ أبحث عن دارٍ لأسكنها
//       «بغيت نكري داري»  ⇒ أعرض داري للكراء
//
//   حرفٌ واحد — ياءُ الملكيّة — يقلب المعنى كلَّه. وكان المحرّكُ يقرأ
//   الاثنتين `rent` بلا فرق.
//
//   والسببُ بنيويّ: محورٌ واحد (`intent`) لا يستطيع أن يحمل ضدَّين. والدارجةُ
//   تحمل محورين مستقلَّين — الفعلَ والموقف. وكان الموقفُ يُحسَب في المحرّك
//   **ثمّ يُرمى** قبل أن يخرج، فلا يعرف من يستقبل النتيجةَ من أمامه.
//
//   ودرسٌ عن القياس نفسِه: أوّلُ قياسٍ لهذه الجُمَل قال «٤٣ من ٤٣ مفهومة».
//   كان يقيس «النيّة ليست unknown» — مقياسٌ لا يستطيع أن يفشل. وحين قِيس
//   الصوابُ المتوقَّع صار الجوابُ **صفرًا من ٢٣**.
// ============================================================

/** [الجملة، النيّة، الموقف] — من كلام المالك نفسِه. */
const CASES: [string, string, string][] = [
  // شراء: يطلب شيئًا
  ['بغيت نشري تلفون',                         'buy',  'seek'],
  ['بغيت كسوة',                               'buy',  'seek'],
  ['كنقلب على سيارة',                         'buy',  'seek'],
  ['خاصني حاسوب',                             'buy',  'seek'],
  ['بغيت كسوة لبنتي عمرها 8 سنين',            'buy',  'seek'],
  ['خاصني لابتوب مستعمل ما يفوتش 3000 درهم',  'buy',  'seek'],
  ['بغيت صباط بثمن مناسب',                    'buy',  'seek'],

  // بيع: يعرض شيئًا
  ['بغيت نبيع طوموبيل',                       'sell', 'offer'],
  ['عندي صالون للبيع',                        'sell', 'offer'],
  ['كنبيع ملابس أطفال',                       'sell', 'offer'],
  ['بغيت نبيع داري',                          'sell', 'offer'],

  // كراء: الفعلُ واحدٌ والموقفُ يحسم
  ['بغيت نكري دار',                           'rent', 'seek'],
  ['بغيت نكري سيارة',                         'rent', 'seek'],
  ['بغيت نكري داري',                          'rent', 'offer'],
  ['عندي دار للكراء',                         'rent', 'offer'],
  ['عندي محل للكراء',                         'rent', 'offer'],
  ['بغيت نكري السيارة ديالي',                 'rent', 'offer'],

  // حِرفيّ: يطلب إنسانًا
  ['بغيت شي واحد يصلح ليا الثلاجة',           'find_pro', 'seek'],
  ['الثلاجة خاسرة',                           'find_pro', 'seek'],
  ['بغيت شي واحد يركب ليا كاميرات',           'find_pro', 'seek'],
  ['بغيت شي واحد يوصلني للرباط',              'find_pro', 'seek'],

  // تعريفٌ بالنفس: يعرض مهنة
  ['أنا سباك',                                'create_service', 'offer'],
  ['أنا كهربائي فكازا',                       'create_service', 'offer'],
];

test('كلُّ جملةٍ من كلام المالك تُقرأ نيّةً وموقفًا صحيحين', () => {
  const wrong: string[] = [];
  for (const [need, wantIntent, wantStance] of CASES) {
    const r = parseNeed(need);
    if (r.intent !== wantIntent || r.stance !== wantStance)
      wrong.push(`«${need}» ⇒ ${r.intent}/${r.stance} (المتوقَّع ${wantIntent}/${wantStance})`);
  }
  assert.deepEqual(wrong, [], `\n  ${wrong.join('\n  ')}`);
});

test('ياءُ الملكيّة تقلب الاتّجاه — «دار» ليست «داري»', () => {
  // جوهرُ الملاحظة. لو سقط هذا وحدَه لعاد صاحبُ الدار يستأجر ما يملك.
  const seek  = parseNeed('بغيت نكري دار');
  const offer = parseNeed('بغيت نكري داري');
  assert.equal(seek.intent, offer.intent, 'الفعلُ يجب أن يبقى واحدًا');
  assert.equal(seek.stance, 'seek');
  assert.equal(offer.stance, 'offer', 'الياءُ لم تُقرأ — صاحبُ الدار سيُرسَل ليستأجر');
  assert.notEqual(seek.page ?? seek.url, offer.page ?? offer.url,
    'الوجهةُ واحدةٌ رغم اختلاف الموقف');
});

test('«ديالي» و«ديالنا» تعملان كما تعمل الياء', () => {
  for (const t of ['بغيت نكري السيارة ديالي', 'عندي المحل ديالنا للكراء'])
    assert.equal(parseNeed(t).stance, 'offer', `«${t}» تُقرأ طلبًا وهي عرض`);
});

test('الموقفُ يخرج مع النتيجة — لا يُحسَب ثمّ يُرمى', () => {
  // كان يُحسَب في المحرّك ويُستعمل في القواعد ثمّ يُسقَط قبل الخروج.
  for (const t of ['بغيت نبيع طوموبيل', 'خاصني سباك', 'أنا نجار'])
    assert.ok(['offer', 'seek', 'unknown'].includes(parseNeed(t).stance as string),
      `«${t}» تخرج بلا موقف`);
});

test('قاعدةُ المشكلة لا تُطلَق على من يَعرض', () => {
  // «أنا كهربائي فكازا» كانت تُقرأ **عُطلًا كهربائيًّا عاجلًا**، فيُستقبَل
  // الحرفيُّ الذي يعرّف بنفسه بشاشةِ طوارئ. صنفٌ لا حالة.
  for (const t of ['أنا كهربائي فكازا', 'أنا سباك فالرباط']) {
    const r = parseNeed(t);
    assert.notEqual(r.intent, 'urgent', `«${t}» ⇒ طوارئ`);
    assert.equal(r.stance, 'offer');
  }
});

test('كلمةُ الإعلان تسبق كلمةَ المهنة', () => {
  // «عندي محل للكراء» كانت تُقرأ تعريفًا بالنفس («عندي محل» علامةُ صاحبِ
  // نشاط) فيُساق من يريد كراءَ محلِّه إلى إعداداتِ متجر.
  const r = parseNeed('عندي محل للكراء');
  assert.equal(r.intent, 'rent');
  assert.notEqual(r.intent, 'create_store');
  assert.notEqual(r.intent, 'create_service');
});

test('الطلبُ لشيءٍ شراءٌ، لا بحثٌ عن حِرفيّ', () => {
  // «بغيت كسوة» كانت `find_pro`: «بغيت» طلبٌ، ولا قاعدةَ تقول إنّ الكسوةَ
  // شيءٌ لا إنسان — فيُساق من يريد ثوبًا إلى قائمة الصنّاع.
  for (const t of ['بغيت كسوة', 'خاصني حاسوب', 'بغيت صباط'])
    assert.equal(parseNeed(t).intent, 'buy', `«${t}» تُقرأ بحثًا عن حِرفيّ`);
});

test('وصفُ عطبٍ طلبٌ ولو بلا «عندي»', () => {
  for (const t of ['الثلاجة خاسرة', 'التلفاز ما خدامش', 'الطوموبيل واقفة'])
    assert.equal(parseNeed(t).stance, 'seek', `«${t}» بلا اتّجاه`);
});

test('مَن طلب خدمةً طلب إنسانًا — قاعدةٌ لا قائمة', () => {
  // **قياسٌ كشف تناقضًا:** «كنقلب على ميكانيكي» ⇒ `buy` بينما «كنقلب على
  // سباك» ⇒ `find_pro`. السببُ أنّ الحسمَ كان بقائمةِ أسماءِ أشخاصٍ مكتوبةٍ
  // بيدٍ لا تعرف «ميكانيكي»، والمعرفةُ تعرفه خدمةً منذ البداية.
  // (الكهرباءُ استُثنيت عمدًا: «كهربائي» لها مسارُ طوارئَ قائمٌ يسبق هذا —
  //  `urgent` — وهو سلوكٌ مقصودٌ لا عطب. الحارسُ لا يُصحَّح بكسر ما يعمل.)
  for (const q of ['كنقلب على ميكانيكي', 'كنقلب على سباك', 'كنقلب على مدرس دعم', 'بغيت ميكانيكي'])
    assert.equal((parseNeed(q) as any).intent, 'find_pro', `«${q}» ⇒ ${(parseNeed(q) as any).intent}`);
  // والسلعةُ تبقى سلعة: القاعدةُ لم تبتلع الحالةَ الأخرى.
  assert.equal((parseNeed('كنقلب على طوموبيل') as any).intent, 'buy');
});

// ============================================================
// **الصيغةُ المجرّدة كما الانعكاسيّة.**
//
//   قِيس على المدوّنة: «الماكينة ديال الخياطة **خربات**» تُقرأ بلا اتّجاه
//   بينما «الطوموبيل **تخربقات**» تُقرأ شكوى. وهما كلمةٌ واحدةٌ بصيغتَين،
//   والمغربيُّ يقول المجرّدةَ أكثر. فشكوى تُقرأ بلا اتّجاه ⇒ لا يعرف المحرّكُ
//   أنّ صاحبَها **يطلب** إصلاحًا، فيُعامَل معاملةَ مستفسِرٍ عابر.
// ============================================================
test('العطبُ بصيغته المجرّدة شكوى — كما بالانعكاسيّة', () => {
  for (const q of ['الماكينة ديال الخياطة خربات', 'الثلاجة خربات', 'الشاشة تهرست', 'الغسالة وقفات']) {
    assert.equal(stanceOf(q), 'seek', `«${q}» شكوى تُقرأ بلا اتّجاه`);
  }
  // والانعكاسيّةُ لم تنكسر.
  assert.equal(stanceOf('الطوموبيل تخربقات'), 'seek');
});

test('ولا تبتلع الكلمةُ الجديدةُ عرضًا صحيحًا', () => {
  // «خربات» و«طاحت» و«وقفات» أفعالٌ شائعة. لو أطلقناها على كلّ جملةٍ لقلبت
  // بائعًا طالبًا. الحدُّ: تُقرأ شكوى، ولا تمسّ من صرّح بحرفته.
  assert.equal(stanceOf('عندي محل ديال الخضرة'), 'offer');
  assert.equal(stanceOf('أنا خضار'), 'offer');
  assert.equal(stanceOf('كنبيع كسيوات ديال الدراري'), 'offer');
});

test('**والمجهولُ يبقى مجهولًا حين يكون هو الصواب**', () => {
  // النفيُ والصيغةُ التي لا تُلزم: `unknown` ليست إخفاقًا بل الجوابَ الذي
  // يوجبه الدستور. من نفى لم يقل ماذا يريد، ومن أخبر عن ماضٍ لم يطلب شيئًا.
  // وتخمينُ اتّجاهٍ هنا يسوق صاحبَ الجملة إلى صفحةٍ لم يطلبها.
  assert.equal(understand('ماشي بغيت نبيع طوموبيل').stance, 'unknown');
  assert.equal(understand('بعت قميص البارح').stance, 'unknown');
});

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { priceCeiling, readAmount, toAsciiDigits } from '../../src/lib/money';
import { expandQuery, toSearchParams } from '../../src/lib/searchIntent';
import { parseNeed } from '../../src/lib/needEngine';

// ============================================================
// **السقفُ يصل إلى المرشِّح** — النصفُ الثاني الذي كان مفقودًا.
//
//   `/api/search` يقبل `priceMax` منذ كُتب، و`applyFilters` يطبّقه. والجملةُ
//   «بغيت سباط بأقلّ من ٢٠٠ درهم» كانت تُقرأ ميزانيّةً **نصًّا للعرض** ثمّ
//   تُهمَل. فيُقال للإنسان «فهمنا: ميزانيّة ٢٠٠» ثمّ يُعرَض عليه ما ثمنُه
//   ألفان — وهو أسوأُ من ألّا نفهم: فهمٌ مُعلَنٌ لا يُعمَل به.
// ============================================================

// ── ① قراءةُ المبلغ ───────────────────────────────────────────
test('الأرقامُ الهنديّةُ تُقرأ — كانت غيرَ مرئيّةٍ لكلّ قارئ', () => {
  // كلُّ قارئي المال في المشروع كانوا يستعملون `\d` وحدَها، ولوحةُ المفاتيح
  // العربيّةُ تكتب «٢٠٠». فمن كتب ميزانيّتَه بالعربيّة لم يكن له ميزانيّة.
  assert.equal(toAsciiDigits('٢٠٠٠'), '2000');
  assert.equal(readAmount('بغيت سباط ب ٢٠٠ درهم'), 200);
  assert.equal(priceCeiling('بغيت بيكالا متفوتش ٢٠٠٠ درهم'), 2000);
});

test('التشكيلُ لا يُعمي السقف', () => {
  // «بأقلّ من» — بشدّةٍ على اللام — سقطت في أوّل قياس. وهي الصيغةُ الفصيحةُ
  // التي تُكتب بها الجملةُ في التسليم نفسِه.
  assert.equal(priceCeiling('عطيني سباط بأقلّ من 200 درهم'), 200);
  assert.equal(priceCeiling('بأقل من 200 درهم'), 200);
});

test('الفواصلُ والنقطُ في المبلغ لا تقصمه', () => {
  assert.equal(readAmount('بغيت سباط ب 10.000 درهم'), 10000);
  assert.equal(readAmount('بغيت سباط ب 10,000 درهم'), 10000);
});

// ── ② سقفٌ أم ثمنٌ مطلوب — الفرقُ ليس لغويًّا ─────────────────
test('**من يبيع لا يُصفّى له بحثٌ بثمنِ سلعته**', () => {
  // «نبيع سباط ب ٥٠٠ درهم»: الخمسُمئة ثمنٌ **يُعرَض**، لا ميزانيّةٌ تُصفّى
  // بها النتائج. ولو صارت سقفًا لرأى العارضُ نصفَ السوق محجوبًا عنه.
  assert.equal(priceCeiling('بغيت نبيع سباط ب 500 درهم'), undefined);
  assert.equal(priceCeiling('شقة للكراء ب 3000 درهم'), undefined);
  // والمبلغُ نفسُه يبقى مقروءًا — الصمتُ في السقف لا في القراءة.
  assert.equal(readAmount('بغيت نبيع سباط ب 500 درهم'), 500);
});

test('الموديلُ ليس سقفًا — والرقمُ المجرّدُ لا يُتَّخذ ثمنًا', () => {
  // «طوموبيل موديل 2015»: رقمٌ بلا عملةٍ ولا عبارةِ سقف. ولو قُرئ سقفًا
  // لاختفت كلُّ سيّارةٍ ثمنُها فوق ٢٠١٥ درهمًا — أي كلُّ السيّارات.
  assert.equal(priceCeiling('بغيت طوموبيل موديل 2015'), undefined);
  assert.equal(readAmount('بغيت طوموبيل موديل 2015'), undefined);
  // وحين يُذكر السقفُ صراحةً يُؤخَذ هو، لا السنة.
  assert.equal(priceCeiling('بغيت طوموبيل موديل 2015 بأقل من 50000 درهم'), 50000);
});

test('صيغُ السقف التي يقولها المغربيّ', () => {
  const at = (s: string) => priceCeiling(s);
  assert.equal(at('بغيت بيكالا متفوتش 2000 درهم'), 2000);
  assert.equal(at('بغيت بيكالا ماتفوتش 2000 درهم'), 2000);
  assert.equal(at('بغيت تلفون فحدود 1500 درهم'), 1500);
  assert.equal(at('بغيت سباط ماكس 300'), 300);
  assert.equal(at('bghit sbat moins de 300 dh'), 300);
});

test('وما لا ثمنَ فيه لا يُخترَع له ثمن', () => {
  assert.equal(priceCeiling('بغيت سباك'), undefined);
  assert.equal(priceCeiling(''), undefined);
  assert.equal(readAmount('بغيت سباك مستعجل'), undefined);
});

// ── ③ الوصلُ إلى الطلب — الجزءُ الذي كان مقطوعًا ───────────────
test('**السقفُ يُرسَل إلى الخادم رقمًا**', () => {
  const p = toSearchParams(expandQuery('بغيت سباط بأقل من 200 درهم'), 'الدار البيضاء');
  assert.equal(p.get('priceMax'), '200',
    'الميزانيّةُ تُقرأ ولا تُرسَل — المرشِّحُ قائمٌ في الخادم ولا شيءَ يوصله');
  assert.equal(p.get('city'), 'الدار البيضاء');
});

test('والسقفُ لا يتعلّق بفهم المفهوم', () => {
  // «شي حاجة» لا مفهومَ لها، والميزانيّةُ مفهومةٌ تمامًا. وربطُ الثاني
  // بالأوّل يُسقطه لعجزٍ ليس فيه.
  const intent = expandQuery('بغيت شي حاجة بأقل من 100 درهم');
  assert.equal(intent.concept, undefined, 'الاختبارُ نفسُه فقد شرطَه: صار المفهومُ يُفهَم');
  assert.equal(intent.maxPrice, 100, 'سقطت الميزانيّةُ لأنّ المفهومَ لم يُفهَم');
  assert.equal(toSearchParams(intent).get('priceMax'), '100');
});

test('وبلا سقفٍ لا يُرسَل مفتاحٌ فارغ', () => {
  // مفتاحٌ فارغٌ أخطرُ من غيابه: `+'' || 0` تجعله سقفًا **بصفر**.
  const p = toSearchParams(expandQuery('بغيت سباك'), 'الرباط');
  assert.equal(p.has('priceMax'), false);
});

test('والعارضُ لا يُرسَل له سقف', () => {
  const p = toSearchParams(expandQuery('بغيت نبيع سباط ب 500 درهم'));
  assert.equal(p.has('priceMax'), false, 'ثمنُ سلعةِ البائع صار سقفًا يُصفّى به بحثُه');
});

// ── ④ ما يُعرَض هو ما يُرشَّح به ───────────────────────────────
test('الميزانيّةُ المعروضةُ والسقفُ المُرسَلُ رقمٌ واحد', () => {
  // كانا تعبيرَين متقاربَين لا متطابقَين. واختلافُهما لا يظهر خطأً — يظهر
  // نتائجَ لا تطابق ما قيل للإنسان إنّه فُهم عنه.
  for (const s of ['بغيت سباط بأقل من 200 درهم', 'بغيت بيكالا متفوتش 2000 درهم', 'بغيت تلفون فحدود 1500 درهم']) {
    const shown = (parseNeed(s, {}) as any).object?.budget;
    const sent = expandQuery(s).maxPrice;
    assert.equal(shown, `${sent} درهم`, `«${s}» — يُعرَض «${shown}» ويُرشَّح بـ${sent}`);
  }
});

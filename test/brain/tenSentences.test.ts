import { test } from 'node:test';
import assert from 'node:assert/strict';
import { understand } from '../../src/lib/akg/kb';
import { parseNeed } from '../../src/lib/needEngine';
import { decideExecution } from '../../src/lib/executionPolicy';
import { abilityFor } from '../../src/lib/abilities';
import { readAction } from '../../src/lib/akg/kb/actions';

// ============================================================
// **عشرُ جملٍ من صاحب المشروع** — طلب قياسَ التفكيك والتحليل والاستنتاج
// والفهم والجواب المناسب والطريق التي يريدها.
//
//   القياسُ الأوّل: **٣ صحيحة · ١ مقبولة · ٦ خاطئة**. وأربعةُ أعطابٍ
//   مختلفةِ الصنف ظهرت — لا صنفٌ واحد:
//     ① **يعرف ثمّ يسأل**: «بثمن مناسب ٥٠ درهم» ⇒ «بشحال؟». الرقمُ مقروءٌ
//        في `readAmount` منذ زمنٍ ولا يبلغ الحَكَم.
//     ② **كلمةٌ بمعنيَين**: «منتوج **آخر**» تُقرأ إشارةً إلى آخِر منتوج —
//        فيُساق مَن أراد إضافةً إلى تعديلِ ما عنده.
//     ③ **مفرداتٌ غائبة**: «الميناج» · «تخمل» · «بارطاجي».
//     ④ **القناةُ تُقرأ هدفًا**: «بارطاجي هدشي فالفيسبوك» ⇒ «شنو نوع النشاط؟»
// ============================================================

const judge = (s: string) => {
  const u = understand(s) as any;
  const r = parseNeed(s, {} as any) as any;
  const match = abilityFor({ action: u.action, intent: r?.intent });
  return { u, match, d: decideExecution(u, match || undefined, false) };
};

test('**الثمنُ المذكورُ لا يُسأل عنه** — «يعرف ثمّ يسأل» في أوضح صوره', () => {
  const s = 'بغيت نبيع كسوة لونها أزرق ديال البنيتات الصغار 5 سنين حتال 7 سنين بثمن مناسب 50 درهم';
  const { u, d } = judge(s);
  assert.equal(u.amount, 50, 'المبلغُ لا يبلغ `Understanding` — فلا يستطيع الحَكَمُ طرحَه');
  assert.ok(!/بشحال/.test(d.say), `قال «${d.say}» وقد ذكر الثمنَ في الجملة نفسِها`);
  assert.equal(d.verdict, 'execute');
  // وما لم يُذكَر يبقى مسؤولًا عنه — الطرحُ لا يعني الصمت.
  assert.match(judge('بغيت نبيع كسوة ديال الدراري').d.say, /بشحال/, 'صار يُنفَّذ بيعٌ بلا ثمن');
});

test('«منتوج آخر» غيرُ «آخر منتوج» — والفارقُ ما بعدَ الكلمة', () => {
  // مجرّدةٌ تُنهي العبارةَ ⇒ «واحدٌ غيرُه». ومجرّدةٌ يليها اسمٌ، أو معرّفةٌ
  // ⇒ إشارةٌ إلى واحدٍ بعينه.
  assert.equal(readAction('بغيت نزيد منتوج آخر')?.ref, undefined,
    '«منتوج آخر» تُقرأ إشارةً — فيُساق مَن أراد إضافةً إلى تعديلِ ما عنده');
  assert.equal(readAction('بدّل ليا ثمن آخر منتوج')?.ref, 'last', 'ضاعت إشارةٌ حقيقيّة');
  assert.equal(readAction('مسح المنتوج الأخير')?.ref, 'last', 'المعرّفةُ فقدت إشارتَها');
  assert.equal(readAction('حيد آخر منتوج')?.ref, 'last');
});

test('ومفرداتُ التنظيف والمشاركة صارت مقروءة', () => {
  assert.equal(judge('محتاج شي مرة كدير الميناج تخمل ليا الدار').u.service, 'house_cleaner',
    '«الميناج» و«تخمل» غيرُ معروفتَين — فيُقابَل بـ«شنو محتاج بالضبط؟» وقد قاله');
  const share = judge('بغيت نبارطاجي هدشي فالفيسبوك و انستغرام ديالي');
  assert.equal(share.match?.id, 'SHARE_WORKSPACE', `«بارطاجي» ⇒ ${share.match?.id}`);
  assert.ok(!/نوع النشاط/.test(share.d.say), 'ما زال يُسأل عن حرفته');
});

test('**والقناةُ «أين» لا «ماذا» — مع المشاركة وحدَها**', () => {
  // حدُّ الإصلاح: «بغيت نربط الواتساب» القناةُ فيها هي المقصودةُ نفسُها.
  assert.equal(readAction('بغيت نربط الواتساب ديالي بالحساب')?.object, 'channel',
    'ابتُلع ربطُ القناة في المشاركة — وهما فعلان مختلفان');
  assert.equal(readAction('بغيت نبارطاجي هدشي فالفيسبوك')?.object, 'workspace');
});

test('ولا جملةَ من العشر تُقابَل بـ«ما فهمتش»', () => {
  const TEN = [
    'بغيت نشري شي فران يكون جديد ومايفوتش 800 درهم', 'عندي واحد الماكينة قديمه باغي نبيعها',
    'محتاج شي مرة كدير الميناج تخمل ليا الدار', 'فين وصلات الكوموند ديال مراكش',
    'بغيت نزيد منتوج آخر', 'شحال ثمن التوصيل لمدينة الداخلة',
    'بغيت نبيع كسوة لونها أزرق ديال البنيتات الصغار 5 سنين حتال 7 سنين بثمن مناسب 50 درهم',
    'بغيت نبارطاجي هدشي فالفيسبوك و انستغرام ديالي', 'بغيت نسيفط لبنتي واحد الأمانة',
    'خاسني شي واحد يصايب ليا شراجم بالألمنيوم',
  ];
  const lost = TEN.filter(s => /ما فهمتش/.test(judge(s).d.say));
  assert.deepEqual(lost, [], `جملٌ يُعتذَر عن فهمها:\n  ${lost.join('\n  ')}`);
});

// ============================================================
// **وما لم يُصلَح — مكتوبٌ لا مخفيّ.**
//
//   · «شي **فران** جديد ومايفوتش ٨٠٠ درهم» ⇒ `bakery` (مخبز). و«فران»
//     في الدارجة **آلةٌ** تُشترى و**مخبزٌ** يُقصَد — كلمةٌ لمعنيَين، وهذا
//     بابُ `ambiguity.ts` بعينه: «اسأل ولا تُخمّن». ولم يُطلَق.
//   · «بغيت نسيفط لبنتي واحد **الأمانة**» — «أمانة» طردٌ يُرسَل مع سائق،
//     ولا مفهومَ لها. والفعلُ «نسيفط» مقروءٌ ولا هدفَ له.
//   · «الماكينة **قديمة**» — حالُ السلعة (جديد/مستعمل) لا يُقرأ إطلاقًا،
//     وهو أوّلُ ما يسأل عنه المشتري.
// ============================================================
test('الغموضُ المُعلَن: «فران» ما زالت تُخمَّن ولا تُسأل', () => {
  // يُثبَّت ليُقاس، لا ليُقبَل. ويومَ تُضاف إلى `ambiguity.ts` يُقلَب هذا
  // الاختبارُ فيحرس السؤالَ بدل أن يشهد على التخمين.
  const { u } = judge('بغيت نشري شي فران يكون جديد ومايفوتش 800 درهم');
  assert.equal(u.ambiguity, undefined, 'أُضيف الغموضُ — اقلب هذا الاختبار');
  assert.equal(u.service, 'bakery', 'تغيّر التخمينُ — أعِد القياس');
});

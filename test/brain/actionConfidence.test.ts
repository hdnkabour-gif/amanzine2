import { test } from 'node:test';
import assert from 'node:assert/strict';
import { understand } from '../../src/lib/akg/kb';
import { readHuman } from '../../src/lib/humanIntent';
import { parseNeed } from '../../src/lib/needEngine';
import { decideExecution } from '../../src/lib/executionPolicy';
import { abilityFor } from '../../src/lib/abilities';

// ============================================================
// **يعرف ثمّ يسأل — «موتُ السحر» في موضعٍ لم يُفحَص.**
//
//   خطوةُ الثقة كانت تقرأ `u.confidence` وحدَه، وهو ثقةُ **المفهوم**:
//   «أيُّ شيءٍ في الدنيا يتكلّم عنه؟». وللفعل الإداريّ لا مفهومَ أصلًا.
//
//     «بغيت نشوف الكوموند ديالي فين وصلات»
//        مفهوم ٠٫٢٠ · فعل `view/orders` ٠٫٨٥ · قدرة `VIEW_ORDERS` ⇒ orders
//        ⇒ «ما فهمتش مزيان — تقدر توضّح ليا بجملة أخرى؟»
//
//   قرأ الفعلَ قراءةً تامّة، وطابق قدرةً، وعرف البابَ — ثمّ اعتذر.
//
//   ── وحدُّ الإصلاح ──
//   الثقةُ ترتفع **فقط** حين تكون قدرةٌ مطابقةً جاءت من فعلٍ مقروء. ولا
//   تُمَسّ عتبةُ الخطورة: ما لا يُسترجَع يبقى مغلقًا مهما بلغ اليقين، وسؤالُ
//   النقص يقع قبل الثقة فلا يُنفَّذ فعلٌ ناقصُ المفعول.
// ============================================================

const judge = (s: string) => {
  const u = understand(s) as any;
  const r = (readHuman(s) ?? parseNeed(s)) as any;
  const match = abilityFor({ action: u.action, intent: r?.intent });
  return { u, match, d: decideExecution(u, match || undefined, false) };
};

test('فعلٌ مقروءٌ بيقينٍ + قدرةٌ مطابقة ⇒ لا يُقال «ما فهمتش»', () => {
  for (const s of [
    'بغيت نشوف الكوموند ديالي فين وصلات',
    'بغيت نشوف الزبناء ديالي',
    'بغيت نشوف الرصيد ديالي',
  ]) {
    const { u, match, d } = judge(s);
    assert.ok(match, `«${s}»: لم تُطابَق قدرةٌ أصلًا — سبرٌ في غير موضعه`);
    assert.ok((u.action?.confidence ?? 0) >= 0.8, `«${s}»: الفعلُ نفسُه لم يُقرأ بيقين`);
    assert.equal(d.verdict, 'execute',
      `«${s}» ⇒ ${d.verdict}: «${d.say}» — قُرئ الفعلُ وطُوبقت القدرةُ ثمّ اعتُذر عن الفهم`);
  }
});

test('**ولا يُوسَّع البابُ لغير ذلك** — جملةٌ بلا فعلٍ تبقى كما كانت', () => {
  // حارسُ الاتّجاه المعاكس: لو رُفعت الثقةُ بلا شرط الفعلِ والقدرة لصار
  // كلُّ غامضٍ منفَّذًا. «مسح المنتوج ديال طنجة» لا فعلَ فيها ولا قدرة.
  for (const s of ['مسح المنتوج ديال طنجة', 'شي وحدة تسيق ليا الدار']) {
    const { d } = judge(s);
    assert.notEqual(d.verdict, 'execute', `«${s}» صارت تُنفَّذ وهي غامضة`);
  }
});

test('وعتبةُ الخطورة فوقَ الثقة — الفعلُ اليقينُ لا يفتح الحذف', () => {
  // `CHANGE_PHONE` و`DELETE_WORKSPACE` يُقرأ فعلُهما عند ٠٫٧٠–٠٫٨٥، وهو
  // فوقَ كلّ عتبةٍ عاديّة. ولو تبعت الخطورةُ الثقةَ لنُفِّذ الحذفُ بلا تأكيد.
  for (const s of ['بغيت نبدل رقم الهاتف ديالي', 'بغيت نحيد هاد المحل']) {
    const { d } = judge(s);
    assert.notEqual(d.verdict, 'execute',
      `«${s}» ⇒ نُفِّذت بلا تأكيد — فعلٌ لا يُسترجَع`);
  }
});

// ============================================================
// **سؤالُ العدد عرضٌ — والمغربيُّ يسأل بالعدد أكثرَ ممّا يأمر بالعرض.**
//
//   «وريني الطلبات» كانت تُقرأ، و«شحال من طلب عندي» لا تُقرأ إطلاقًا:
//   لا فعلَ ولا قدرة ⇒ «ما فهمتش». وهما طلبٌ واحد.
//
//   ونصفُ العطب في المفعول لا في الفعل: «الطلبات» جمعًا كانت مُعلَنةً
//   و«طلب» مفردًا لا — والمغربيُّ **يُفرد** بعد «شحال من» دائمًا.
// ============================================================
test('«شحال من ⟨شيء⟩» تُقرأ عرضًا كما تُقرأ «وريني ⟨الشيء⟩»', () => {
  for (const [s, want] of [
    ['شحال من طلب عندي', 'VIEW_ORDERS'],
    ['شحال من زبون عندي', 'VIEW_CUSTOMERS'],
  ] as const) {
    const { match, d } = judge(s);
    assert.equal(match?.id, want, `«${s}» ⇒ ${match?.id || 'لا قدرة'}`);
    assert.equal(d.verdict, 'execute', `«${s}» ⇒ ${d.verdict}`);
  }
});

test('**ولا يبتلع المفردُ ما ليس عرضًا** — «بغيت نطلب بيتزا» ليست طلباتي', () => {
  // إضافةُ «طلب» مفردًا خطرُها أن تُقرأ كلُّ جملةٍ فيها الكلمةُ عرضًا
  // لسجلّ الطلبات. والزبونُ الذي يطلب بيتزا لا يريد أن يرى سجلَّ تاجر.
  const { d, match } = judge('بغيت نطلب بيتزا');
  assert.notEqual(match?.id, 'VIEW_ORDERS', 'طلبُ بيتزا صار عرضًا لسجلّ الطلبات');
  assert.notEqual(d.verdict, 'execute', 'نُفِّذ عرضٌ لم يطلبه أحد');
});

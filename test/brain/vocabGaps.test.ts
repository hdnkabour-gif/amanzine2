import { test } from 'node:test';
import assert from 'node:assert/strict';
import { resolveConcept } from '../../src/lib/akg/kb/knowledge';
import { parseNeed } from '../../src/lib/needEngine';
import { collapseRepeats } from '../../src/lib/normalize';

// ============================================================
// مفرداتٌ قالها المالكُ ولم يعرفها التطبيق — ومصرفٌ ومسألةُ مال.
//
//   كلُّها من قياسٍ على جملٍ حقيقيّة، لا من قاموس. وأخطرُها ليس ما جُهل
//   بل ما فُهم **خطأً**: الجهلُ يُسأل عنه، والخطأُ يمضي بالإنسان وهو واثق.
// ============================================================

// ── ① «الروبيني» حنفيّةٌ لا فستان ──────────────────────────────
test('الحنفيّةُ لا تُقرأ فستانًا', () => {
  // «الروب» (فستان) تقع في **أوّل** «الروبيني»، والمطابقةُ الطويلةُ تشترط
  // حدَّ البداية لا النهاية. ولا يجوز اشتراطُ النهاية: العربيّةُ تلحق
  // («حلاقين» · «حلاقة»)، فالتشديدُ يُحدث صممًا مكانَ المصرف.
  //   والعلاجُ معلَنٌ في هذا المشروع منذ البداية: **الفهرسُ يفوز فيه الأطول**.
  for (const q of ['الروبيني', 'عندي مشكل فالروبيني', 'الروبيني كيقطر']) {
    assert.equal(resolveConcept(q)?.id, 'plumber', `«${q}» سِيقت إلى محلّ فساتين`);
  }
  // والفستانُ لم ينكسر — وهذا نصفُ الحارس.
  assert.equal(resolveConcept('بغيت روب للعرس')?.id, 'garment_dress');
});

// ── ② «بيكالا» درّاجةٌ عاديّةٌ لا ناريّة ───────────────────────
test('البيكالا ليست موطورًا — خطأٌ في السلعة وفي الثمن معًا', () => {
  // «بغيت بيكالا متفوتش ٢٠٠٠ درهم» كانت تُقرأ درّاجةً ناريّة: يُعرَض على
  // من عنده ألفان ما ثمنُه عشرون ألفًا.
  assert.equal(resolveConcept('بغيت بيكالا')?.id, 'bicycle');
  assert.equal(resolveConcept('بشكليطة')?.id, 'bicycle');
  assert.equal(resolveConcept('تروتينيت')?.id, 'bicycle');
  // والناريّةُ تبقى ناريّة.
  assert.equal(resolveConcept('بغيت نشري موطور')?.id, 'motorcycle');
  assert.equal(resolveConcept('سكوتر')?.id, 'motorcycle');
});

test('و«موطور» يبقى غامضًا — «بيكالا» ما عادت قرينةً له', () => {
  // كانت «بيكالا» ضمن قرائن الدرّاجة الناريّة في `ambiguity.ts`. وإخراجُها
  // من المفهوم بلا إخراجها من القرائن يترك نصفَ العطب.
  const u = resolveConcept('عندي موطور');
  assert.ok(u, 'سقط «موطور» كلَّه');
});

// ── ③ مفرداتٌ كانت صامتة ──────────────────────────────────────
test('«تسيق» تنظيفُ بيتٍ — أشيعُ ما يُطلَب به', () => {
  assert.equal(resolveConcept('بغيت شي وحدة تسيق ليا الدار')?.id, 'house_cleaner');
  assert.equal(resolveConcept('تنظيف الدار')?.id, 'house_cleaner');
});

test('«لابرييون» بأداة التعريف الفرنسيّة الملتصقة', () => {
  // «برييون» وحدَها كانت تُقرأ، و«لا» ليست من سوابق العربيّة في المطابِق —
  // ولا تُضاف إليها: «لا» أداةُ نفيٍ، وقبولُها سابقةً يفتح مصارفَ لا تُحصى.
  assert.equal(resolveConcept('كندير لابرييون')?.id, 'car_painting');
  assert.equal(resolveConcept('كندير البرييون')?.id, 'car_painting');
});

test('وما كان يعمل لم ينكسر', () => {
  // «طولي» و«برييون» كانتا مُعلَنتَين ناقصتَين في تسليمٍ سابق — والقياسُ
  // يقول إنّهما تعملان. الحارسُ يمنع أن يُهدَم ما ظُنّ مفقودًا.
  assert.equal(resolveConcept('طولي')?.id, 'auto_body_paint');
  assert.equal(resolveConcept('برييون')?.id, 'car_painting');
  assert.equal(resolveConcept('لافاج')?.id, 'car_wash');
});

// ── ④ الأصفارُ تُبتلَع — عطبٌ في مالِ الناس ────────────────────
test('**الألفُ تبقى ألفًا**: التطبيعُ لا يمسّ الأرقام', () => {
  // `collapseRepeats` وُلدت لمدّ الحروف («حلااااق»)، وشملت كلَّ محرف:
  //     ٢٠٠٠  ⇒ ٢٠      ·      ١٠٠٠٠ ⇒ ١٠
  // فمن قال ميزانيّتَه عشرةَ آلافٍ يُعرَض عليه ما ثمنُه عشرة. و«١٥٠٠» تنجو
  // لأنّ أصفارَها اثنان — فالعطبُ يظهر عند الآلاف وحدَها، وهي المبالغُ التي
  // يشتري بها المغربيُّ دراجةً أو هاتفًا أو أثاثًا.
  assert.equal(collapseRepeats('2000'), '2000');
  assert.equal(collapseRepeats('10000'), '10000');
  assert.equal(collapseRepeats('٢٠٠٠'), '٢٠٠٠');
  // ومدُّ الحروف لم ينكسر — وهو ما وُلدت له.
  assert.equal(collapseRepeats('حلااااق'), 'حلاق');
});

test('والميزانيّةُ تصل كما قيلت', () => {
  const bud = (s: string) => (parseNeed(s, {}) as any).object?.budget;
  assert.equal(bud('بغيت بيكالا متفوتش 2000 درهم'), '2000 درهم');
  assert.equal(bud('بغيت سباط ب 10000 درهم'), '10000 درهم');
  assert.equal(bud('بغيت سباط بأقل من 200 درهم'), '200 درهم');
});

// ── ⑤ جملةٌ واحدةٌ تحمل أكثرَ من خدمة ─────────────────────────
//
//   «عندي محل ديال **لافاج** وكندير **ستيكاج** و**البرييون** ومعايا **طولي**»
//   أربعُ خدماتٍ يعيش منها الرجل، وكانت تُختصَر في واحدةٍ ليست حتّى أولاها —
//   فيُسجَّل محلُّه بخدمةٍ واحدة، وتضيع ثلاثةُ أبوابِ رزق.
import { understand } from '../../src/lib/akg/kb';
import { readPersonFacts } from '../../src/lib/personFacts';

const SHOP = 'عندي محل ديال لافاج وكندير ستيكاج والبرييون و معايا طولي';

test('الجملةُ متعدّدةُ الخدمات تُقرأ كلُّها', () => {
  const u = understand(SHOP);
  const ids = u.services || [];
  for (const need of ['car_wash', 'car_wrapping', 'car_painting', 'auto_body_paint']) {
    assert.ok(ids.includes(need), `ضاعت خدمة: ${need} — قُرئ: ${ids.join(' · ')}`);
  }
});

test('والمفردُ لا يُمَسّ — لا ارتدادَ في التوجيه', () => {
  // `resolveConcepts` **أضعفُ من المفرد**: لا تعرف الوعاءَ ولا جدولَ
  // البضائع. فلو حلّت محلَّه لسقطت «عندي محل ديال الخضرة» إلى صفر.
  const u = understand('عندي محل ديال الخضرة');
  assert.equal(u.service, 'greengrocer');
  assert.equal(u.services, undefined, 'خدمةٌ واحدةٌ لا تُعلَن متعدّدة');
  assert.equal(understand(SHOP).service, 'car_painting', 'تغيّر المفهومُ الأوّل');
});

test('والترتيبُ بموضع الكلمة لا بطول المصطلح', () => {
  //   ترتيبُ الجملة : لافاج ⇒ ستيكاج ⇒ برييون ⇒ طولي
  //   ترتيبُ الفهرس : برييون ⇒ ستيكاج ⇒ لافاج ⇒ طولي  (بطول المصطلح)
  //   فالزوجُ الحاسم **لافاج قبل ستيكاج** — وهو وحدَه ينقلب بين الترتيبَين.
  //   وسَبرٌ أوّلُ نزع الفرزَ ومرّ الحارس: كنتُ أقارن «لافاج قبل طولي» وهي
  //   محفوظةٌ في الحالتين. حارسٌ يقارن ما لا يتغيّر لا يحرس شيئًا.
  const ids = understand(SHOP).services || [];
  assert.ok(ids.indexOf('car_wash') < ids.indexOf('car_wrapping'),
    `رُتّبت بطول المصطلح لا بما قاله: ${ids.join(' · ')}`);
});

test('وتُعرَض لصاحبها ليراجعها — لا تُخزَّن صامتة', () => {
  try { localStorage.clear(); } catch { /* noop */ }
  const say = readPersonFacts(SHOP).find(f => f.kind === 'trade')?.say || '';
  assert.match(say, /ومعاها/, 'سُجّل بخدمةٍ واحدةٍ وله أربع');
  for (const w of ['لاڤاج', 'ستيكاج', 'طولي']) {
    assert.ok(say.includes(w), `خدمةٌ لا تُعرَض: ${w} — «${say}»`);
  }
  // ولا مُعرِّفَ تقنيًّا يُعرَض (القانون ١٠).
  assert.ok(!/[a-z_]{4,}/.test(say), `مُعرِّفٌ تقنيٌّ في وجه الإنسان: «${say}»`);
});

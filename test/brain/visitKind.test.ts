import { test } from 'node:test';
import assert from 'node:assert/strict';
import { kindOfConcept, KIND_SAY, ASKS, GOLDEN, missingFor, type VisitKind } from '../../src/lib/visitKind';
import { categoryForConcept } from '../../src/lib/catalog';
import { CONCEPTS } from '../../src/lib/akg/kb/concepts';

// ============================================================
// **صنفُ النشاط في الزيارة الميدانيّة** — يُشتقّ ولا يُسأل.
//
//   القيدُ الذي وُلد منه، بنصّ صاحب المشروع: «صاحبُ محلٍّ أو تاجرٌ أو حرفيٌّ
//   أو مقدّمُ خدمةٍ **لا يمكن أن تأخذ نصفَ ساعةٍ من وقته وهو يشتغل**».
//
//   فكلُّ سؤالٍ يُطرَح يُدفَع ثمنُه من وقت رجلٍ واقفٍ ووراءه زبون. و«واش نتا
//   محلّ ولا حرفيّ؟» سؤالٌ **جوابُه مقروءٌ سلفًا** من جملته — فطرحُه ثمنٌ بلا
//   مقابل.
//
//   وهذه الاختباراتُ تحرس **ثلاثَ قواعدَ مرتَّبة**، وترتيبُها هو الحارسُ لا
//   وجودُها: كلُّ قاعدةٍ منها كُتبت لأنّ القاعدةَ التي بعدها أخطأت مقيسةً.
// ============================================================

const has = (id: string) => (CONCEPTS as any[]).some(c => c.id === id);

test('① **الإصلاحُ يسبق كلَّ شيء** — والكتالوجُ لا يعرف الفرقَ بين تدخّلٍ وموعد', () => {
  // مقيسٌ: `categoryForConcept('plumber').kind === 'service'` و`tv_repair`
  //   ليست في الكتالوج أصلًا. فلو حُذفت قاعدةُ الإصلاح لصار السبّاكُ «خدمةً
  //   بموعد» — وهو يُطلَب **حين يقع عطبٌ** لا حين يختار الإنسانُ موعدًا.
  //   والفرقُ ليس تصنيفًا: صفحةُ الخدمة تعرض «إمتا؟» وصفحةُ الحرفة تعرض
  //   «واش تقدر دابا؟ وشحال الخرجة؟» — فالتصنيفُ الخاطئ **يُخفي ما يُقرِّر**.
  for (const id of ['plumber', 'electrician', 'tv_repair']) {
    assert.ok(has(id), `المفهومُ «${id}» اختفى — الاختبارُ يحرس فراغًا`);
    assert.equal(kindOfConcept(id), 'craft', `«${id}» ماشي حرفة`);
  }
  // وهذا ما يثبت أنّ القاعدةَ هي التي حسمت، لا الكتالوجُ:
  assert.notEqual(categoryForConcept('plumber')?.kind, 'craft',
    'الكتالوجُ صار يعرف الحرفةَ — فالقاعدةُ ①ما بقاتش هي الحاسمة، راجع الاختبار');
});

test('② **والإصلاحُ يسبق البيعَ أيضًا** — «محل اطارات» يبيع ويُصلح، ويُقرَّر بالتدخّل', () => {
  // `tire_shop` نصُّه «بيع الاطارات · اصلاح الثقوب». فالكلمتان حاضرتان معًا،
  //   والترتيبُ وحدَه يفصل. ومن جاء بعجلةٍ مثقوبةٍ لا يشتري إطارًا — يشتري
  //   **تدخّلًا الآن**. فلو سبق البيعُ الإصلاحَ لصارت الصفحةُ شبكةَ منتجات.
  assert.ok(has('tire_shop'), 'المفهومُ «tire_shop» اختفى');
  assert.equal(kindOfConcept('tire_shop'), 'craft',
    'البيعُ سبق الإصلاح — فمن عنده عجلةٌ مثقوبةٌ يُعرَض عليه رفُّ إطارات');
});

test('③ **مَن يبيع سلعةً يسبق الكتالوج** — لأنّ الكتالوجَ يقرأ البقّالَ «خدمة»', () => {
  // العطبُ مقيسٌ لا مُتخيَّل: `categoryForConcept` تختار **قالبَ الاستمارة**
  //   بقاعدةٍ فيها «مَن تعرف قاعدةُ المعرفة ما يفعله ⇒ خدمة». وهي صحيحةٌ
  //   لسؤالها، خاطئةٌ لسؤالنا. وهي **ثالثُ مرّةٍ** أُستعمَل فيها هذه الدالّةُ
  //   لسؤالٍ ليس سؤالَها — ولذلك يُقاس الخطأُ هنا صراحةً بدل أن يُوصَف.
  const shops = ['bakery', 'restaurant', 'butcher', 'greengrocer'];
  for (const id of shops) {
    assert.ok(has(id), `المفهومُ «${id}» اختفى`);
    assert.equal(kindOfConcept(id), 'shop', `«${id}» ماشي محلّ كيبيع`);
    assert.equal(categoryForConcept(id)?.kind, 'service',
      `الكتالوجُ صحّح نفسَه لـ«${id}» — فالقاعدةُ ③ما بقاتش هي الحاسمة، راجع الاختبار`);
  }
  // و«مقهى» ليست في الكتالوج أصلًا: بلا القاعدة ③ تسقط إلى `null`.
  assert.equal(kindOfConcept('cafe'), 'shop', 'المقهى ماشي محلّ');
  assert.equal(categoryForConcept('cafe'), undefined, 'المقهى دخل الكتالوجَ — راجع الاختبار');
});

test('④ **«محل» كلمةُ مكانٍ لا تجارة** — ولو عُدَّت بيعًا لصار غاسلُ السيّارات بقّالًا', () => {
  // «محل» تقع في ستّةَ عشرَ مفهومًا، منها «محل لافاج» و«محل نظارات» و«محل
  //   اثاث». وهي في بعضها تجارةٌ وفي بعضها مكانٌ يُعمَل فيه على شيءٍ تملكه.
  //   فعَدُّها بيعًا يشتري تسعةَ مفاهيمَ صحيحةً بثمن مغسلةٍ تُعرَض رفَّ سلع.
  const wash = 'lavage_automobile_station_de_lavage';
  assert.ok(has(wash), `المفهومُ «${wash}» اختفى`);
  assert.notEqual(kindOfConcept(wash), 'shop',
    '«محل لافاج» صار محلًّا كيبيع — «محل» رجعات لقائمة البيع');
});

test('⑤ **و`null` جوابٌ مشروع** — يُسأل سؤالٌ واحدٌ ولا يُخمَّن', () => {
  // التخمينُ هنا يُنتج صفحةً **تُخفي ما يُقرِّر الشراء** — وهو أغلى من سؤالٍ
  //   واحدٍ يُطرَح. والمقيسُ اليوم: ٢٦ مفهومًا من ٢٠٨ لا تُحسَم، أي واحدةٌ من
  //   كلّ ثمانِ زياراتٍ تدفع سؤالًا زائدًا. وهذا الثمنُ **معلومٌ ومقبول**.
  assert.equal(kindOfConcept('lavage_automobile_station_de_lavage'), null,
    'حُسم بلا دليل — راجع أيَّ قاعدةٍ التقطته');
  assert.equal(kindOfConcept(null), null);
  assert.equal(kindOfConcept('لا_وجود_له'), null, 'مفهومٌ غيرُ موجودٍ ورجع بصنف');

  // وحدُّ الغموض يُقاس ولا يُترَك يزحف: لو تجاوز الثلثَ صار السؤالُ هو القاعدة.
  const nulls = (CONCEPTS as any[]).filter(c => kindOfConcept(c.id) === null).length;
  assert.ok(nulls / (CONCEPTS as any[]).length < 0.25,
    `${nulls} من ${(CONCEPTS as any[]).length} مفهومًا بلا صنف — الاشتقاقُ صار سؤالًا`);
});

test('⑥ **ثلاثةُ أسئلةٍ لكلّ صنفٍ لا رابع** — والرابعُ ثمنُه دقيقةٌ من وقت رجلٍ يشتغل', () => {
  const kinds: VisitKind[] = ['shop', 'craft', 'service'];
  for (const k of kinds) {
    assert.ok(KIND_SAY[k], `«${k}» بلا عبارةٍ تُقال للزائر`);
    const asks = ASKS[k];
    assert.ok(asks?.length, `«${k}» بلا أسئلة`);
    assert.ok(asks.length <= 3,
      `«${k}» فيه ${asks.length} أسئلة — والقيدُ نصفُ ساعةٍ لا تُؤخَذ`);
    // سؤالٌ واحدٌ يمنع الحفظَ لا أكثر: مَن مَنَع بثلاثةٍ منع الزيارةَ كلَّها.
    const req = asks.filter(a => a.required);
    assert.equal(req.length, 1, `«${k}» فيه ${req.length} أسئلةٍ إجباريّة`);
    assert.equal(req[0].kind, 'lines', 'الإجباريُّ خاصّو يكون سطورًا — هو المحصول');
    // ولا سؤالَ بلا نصٍّ بالدارجة يُقرأ كما يُنطَق.
    for (const a of asks) assert.ok(a.q.trim().length > 5, `سؤالٌ فارغٌ في «${k}»`);
  }
  // والأصنافُ تختلف في **ما تسأل عنه** — وإلّا فالتصنيفُ زينةٌ بلا أثر.
  const firsts = kinds.map(k => ASKS[k][0].q);
  assert.equal(new Set(firsts).size, 3, 'صنفان كيسولو نفسَ السؤال — فالصنفُ بلا معنى');
});

test('⑦ **السؤالُ الذهبيّ يُطرَح على الجميع** — وهو أثمنُ ما في الزيارة', () => {
  // جوابُه ليس بيانًا عن محلّ، بل **لغةَ الحرفة كما ينطقها الزبناء**. وخمسُ
  //   لقطاتٍ من الشارع كشفت ما لم تكشفه ستُّمئةٍ وسبعون اختبارًا — لأنّها منه.
  assert.equal(GOLDEN.kind, 'lines');
  assert.ok(!GOLDEN.required, 'الذهبيُّ صار يمنع الحفظ — فمن ما عندوش جوابٌ ما تسجّلش');
  for (const k of ['shop', 'craft', 'service'] as VisitKind[]) {
    assert.ok(!ASKS[k].some(a => a.id === GOLDEN.id),
      `«${GOLDEN.id}» متكرّرٌ في «${k}» — يُسأل مرّتين`);
  }
});

test('⑧ **ما ينقص يُحسَب من مكانٍ واحد** — لا قائمةً ثانيةً في الواجهة', () => {
  assert.deepEqual(missingFor('shop', {}), [ASKS.shop[0].q]);
  assert.deepEqual(missingFor('shop', { top: ['خبز ١٫٢٠'] }), []);
  assert.deepEqual(missingFor('shop', { top: [] }), [ASKS.shop[0].q], 'قائمةٌ فارغةٌ عُدّت جوابًا');
  assert.deepEqual(missingFor('shop', { top: '   ' }), [ASKS.shop[0].q], 'فراغاتٌ عُدّت جوابًا');
  assert.deepEqual(missingFor('craft', { mobile: true }), [ASKS.craft[0].q],
    'جوابُ سؤالٍ اختياريٍّ فتح الحفظَ — والإجباريُّ مازال فارغًا');
});

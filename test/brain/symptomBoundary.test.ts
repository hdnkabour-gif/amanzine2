import { test } from 'node:test';
import assert from 'node:assert/strict';
import { findProblemBySymptom } from '../../src/lib/akg/kb/symptomGraph';
import { understand } from '../../src/lib/akg/kb';
import { readPersonFacts } from '../../src/lib/personFacts';
import { hitsWord } from '../../src/lib/normalize';

// ============================================================
// **أربعةُ أحرفٍ تبتلع بابَين.**
//
//   نمطُ «الما كيهرب» يحمل كلمةَ «الما». وكانت المطابقةُ الجزئيّةُ في
//   `findProblemBySymptom` بالاحتواء (`t.includes(w)`) — فوقعت «الما» داخل
//   «ال**ما**كلة» و«ال**ما**كن»:
//
//     «عندي محل ديال الماكلة كندير طواجن» ⇒ water_leak ⇒ **سبّاك**
//     «الماكن ديال الخياطة خربات»          ⇒ water_leak ⇒ **سبّاك**
//
//   بائعُ الطواجن ومُصلِّحُ ماكينات الخياطة كلاهما سبّاك. وهذا **أسوأُ من
//   الصمت**: الصامتُ يُسأل فيُصحَّح، وهذا يُسجَّل حقيقةً تدوم في `personFacts`.
//
//   وهو نفسُ مصرف الكلمة العامّة الذي هُدم في `merchandise.ts` بحدِّ الكلمة.
//   وبقي هذا البابُ مفتوحًا لأنّ المطابِقَ كان يعيش هناك وحدَه — فصار في
//   `normalize.ts` مصدرًا واحدًا.
// ============================================================

test('كلمةُ العَرَض لا تُطابَق داخلَ كلمةٍ أخرى', () => {
  for (const t of ['الماكلة', 'الماكن', 'عندي محل ديال الماكلة كندير طواجن']) {
    const p = findProblemBySymptom(t);
    assert.equal(p, null,
      `«${t}» أرجعت «${p?.problemId}» — كلمةٌ ابتُلعت داخل كلمة`);
  }
});

test('**والتسرّبُ الحقيقيُّ ما زال يُقرأ** — الإصلاحُ لا يصمّ الأذن', () => {
  // حارسُ الاتّجاه المعاكس: أسهلُ «إصلاحٍ» هو تعطيلُ المطابقة الجزئيّة
  // كلِّها، فتختفي الأخطاءُ وتختفي معها القراءاتُ الصحيحة.
  const leak = findProblemBySymptom('الما كيهرب من الروبيني');
  assert.equal(leak?.problemId, 'water_leak', 'تسرّبٌ صريحٌ لم يعد يُقرأ');
  assert.ok((leak?.confidence ?? 0) >= 0.9, 'المطابقةُ الدقيقةُ فقدت ثقتَها');

  // ومطابقةٌ جزئيّةٌ صحيحةٌ تبقى: «كيخدمش» كلمةُ عطبٍ، والشيءُ يُسمّي الحرفة.
  const fridge = understand('الفريجيدير ديالي ما كيخدمش');
  assert.equal((fridge as any).problem?.id, 'fridge_not_cooling',
    'عطبُ الثلّاجة لم يعد يُقرأ — أُغلقت المطابقةُ الجزئيّةُ كلُّها');
});

test('بائعُ الطواجن ليس سبّاكًا — ولا مُصلِّحُ ماكينات الخياطة', () => {
  const food: any = understand('انا عندي محل ديال الماكلة كندير طواجن في حي البركة الدارالبيضاء');
  assert.equal(food.service, 'restaurant');
  assert.notEqual(food.profession?.id, 'plumber', '**بائعُ الطواجن ما زال سبّاكًا**');
  assert.equal(food.problem, undefined, 'شكوى تسرّبِ ماءٍ في جملةِ تعريفٍ بالنفس');

  const machine: any = understand('الماكن ديال الخياطة خربات');
  assert.notEqual(machine.profession?.id, 'plumber', 'مُصلِّحُ الماكينات ما زال سبّاكًا');
});

test('**والحقيقةُ الدائمةُ لا تُكتَب كاذبة** — هنا يقع الأذى', () => {
  // `personFacts` تكتب ما تقرأ في ذاكرةٍ تدوم. وحقيقةٌ خاطئةٌ تدوم أسوأُ من
  // صفرِ حقائق — يقولها الملفُّ نفسُه.
  const facts = readPersonFacts('انا عندي محل ديال الماكلة كندير طواجن في حي البركة الدارالبيضاء');
  const trade = facts.find(f => f.kind === 'trade');
  assert.ok(trade, 'لم تُقرأ حرفةٌ إطلاقًا');
  assert.equal(trade!.value, 'restaurant');
  assert.ok(!/سبّاك|سباك/.test(trade!.say),
    `يُعرَض عليه «${trade!.say}» وهو صاحبُ مطعم — سيصحّح ما هو صحيحٌ أصلًا`);
});

test('حدُّ الكلمة يسمح بالسوابق المتراكبة — ومنعُها هو الخطأُ المعاكس', () => {
  // كشفه هذا السبرُ نفسُه: النسخةُ الأولى من `hitsWord` تسمح بسابقةٍ **واحدة**،
  // والمغربيُّ يقول «مشكل **فال**طوموبيل» و«**وال**ثلاجة واقفة» — سابقتان.
  // فلو نُقل المطابِقُ كما هو لأُبدِل عطبُ الابتلاع بعطبِ الصمم.
  assert.equal(hitsWord('طوموبيل', 'مشكل فالطوموبيل ديالي'), true, 'السابقتان «ف»+«ال» أسقطتا المطابقة');
  assert.equal(hitsWord('ثلاجه', 'والثلاجه واقفه'), true, 'السابقتان «و»+«ال» أسقطتا المطابقة');
  assert.equal(hitsWord('طوموبيل', 'صيفطها للطوموبيل'), true, 'الإدغامُ «لل» أسقط المطابقة');
  assert.equal(hitsWord('خضره', 'عندي حانوت ديال الخضره'), true, 'السابقةُ «ال» وحدَها أسقطت المطابقة');

  // **والتوسيعُ لا يُعيد الابتلاع**: نهايةُ الكلمة شرطٌ ثانٍ قائم.
  assert.equal(hitsWord('ما', 'الماكله'), false, '**الابتلاعُ عاد بعد توسيع السوابق**');
  assert.equal(hitsWord('الما', 'الماكن ديال الخياطه'), false, 'الابتلاعُ عاد');
  assert.equal(hitsWord('ما', 'فالماكن'), false, 'سابقتان ثمّ ابتلاعٌ — أسوأُ الحالتَين');
});

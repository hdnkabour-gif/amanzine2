import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readCondition } from '../../src/lib/condition';
import { understand } from '../../src/lib/akg/kb';
import { expandQuery, toSearchParams } from '../../src/lib/searchIntent';

// ============================================================
// **حالُ السلعة** — أوّلُ ما يسأل عنه المشتري بعد الثمن.
//
//   جملتان من صاحب المشروع تذكرانه صراحةً:
//     «بغيت نشري شي فران يكون **جديد** ومايفوتش ٨٠٠ درهم»
//     «عندي واحد الماكينة **قديمه** باغي نبيعها»
//   ولم يكن في التطبيق شيءٌ يقرؤه — لا في البحث ولا في النشر.
// ============================================================

test('يُقرأ من الجملة — للمشتري وللبائع', () => {
  assert.equal(readCondition('بغيت نشري شي فران يكون جديد'), 'new');
  assert.equal(readCondition('عندي واحد الماكينة قديمه باغي نبيعها'), 'used');
  assert.equal(readCondition('بغيت طوموبيل دوكازيون'), 'used');
  assert.equal((understand('عندي واحد الماكينة قديمه باغي نبيعها') as any).condition, 'used');
});

test('**ولا يُخمَّن** — سلعةٌ لم يُقَل حالُها ليست جديدةً ولا مستعملة', () => {
  // التخمينُ هنا يصنع وعدًا لا يُوفى في أوّل صفقة.
  for (const s of ['بغيت نبيع كسوة', 'عندي منتوج', 'بغيت سباط بأقل من 200 درهم']) {
    assert.equal(readCondition(s), undefined, `«${s}» خُمِّن حالُها`);
  }
});

test('ونفيُ الصفةِ من اثنتَين يحسم الثانية', () => {
  // «ماشي جديد» تعني مستعملةً بلا لبس — بخلاف «ماشي بغيت نبيع» التي تُبطِل
  // الاتّجاهَ ولا تقول ماذا يريد. نفيُ صفةٍ من اثنتَين ≠ نفيُ فعلٍ من كثير.
  assert.equal(readCondition('بغيت واحد ماشي جديد'), 'used');
});

test('**والحالُ يصل إلى المرشِّح** — لا يُقرأ ويُرمى', () => {
  const p = toSearchParams(expandQuery('بغيت نشري شي فران يكون جديد ومايفوتش 800 درهم'));
  assert.equal(p.get('condition'), 'new', 'الحالُ يُفهَم ولا يُرسَل — نصفُ عملٍ صامت');
  assert.equal(p.get('priceMax'), '800', 'ضاع السقفُ مع إضافة الحال');
  // وما لم يُقَل لا يُرسَل: مرشِّحٌ فارغٌ يُضيّق بلا سبب.
  assert.equal(toSearchParams(expandQuery('بغيت سباط')).get('condition'), null);
});

test('ولا يبتلع كلماتٍ أخرى — حدُّ الكلمة قائم', () => {
  // «جديد» داخل «تجديد» و«الجديدة» (المدينة). والابتلاعُ هنا يُقصي سلعًا
  // مستعملةً من نتائج مَن لم يطلب جديدًا أصلًا.
  assert.equal(readCondition('بغيت تجديد الديكور'), undefined, '«تجديد» قُرئت «جديد»');
  assert.equal(readCondition('أنا من الجديدة'), undefined, '«الجديدة» (المدينة) قُرئت حالَ سلعة');
});

test('**وحدٌّ مُعلَن**: «الجديدة» وحدَها تصمت — مدينةٌ واسمُ صفةٍ في آن', () => {
  // `hitsWord` تسمح بسابقة «ال» بحقّ، و«الجديدة» مدينةٌ مغربيّةٌ كذلك.
  //   فسؤالُ مصدرِ المدن يُسكِت «أنا من الجديدة» — ويُسكِت معها «الماكينة
  //   الجديدة». وهذا **ثمنٌ مدفوعٌ بوعي**: الخسارةُ صمتٌ عن صفةٍ صحيحة،
  //   والربحُ ألّا يُضيَّق بحثُ مَن ذكر مدينتَه. وصمتٌ خيرٌ من تضييقٍ كاذب.
  assert.equal(readCondition('أنا من الجديدة'), undefined, '«الجديدة» المدينةُ قُرئت حالَ سلعة');
  assert.equal(readCondition('عندي محل ف الجديدة'), undefined);
  // والصيغُ الأخرى تعمل كلُّها — الحدُّ على هذه الصيغة وحدَها.
  assert.equal(readCondition('بغيت ماكينة جديدة'), 'new');
  assert.equal(readCondition('بغيت فران جديد'), 'new');
  // وحين تُذكَر المدينةُ مع صفةٍ صريحةٍ يبقى الحالُ مقروءًا: المطابِقُ «جديد»
  // لا اسمُ المدينة.
  assert.equal(readCondition('عندي فران جديد ف الجديدة'), 'new');
});

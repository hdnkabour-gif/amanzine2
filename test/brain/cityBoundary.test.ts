import { test } from 'node:test';
import assert from 'node:assert/strict';
import { cityInText } from '../../src/lib/akg/kb/geo';
import { understand } from '../../src/lib/akg/kb';

// ============================================================
// **مدينةٌ مخترَعة** — رابعُ مواضع مصرفِ الكلمة العامّة.
//
//   قِيس حرفيًّا على جملةٍ كتبها صاحبُ المشروع:
//
//       «Fin wesselat lcomonde deyali»  ⇒  المدينة: **سلا**
//
//   فكُّ الـArabizi يعطي «فين وسسلات لكوموند ديالي»، و«سلا» تقع **داخل**
//   «وسسلات». والرجلُ يسأل عن طردِه، لا عن سلا، ولم يذكرها قطّ.
//
//   ── ولماذا هذه أخطرُ من أخواتها ──
//   المفهومُ الخاطئُ يُصحَّح بجملةٍ ثانية. والمدينةُ الخاطئةُ تفعل شيئَين:
//     ① تُصفَّى بها النتائجُ فلا يجد شيئًا — ولا يعرف لماذا؛
//     ② تُكتَب **حقيقةً تدوم** في ملفّه، فتتبعه في كلّ بحثٍ بعدها.
//
//   والحدُّ يُقرأ من `normalize` ولا يُكتَب نسخةً رابعة: أربعُ نسخٍ تنحرف.
// ============================================================

test('لا تُخترَع مدينةٌ من داخل كلمة', () => {
  assert.equal(cityInText('فين وسسلات لكوموند ديالي'), undefined,
    '«سلا» التُقطت داخل «وسسلات» — مدينةٌ لم تُذكر');
  assert.equal(understand('Fin wesselat lcomonde deyali').city, undefined,
    'المدينةُ المخترَعةُ تعبر إلى الفهم وتُكتَب حقيقةً تدوم');
});

test('والمدينةُ المذكورةُ تبقى مقروءة — الحدُّ ليس صممًا', () => {
  // نصفُ الحارس: تشديدُ الحدّ بلا هذا يُنتج الخطأَ المعاكس — مدينةٌ تُقال
  // ولا تُقرأ، وهي أشيعُ من المخترَعة.
  assert.equal(cityInText('بغيت سباك ف سلا'), 'سلا');
  assert.equal(cityInText('أنا فسلا'), 'سلا', 'السابقةُ الملتصقة «ف» أسقطت المدينة');
  assert.equal(cityInText('بغيت طبيب فالرباط'), 'الرباط');
  assert.equal(cityInText('كنسكن فالدار البيضاء'), 'الدار البيضاء');
  assert.equal(understand('بغيت سباك ف سلا').city, 'سلا');
});

test('ولا مدينةَ حيث لا مدينة', () => {
  assert.equal(cityInText('بغيت سباك مستعجل'), undefined);
  assert.equal(cityInText(''), undefined);
});

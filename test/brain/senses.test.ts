// ============================================================
// **اللفظُ المشترك — لا يُحسَم بالتخمين، ويُسأل عنه بسؤالٍ يخصّه.**
//
//   قِيس قبل هذا العمل، وهذه أرقامٌ لا وصف:
//     «سكانير ديال الوراق»        ⇒ `car_diagnostics` بيقين ٠٨٦ · ٠ أسئلة
//     «سكانير ديال التحاليل»      ⇒ `car_diagnostics` بيقين ٠٨٦ · ٠ أسئلة
//     «بغيت ندير سكانير فالمستشفى» ⇒ `car_diagnostics` بيقين ٠٨٦ · ٠ أسئلة
//     «كنبدل الثوب»               ⇒ `car_upholstery` بيقين **٠٩٠** — فوق
//                                    عتبةِ التنفيذ، فلا سؤالَ ولا تأكيد
//   أي أنّ تمامَ الجملة كان **موجودًا في النصِّ ومُهمَلًا**: الثلاثُ الأولى
//   جوابُها واحد. وأقبحُ منه أنّ «بغيت نبدل الثوب ديال الطوموبيل» كانت
//   تُجيب `car` — فالجملةُ الأدقُّ تُجيب أسوأ.
//
//   وهذه الاختباراتُ **سلوكيّةٌ** (BEHAVIORAL): تمرّ من `parseNeed` و
//   `resolveConcept` كما يمرّ المستخدم، لا تقرأ شكلَ الجدول. وما يقرأ
//   الجدولَ منها معلَّمٌ صريحًا (SOURCE_SHAPE) ولا يقوم وحدَه دليلًا.
// ============================================================
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseNeed } from '../../src/lib/needEngine';
import { resolveConcept } from '../../src/lib/akg/kb/knowledge';
import { CONCEPTS } from '../../src/lib/akg/kb/concepts';
import { CONFIDENCE } from '../../src/lib/clarify';
import { SHARED_WORDS, readSense, MIN_CUE } from '../../src/lib/akg/kb/senses';

const idOf = (t: string) => (resolveConcept(t) as { id?: string } | null)?.id ?? null;

// ── ① الجملةُ إذا اكتملت ⇒ المعنى يُحسَم، ولا سؤال ───────────────
test('**مُكمِّلٌ أصاب ⇒ المعنى حُسِم** — ولا يفوز أطولُ لفظٍ في الفهرس', () => {
  const want: [string, string][] = [
    ['سكانير ديال الوراق', 'cybercafe'],
    ['بغيت نصور وراق فسكانير', 'cybercafe'],
    ['سكانير ديال الطوموبيل', 'car_diagnostics'],
    ['بغيت سكانير للطوموبيل', 'car_diagnostics'],
    // «طوموبيل» أطولُ ممّا يعرفه الفهرسُ هنا، وكانت تسرق الجوابَ لـ`car`.
    ['بغيت نبدل الثوب ديال الطوموبيل', 'car_upholstery'],
    ['بغيت نبدل الثوب ديال الصالون', 'furniture_upholsterer'],
    ['حمام بلدي', 'traditional_hammam'],
    ['بغيت نمشي لحمام بالكيس', 'traditional_hammam'],
    ['حمام رومي', 'hammam'],
    ['بغيت حمام فيه ساونا', 'hammam'],
  ];
  const bad = want.filter(([t, id]) => idOf(t) !== id)
    .map(([t, id]) => `«${t}» ⇒ ${idOf(t)} بدل ${id}`);
  assert.deepEqual(bad, [], 'جملةٌ مكتملةٌ لم تُحسَم لمعناها:\n  ' + bad.join('\n  '));
});

test('**ولا يُسأل عمّا اكتمل** — السؤالُ بعد الجواب إهانة', () => {
  const done = ['سكانير ديال الوراق', 'سكانير ديال الطوموبيل', 'حمام بلدي',
    'حمام رومي', 'بغيت نبدل الثوب ديال الصالون'];
  const asked = done.filter(t => (parseNeed(t).steps?.length ?? 0) > 0);
  assert.deepEqual(asked, [], 'سُئل عن معنًى اكتمل: ' + asked.join(' · '));
});

// ── ② وإذا لم تكتمل ⇒ سؤالٌ يخصّ اللفظ، واليقينُ ينزل ───────────
test('**لفظٌ مشترك بلا مُكمِّل ⇒ سؤالٌ يخصُّه** — لا «شنو بالضبط؟»', () => {
  const cases: [string, string][] = [
    ['سكانير', 'سكانير ديال شنو؟'],
    ['عندي سكانير', 'سكانير ديال شنو؟'],
    ['كنبدل الثوب', 'الثوب ديال شنو؟'],
    ['حمام', 'حمام بلدي ولا رومي؟'],
    ['بغيت حمام', 'حمام بلدي ولا رومي؟'],
  ];
  const bad: string[] = [];
  for (const [t, q] of cases) {
    const r = parseNeed(t);
    const step = r.steps?.[0];
    if (!step) { bad.push(`«${t}» لم يُسأل عنه إطلاقًا`); continue; }
    if (step.q !== q) bad.push(`«${t}» سُئل «${step.q}» بدل «${q}»`);
    if (step.options.length < 2) bad.push(`«${t}» سؤالٌ بخيارٍ واحد`);
  }
  assert.deepEqual(bad, [], 'أسئلةٌ ناقصةٌ أو عامّة:\n  ' + bad.join('\n  '));
});

test('**واليقينُ ينزل دون عتبةِ التأكيد** — وإلّا نفّذ التطبيقُ بلا سؤال', () => {
  // **هذا هو قلبُ الإصلاح.** «كنبدل الثوب» كانت ٠٩٠ = فوق `ACT`، فيُنفَّذ
  //   بلا سؤالٍ ولا تأكيد. واللفظُ المشترك يجب أن **يُنزل** اليقينَ لأنّه
  //   مشترك، لا أن يرفعه.
  const bad: string[] = [];
  for (const t of ['سكانير', 'كنبدل الثوب', 'حمام', 'بغيت حمام', 'عندي سكانير']) {
    const c = parseNeed(t).confidence ?? 1;
    if (c >= CONFIDENCE.CONFIRM) bad.push(`«${t}» يقينُها ${c} ≥ ${CONFIDENCE.CONFIRM}`);
  }
  assert.deepEqual(bad, [], 'لفظٌ مشتركٌ بيقينٍ يمنع السؤال:\n  ' + bad.join('\n  '));
});

// ── ③ الحارسان — مقيسان لا مفترضان ──────────────────────────────
test('**ولا يُسأل في طارئٍ ولا على نيّةٍ إنسانيّةٍ مقروءة**', () => {
  // «الما كيقطر فالحمام» ⇒ `urgent` بيقين ٠٩٧: من ينزف ماؤه لا يُسأل عن
  //   قاموس. و«عندي مشكل فالحمام» تُقرأ `HELP` — ولها سؤالُها، وسؤالان
  //   في نفَسٍ واحدٍ إهانة.
  //
  //   والثانيةُ خاصّةً: الطبقةُ الإنسانيّةُ تتكلّم ثمّ **يُسكِتها** حارسُ
  //   «لا تسأل سؤالًا تعرف جوابه» (لأنّ المجالَ معلوم). فمن قرأ `hr`
  //   رآها صامتةً وسأل — ولذلك يُقرأ `human.intent` نفسُه.
  const quiet = ['الما كيقطر فالحمام', 'عندي مشكل فالحمام'];
  const asked = quiet.filter(t => (parseNeed(t).steps?.[0]?.clarifyId || '').startsWith('sense:'));
  assert.deepEqual(asked, [], 'سُئل عن معنى الكلمة في غير موضعه: ' + asked.join(' · '));
});

test('**و«ثوب» المجرَّدةُ لباسٌ لا تنجيد** — المعنى في العبارة لا الكلمة', () => {
  // قِيس على ٢٥١٠ جملةٍ من المدوّنة: «ثوب» و«الثوب» كلفظٍ مشتركٍ حرّكت
  //   جملةً واحدةً وكانت خطأً — `garment_dress` يملكها بحقّ.
  for (const t of ['بغيت ثوب', 'بغيت ثوب للعيد', 'الثوب غالي']) {
    assert.equal(readSense(t), null, `«${t}» عُدّت لفظًا مشتركًا وهي لباس`);
  }
  // والعبارةُ تُصيب داخلَ سوابقها: «كنبدل» و«نبدل».
  assert.ok(readSense('كنبدل الثوب'), '«كنبدل الثوب» لم تُقرأ لفظًا مشتركًا');
});

// ── ④ الحاسّةُ بلا مفهومٍ تقول الصدق ────────────────────────────
test('**حاسّةٌ بلا مفهومٍ لا تُجيب بمفهومٍ آخر** — `medical_imaging` لا وجودَ له', () => {
  // ما لم يُتحقَّق منه لا يدخل التطبيقَ، لكنّ الفهمَ يُلتقَط: «سكانير ديال
  //   التحاليل» تُفهَم طبّيّةً، ولا تُحَلّ إلى `car_diagnostics` ولا إلى
  //   `cybercafe` — فيُقال الصدقُ بدل أن يُرسَل صاحبُها إلى ميكانيكيّ.
  for (const t of ['سكانير ديال التحاليل', 'سكانير عند الطبيب']) {
    const r = readSense(t);
    assert.equal(r?.decided?.id, 'medical', `«${t}» لم تُقرأ طبّيّة`);
    assert.equal(r?.decided?.concept, null, `«${t}» صارت لها مفهومٌ — إن أُضيف فحدِّث هذا الحارس`);
    const id = idOf(t);
    assert.notEqual(id, 'car_diagnostics', `«${t}» ⇒ ${id} — جوابُ ميكانيكيٍّ لسؤالٍ طبّيّ`);
  }
});

// ── ⑤ سلامةُ الجدول — SOURCE_SHAPE، لا يقوم وحدَه دليلًا ────────
test('[SOURCE_SHAPE] كلُّ مُكمِّلٍ طولُه كافٍ، وكلُّ مفهومٍ موجودٌ أو `null`', () => {
  // مُكمِّلٌ من حرفين يقع داخل عشرات الكلمات بلا معنى — وهو صنفُ العطب
  //   الأشيعُ في هذا المستودع («الما» في «الماكلة»، «دم» في «مدمج»).
  const ids = new Set(CONCEPTS.map(c => c.id));
  const bad: string[] = [];
  for (const w of SHARED_WORDS) {
    const seen = new Set<string>();
    if (!w.question.trim()) bad.push(`«${w.term}» بلا سؤال`);
    if (!w.senses.some(s => s.id === 'other')) bad.push(`«${w.term}» بلا مخرجٍ للإنسان`);
    for (const s of w.senses) {
      if (seen.has(s.id)) bad.push(`«${w.term}» حاسّةٌ مكرّرة: ${s.id}`);
      seen.add(s.id);
      if (s.concept !== null && !ids.has(s.concept)) bad.push(`«${w.term}/${s.id}» ⇒ ${s.concept} — مفهومٌ لا وجودَ له`);
      for (const c of s.cues) if (c.trim().length < MIN_CUE) bad.push(`«${w.term}/${s.id}» مُكمِّلٌ قصير: «${c}»`);
    }
  }
  assert.deepEqual(bad, [], 'جدولُ الحواسِّ فيه خلل:\n  ' + bad.join('\n  '));
});

test('**والمكانُ يُرجِّح ولا يحسم** — «المستشفى» تقول أين لا ماذا', () => {
  // كانت «مستشفى» مُكمِّلًا طبّيًّا، و«أطولُ مُكمِّلٍ يفوز» — فـ«بغيت نصور
  //   وراق فسكانير قريب من المستشفى» كانت تُقرأ طبّيّةً لأنّ «المستشفى»
  //   أطولُ من «وراق»، فيُحرَم صاحبُها من سيبيرٍ موجود.
  const r = parseNeed('بغيت ندير سكانير فالمستشفى');
  assert.equal(r.steps?.[0]?.q, 'سكانير ديال شنو؟',
    'ذكرُ المستشفى حسم المعنى بدل أن يُرجّحه');
  // وذكرُ المستشفى **مع** مُكمِّلٍ حقيقيٍّ لا يسرق الجواب.
  assert.equal(idOf('بغيت نصور وراق فسكانير قريب من المستشفى'), 'cybercafe');
});

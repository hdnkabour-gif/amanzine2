import { test } from 'node:test';
import assert from 'node:assert/strict';
import { understand } from '../../src/lib/akg/kb';
import { parseNeed } from '../../src/lib/needEngine';
import { abilityFor } from '../../src/lib/abilities';
import { decideExecution } from '../../src/lib/executionPolicy';
import { decideInterface } from '../../src/lib/interfaceDecision';
import { boundaryFor } from '../../src/lib/boundary';

// ============================================================
// **«فهمتُك، وهادشي مازال ما كايناش».**
//
//   قِيس على جملةٍ من جملِ القبول: «بغيت نمشي لطنجة» ⇒ الشاشةُ تقول
//   **«شنو محتاج بالضبط؟»**. وقد قال ما يحتاج بالضبط. فالسؤالُ ليس استيضاحًا
//   بل **إخفاءُ عجزٍ في ثوب سؤال**: أيُّ جوابٍ يعطيه لا يجد بابًا، فيُسأل
//   ثانيةً وثالثة — حلقةٌ لا تنتهي، ومخرجُها الوحيدُ أن يملّ ويغلق.
//
//   والقناةُ الثالثةُ التي لم تكن:
//       لم نفهم          ⇒ «ما فهمتش» + نسأل      (`learning_unknowns`)
//       فهمنا غلطًا       ⇒ يردّه صاحبُه            (`learning_misreads`)
//       **فهمنا ولا باب** ⇒ **هنا** — وهي خارطةُ الطريق يكتبها الناس.
// ============================================================

const R = 0.5;
const judge = (s: string) => {
  const u = understand(s) as any;
  const r = parseNeed(s, {} as any) as any;
  const act = (u.action?.confidence ?? 0) >= R ? u.action : null;
  const m = abilityFor({ action: act, intent: r?.intent, stance: u.stance });
  const d = decideExecution(u, m || undefined, false, { raw: s }) as any;
  return { u, d, mode: decideInterface({ ...r, hasInput: true }, d.verdict).mode };
};

// ── ① يُقال، ولا يُسأل سؤالٌ عاجز ──────────────────────────────
test('**طلبُ التنقّل يُفهَم ويُقال له الصدق** — لا «شنو محتاج بالضبط؟»', () => {
  for (const s of ['بغيت نمشي لطنجة', 'بغيت نمشي الحي عندي غير 10 دراهم',
                   'بغيت نسافر لأكادير', 'بغيت طاكسي']) {
    const { d } = judge(s);
    assert.equal(d.verdict, 'soon', `«${s}» ⇒ ${d.verdict}: ${d.say}`);
    assert.doesNotMatch(d.say, /شنو محتاج بالضبط/, `«${s}» مازال يسأل سؤالًا لا جوابَ له`);
  }
});

test('والشكلُ في الواجهة يتبعه — لا حكمَ يُرمى', () => {
  assert.equal(judge('بغيت نمشي لطنجة').mode, 'soon');
});

// ── ② يُثبت أنّه سمع ────────────────────────────────────────────
test('**الاعترافُ قبل الاعتذار** — يُسمّي ما فُهم', () => {
  // من سمع «ما كايناش» قبل أن يسمع أنّه فُهم ظنّ أنّه لم يُفهَم، فأعاد
  // الكتابةَ بصيغةٍ أخرى — وهو نفسُ الملل الذي بُني الحدُّ ليمنعه.
  assert.match(judge('بغيت نمشي لطنجة').d.say, /طنجة/, 'ما ذُكرت الوجهةُ المقروءة');
  assert.match(judge('بغيت نسافر لأكادير').d.say, /أكادير/);
  // والميزانيّةُ مقروءةٌ (١٠) وكانت تُبتلَع — فيسمع الرجلُ كلامًا عامًّا
  // ويظنّ أنّنا لم نقرأ نصفَ جملته.
  const b = judge('بغيت نمشي الحي عندي غير 10 دراهم').d.say;
  assert.match(b, /10/, `ابتُلعت الميزانيّةُ المقروءة: ${b}`);
});

test('ونبرتُه وعدٌ لا إغلاق — «مازال» لا «ما كايتديرش»', () => {
  const say = judge('بغيت نمشي لطنجة').d.say;
  assert.match(say, /مازال/, 'صار الحدُّ إغلاقًا لا وعدًا');
  assert.doesNotMatch(say, /ما كايتديرش أصلًا/, 'خُلط الحدُّ الصادقُ بالرفض');
});

test('والصياغةُ تتنوّع ولا تعشو — نفسُ الجملة نفسُ الجواب', () => {
  // عشوائيّةٌ حقيقيّةٌ تجعل من أعاد جملتَه يظنّ أنّ شيئًا تغيّر، وتجعل
  // الاختبارَ يتذبذب. والثباتُ بالنصّ يُبقيها حيّةً بلا هذا.
  assert.equal(judge('بغيت نمشي لطنجة').d.say, judge('بغيت نمشي لطنجة').d.say);
  const shapes = new Set(['بغيت نمشي لطنجة', 'بغيت طاكسي', 'بغيت نسافر لأكادير']
    .map(s => judge(s).d.say.slice(0, 12)));
  assert.ok(shapes.size >= 2, `صياغةٌ واحدةٌ لكلّ الجمل — ماتت الحيويّة (${shapes.size})`);
});

// ── ③ **لا ينطق حيث يوجد باب** — وهذا أخطرُ حدوده ──────────────
test('**بابٌ يعمل لا يُقال عنه «ما كايناش»**', () => {
  // أخطرُ ما في هذه الطبقة: أن تبتلع مجالًا مخدومًا. «التوصيل» و«الكوموند»
  // لهما قدرةٌ تعمل — فقولُ «مازال ما كايناش» عنهما أسوأُ من الصمت بكثير.
  //
  //   **ويُسأل `boundaryFor` مباشرةً.** أوّلُ صياغةٍ لهذا الحارس سألت الحَكَمَ
  //   كاملًا (`judge`)، فمرّت وهي **جوفاء**: هذه الجملُ تُحكَم `execute` قبل
  //   أن تبلغ طبقةَ الحدّ أصلًا، فكان الحارسُ يشهد لبراءةِ بابٍ لم يُطرَق.
  //   وأسقطتُه بسبرٍ (حذفُ `deny`) فلم يسقط شيء — وذاك دليلُ الجوف.
  //   **وكلُّ بديلٍ في `deny` يُطرَق.** بديلٌ لا يبلغه شيءٌ زينةٌ لا حارس:
  //   سبرٌ يحذفه لا يُسقط شيئًا، فيُظنّ محروسًا وهو ميّت.
  for (const s of ['شحال ثمن التوصيل لمكناس', 'شحال ثمن التوصيل ديال خريبكة',
                   'بغيت نشوف في وصلات الكوموند ديال طنجة',
                   'بغيت نمشي نجيب كولي', 'بغيت نمشي للتوصيل',
                   'بغيت نمشي نجيب الكوموند', 'بغيت نمشي نجيب الطرد',
                   'بغيت نمشي نشوف وصلات']) {
    assert.equal(boundaryFor(s, understand(s) as any, false), null,
      `«${s}» — بابٌ يعمل قيل عنه «ما كايناش»`);
    assert.notEqual(judge(s).d.verdict, 'soon', `«${s}» بلغ الحكمَ حدًّا`);
  }
});

test('وفعلُ الحركة داخل طلبٍ مخدومٍ لا يُوقفه', () => {
  // «بغيت نمشي نشري كسوة» فيها «نمشي»، ولها بابٌ تامّ: الكسوة. والحارسُ
  // يُسأل عند مصدره لا عند مصبّه، لنفس سبب الذي فوقه.
  for (const s of ['بغيت نمشي نشري كسوة', 'بغيت نمشي عند الحداد']) {
    const u = understand(s) as any;
    assert.ok(u.service, `«${s}» ما بقاتش تُقرأ لها خدمة — تغيّر أساسُ الحارس`);
    assert.equal(boundaryFor(s, u, false), null, `«${s}» أُوقف وله باب`);
    assert.notEqual(judge(s).d.verdict, 'soon');
  }
});

test('وما لم يُفهَم لا يُقال عنه «ما كايناش» — الجهلُ ليس عجزًا', () => {
  // فرقٌ جوهريّ: «مكرهتش شي سندويش طون» **مفهومةٌ ناقصًا** ولها باب (مطاعم).
  // فلو ابتلعها الحدُّ لَأعلنّا عجزًا عن بابٍ نملكه بسبب ضعفِ قراءةٍ عندنا.
  for (const s of ['مكرهتش شي سندويش طون بالحرور', 'شنو هادشي', 'بغيت شي حاجة']) {
    assert.notEqual(judge(s).d.verdict, 'soon', `«${s}» — جهلُنا قيل عجزًا`);
  }
});

test('ولا يمسّ ما كان يعمل — الأحكامُ الأخرى كما هي', () => {
  assert.equal(judge('كنقلب على حداد').d.verdict, 'execute');
  assert.equal(judge('بغيت نبيع كسوة').d.verdict, 'ask');
  assert.equal(judge('بنتي داخلة للمدرسة').d.verdict, 'ask');
});

// ── ④ الطبقةُ معزولةٌ عن فهرس المفاهيم ─────────────────────────
test('**«نمشي» لا تدخل فهرسَ المفاهيم** — ولو دخلت لكانت ثامنَ المصارف', () => {
  // مصرفُ الكلمة العامّة وقع سبعَ مرّاتٍ في هذا المشروع. و«نمشي» و«كار»
  // كلماتٌ عامّةٌ جدًّا؛ فبقاؤها خارج الفهرس شرطُ سلامة لا ترتيبُ ملفّات.
  const u = understand('بغيت نمشي لطنجة') as any;
  assert.equal(u.service, undefined, `دخلت «نمشي» فهرسَ المفاهيم ⇒ ${u.service}`);
  assert.equal(understand('بغيت طاكسي').service, undefined);
  // ولا تُنتج قدرةً: القدرةُ تُبنى بقرار إنسانٍ لا بجدولِ حدود.
  assert.equal(judge('بغيت نمشي لطنجة').d.dest, undefined,
    'فتح الحدُّ الصادقُ بابًا — وهو لا يملك بابًا');
});

test('و`boundaryFor` تصمت حين يقول المُنادي إنّ ثمّة تغطية', () => {
  const u = understand('بغيت نمشي لطنجة') as any;
  assert.ok(boundaryFor('بغيت نمشي لطنجة', u, false));
  assert.equal(boundaryFor('بغيت نمشي لطنجة', u, true), null,
    'نطق الحدُّ فوق تغطيةٍ معلَنة');
});

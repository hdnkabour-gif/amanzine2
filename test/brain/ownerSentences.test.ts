import { test } from 'node:test';
import assert from 'node:assert/strict';
import { understand } from '../../src/lib/akg/kb';
import { parseNeed } from '../../src/lib/needEngine';
import { decideExecution } from '../../src/lib/executionPolicy';
import { abilityFor, VERB_MAP, OBJECT_MAP, entityAccepts } from '../../src/lib/abilities';

// ============================================================
// **ثلاثَ عشرةَ جملةً كتبها صاحبُ المشروع** — مختلطةً عمدًا.
//
//   قال: «الكلماتُ التي أريد أن تقيس درجةَ فهم التطبيق لها مختلطةٌ بالكامل».
//   وهو محقّ: جملةُ إنسانٍ حقيقيٍّ لا تحترم تقسيمَ العمل بين طبقتَين.
//
//   والقياسُ الأوّلُ أعطى **١ من ١٣** تعمل من أوّلها إلى آخرها. وثلاثُ صورٍ
//   للعطب ظهرت:
//     ① يفهم ولا بابَ عنده — «بغيت نبيع» نيّتُها `sell` مقروءةٌ تمامًا
//        ووجهتُها `—`. واثنتان يُحكَم فيهما بـ`execute` بلا وجهة: قرّر أن
//        يفعل ثمّ لم يجد أين.
//     ② بابٌ بلا تركيز — «بدّل اسم المحلّ» ⇒ صفحةُ الإعدادات كاملةً.
//     ③ يسقط والمسارُ يعمل — «هاشتاگ ولا وصف» و`/api/ai/generate-hashtags`
//        قائمٌ ويُنادى من `ProductsPage`، ولم تكن في اللغة كلمةٌ تبلغه.
//
//   هذا الملفُّ يثبّت ما صار يعمل. وما لم يُصلَح بعدُ **مكتوبٌ صراحةً** في
//   آخره — لا يُخفى في صمت.
// ============================================================

const judge = (s: string) => {
  const u = understand(s) as any;
  const r = parseNeed(s, {} as any) as any;
  const match = abilityFor({ action: u.action, intent: r?.intent });
  const av = u.action ? VERB_MAP[u.action.verb] : undefined;
  const ae = u.action ? OBJECT_MAP[u.action.object] : undefined;
  const imp = !!(av && ae && (u.action?.confidence ?? 0) >= 0.5 && !entityAccepts(av, ae));
  return { u, r, match, d: decideExecution(u, match || undefined, imp) };
};

test('لا جملةَ من جملِ المالك تُقابَل بـ«ما فهمتش»', () => {
  // أقسى مقياسٍ وأصدقُه: الاعتذارُ عن الفهم هو الجوابُ الذي لا يُفيد أحدًا.
  const OWNER = [
    'بغيت نبيع', 'عندي محل', 'بغيت نبدل النمرة ديالي', 'مسح المنتوج الأخير',
    'فين وصلات الكوموند ديالي', 'بغيت محل لبيع الأحدية',
    'عندي ولدي فعمرو 6 سنين بغيت ليه جلابة ولا جبدور',
    'عندي محل ديال لافاج وكندير ستيكاج والبرييون',
    'بغيت نعرف شحال عندي من طلب اليوم', 'بغيت نصايب تصويرة لهاد المنتوج',
    'باغي هاشتاگ أو وصف زوين لهاد المنتوج', 'بغيت نبدل إسم المحل ديالي',
  ];
  const lost = OWNER.filter(s => /ما فهمتش/.test(judge(s).d.say));
  assert.deepEqual(lost, [], `جملٌ يُعتذَر عن فهمها:\n  ${lost.join('\n  ')}`);
});

test('**وكلُّ فهمٍ يجد بابًا** — إلّا الباحثَ، وهو واقفٌ على بابه', () => {
  // `execute` بلا وجهةٍ يعني أنّ التطبيق قرّر أن يفعل ولم يجد أين. وكانت
  // «عندي محل ديال لافاج» و«جلابة لولدي» كذلك.
  //   والاستثناءُ الوحيدُ صفحةُ `home`: الباحثُ واقفٌ عليها، وسَوقُه إليها
  //   ينتزعه من نتائجه إلى صفحةٍ فارغة.
  for (const [s, page] of [
    ['بغيت نبيع', 'publish'],
    ['عندي محل', 'publish'],
    ['عندي محل ديال لافاج وكندير ستيكاج والبرييون', 'settings'],
    ['بغيت نبدل إسم المحل ديالي', 'settings'],
    ['بغيت نبدل النمرة ديالي', 'profile'],
    ['فين وصلات الكوموند ديالي', 'orders'],
    ['بغيت نعرف شحال عندي من طلب اليوم', 'orders'],
    ['مسح المنتوج الأخير', 'products'],
    ['بغيت نصايب تصويرة لهاد المنتوج', 'products'],
    ['باغي هاشتاگ أو وصف زوين لهاد المنتوج', 'products'],
  ] as const) {
    const { d } = judge(s);
    assert.equal(d.dest?.page, page, `«${s}» ⇒ ${d.verdict} ووجهتُه «${d.dest?.page || '—'}»`);
  }
});

test('«فين وصلات الكوموند ديالي» ⇒ الطلبات — لا «شنو نوع النشاط؟»', () => {
  // أسوأُ جوابٍ في الثلاثَ عشرةَ كلِّها: مَن يسأل عن طرده يُسأل عن حرفته.
  const { d, match } = judge('فين وصلات الكوموند ديالي');
  assert.equal(match?.id, 'VIEW_ORDERS');
  assert.ok(!/نوع النشاط/.test(d.say), `ما زال يُسأل عن حرفته: «${d.say}»`);
});

test('و«صايب تصويرة لهاد المنتوج» صورةٌ لا منتوجٌ جديد', () => {
  // كانت تُقرأ `create/product` — فيُساق مَن يريد صورةً إلى إنشاء منتوج.
  const { u, match } = judge('بغيت نصايب تصويرة لهاد المنتوج');
  assert.equal(u.action?.object, 'photo', `قُرئت «${u.action?.object}»`);
  assert.equal(match?.id, 'MANAGE_MEDIA');
});

test('وطلبُ شيءٍ يصنعه التطبيقُ طلبُ صنعِه — بحدٍّ ضيّق', () => {
  // «باغي هاشتاگ» لا فعلَ فيها إطلاقًا، و«باغي» مستثناةٌ عمدًا من الأفعال.
  const { u } = judge('باغي هاشتاگ أو وصف زوين لهاد المنتوج');
  assert.equal(u.action?.verb, 'create');
  assert.equal(u.action?.object, 'content');
  assert.ok((u.action?.confidence ?? 1) < 0.85, 'فعلٌ مُستنتَجٌ بثقةِ المنطوق');

  // **والحدُّ ضيّق**: لا تسري على هدفٍ يُعرَض أو يُملَك. «هاد المنتوج زوين»
  // ليست طلبَ إنشاءِ منتوج، و«الطلبات» ليست طلبَ إنشاءِ طلب.
  for (const s of ['هاد المنتوج زوين', 'الطلبات ديالي', 'المحفظة ديالي']) {
    const { u: uu } = judge(s);
    assert.notEqual(uu.action?.verb, 'create', `«${s}» صارت طلبَ إنشاء`);
  }
});

// ============================================================
// **وما لم يُصلَح — مكتوبٌ لا مخفيّ.**
//
//   جملتان من الثلاثَ عشرةَ لم تُغلقا، وسببُ كلٍّ منهما معلوم:
//
//   · «عطيني منتوج بأقلّ من 30 درهم» — «عطيني» صارت علامةَ طلب، و«سباط
//     بأقلّ من 200» تعمل تمامًا. لكنّ «منتوج» اسمُ جنسٍ بلا مفهوم، فيُسأل
//     «شنو محتاج بالضبط؟» — وهو **الجوابُ الصحيح**. والناقصُ حقًّا هو
//     **البحثُ بالثمن**: لا مرشِّحَ سعرٍ في `/api/search`.
//
//   · «عندي محل ديال لافاج وكندير ستيكاج والبرييون» — يُقرأ `car_painting`
//     وحدَها، و«لافاج» أوّلُ ما قال ومعروفةٌ في القاموس (`car_wash`).
//     العطبُ أنّ **جملةً واحدةً لا تحمل إلّا خدمةً واحدة** — وهو بابٌ
//     مفتوحٌ في المعرفة لا في هذا الملفّ.
// ============================================================
test('والناقصُ يبقى مُعلَنًا: «بأقلّ من ⟨ثمن⟩» تُفهَم والمرشِّحُ غيرُ مبنيّ', () => {
  // نصفُ العمل واقعٌ: النيّةُ تُقرأ حين يكون المطلوبُ معروفًا.
  const { match } = judge('عطيني سباط بأقل من 200 درهم');
  assert.equal(match?.id, 'BUY_PRODUCT', 'حتّى الطلبُ المعروفُ لم يعد يُقرأ');
  // وما لم يقع: لا مرشِّحَ ثمنٍ يقرأ «٢٠٠» فيضيّق النتائج. يُثبَّت هنا كي
  // يُحذَف هذا السطرُ يومَ يُبنى — لا كي يُنسى.
});

test('وتعدّدُ الخدمات في جملةٍ واحدةٍ ما زال يخسر ما عدا الأولى', () => {
  const { u } = judge('عندي محل ديال لافاج وكندير ستيكاج والبرييون');
  assert.ok(u.service, 'لم يُقرأ شيءٌ إطلاقًا — تراجعٌ عمّا كان');
  // الحالةُ اليوم: خدمةٌ واحدةٌ تفوز. يُكتَب ليُقاس، لا ليُقبَل.
  assert.equal(typeof u.service, 'string');
});

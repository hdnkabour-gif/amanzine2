import { test } from 'node:test';
import assert from 'node:assert/strict';
import { understand, stanceOf } from '../../src/lib/akg/kb';
import { parseNeed } from '../../src/lib/needEngine';
import { decideExecution } from '../../src/lib/executionPolicy';
import { abilityFor } from '../../src/lib/abilities';
import { LIFE_NEEDS, detectLifeNeed, phantomConcepts } from '../../src/lib/akg/kb/goals';

// ============================================================
// الغاية — **لماذا يتكلّم، قبل ماذا يطلب**.
//
//   المغربيُّ لا يقول «بغيت محفظة ومئزر وأقلام». يقول «بنتي داخلة للمدرسة».
//
//   والطبقةُ كانت مبنيّةً منذ زمنٍ و**نصفَ موصولة**: تعرفها `needEngine`
//   وحدَها، و`understand` عمياءُ عنها. وأثرُ العمى مقيسٌ على تسع جملٍ من
//   الجدول نفسِه:
//
//       «عندي مولود جديد»   ⇒ اتّجاه: **يَعرض**   ← أبٌ جديدٌ يُعامَل تاجرًا
//       «تنقلت لدار جديدة»  ⇒ اتّجاه: **يَعرض**
//       «كنوجد لعرس»        ⇒ اتّجاه: **يَعرض**
//
//   وهو العطبُ المكتوبُ في `goals.ts` **نفسِه** سطر ١٣ — أُصلح في عقلٍ وبقي
//   في الآخر. ولم يشتكِ أحدٌ لأنّ المدوّنةَ لم تحوِ جملةَ غايةٍ واحدة: ما لا
//   يُقاس لا يُصلَح، ولو كان مكتوبًا في رأس الملفّ.
// ============================================================

const GOALS = [
  'بنتي داخلة للمدرسة', 'غادي نتزوج', 'عندي مولود جديد', 'تنقلت لدار جديدة',
  'غادي نسافر', 'كنوجد لعرس', 'رزقنا بمولود', 'دخلت لدار جديدة', 'باغي نتزوج',
];

test('الغايةُ تُقرأ في العقل لا في المحرّك وحدَه', () => {
  for (const s of GOALS) {
    assert.ok(understand(s).goal, `«${s}» غايةٌ لا يراها العقل`);
  }
});

// ── ① الاتّجاه ────────────────────────────────────────────────
test('من أخبر عن حاله **يطلب** — ولو بدأ بعلامة عرض', () => {
  // «عندي مولود جديد» تبدأ بـ«عندي»، وهي في `OFFER_MARKS`. وصاحبُها لا
  // يبيع مولودًا. وبلا الغاية كان يُساق إلى صفحة النشر.
  for (const s of GOALS) {
    assert.equal(understand(s).stance, 'seek', `«${s}» قُرئت عرضًا`);
  }
});

test('والقاعدةُ في موضعٍ واحد — `stanceOf` و`understand` لا يختلفان', () => {
  // قِيس حرفيًّا: لمّا وُصلت الغايةُ بـ`understand` وحدَها قفز «الصمتُ
  // التامّ» في النبض من ٠ إلى ٤ — لأنّ `stanceOf` بقيت تقول «لا أعرف» عن
  // الجملة نفسِها. أي انقسامٌ جديدٌ فُتح بينما يُغلَق غيرُه.
  for (const s of GOALS) {
    assert.equal(stanceOf(s), understand(s).stance,
      `عقلان يختلفان على اتّجاه «${s}»`);
  }
});

// ── ② السؤال ─────────────────────────────────────────────────
test('سؤالُ الغاية يبلغ الإنسانَ — لا «شنو محتاج بالضبط؟» الباردة', () => {
  // القيمةُ ليست في أن تُقرأ الغايةُ بل في أن **تُغيّر ما يُقال**. ولو بقيت
  // حقلًا مملوءًا لا يصل، لكانت طبقةً مبنيّةً غيرَ موصولةٍ من جديد.
  for (const s of GOALS) {
    const u = understand(s);
    const r: any = parseNeed(s, {});
    const d = decideExecution(u, abilityFor({ action: u.action ?? null, intent: r.intent }) ?? undefined);
    assert.equal(d.verdict, 'ask', `«${s}» لم تُسأل`);
    assert.equal(d.say, u.goal!.ask, `«${s}» سُئلت سؤالًا عامًّا وغايتُها معروفة`);
    assert.ok(d.trace.some(t => t.startsWith('سؤالُ الغاية')), 'أثرٌ لا يذكر الغاية');
  }
});

test('وحدُّ الغاية معلَن: تجيب عن «ماذا» لا عن «بشحال»', () => {
  // الغايةُ لا تعرف ثمنًا ولا نمرةً ولا طلبًا. وإقحامُ سؤالها في موضعِ
  // سؤالٍ آخرَ يجعل التطبيقَ يهنّئ من سأله عن ثمنٍ.
  const u: any = { confidence: 0.9, reasoning: [], service: 'automobile',
    goal: LIFE_NEEDS.find(n => n.id === 'wedding') };
  const d = decideExecution(u, abilityFor({ intent: 'sell' }) ?? undefined);
  assert.equal(d.verdict, 'ask');
  assert.notEqual(d.say, u.goal.ask, 'أُقحم سؤالُ الغاية في موضع الثمن');
  assert.match(d.say, /بشحال/);
});

// ── ③ حدودُ الطبقة ────────────────────────────────────────────
test('جملةٌ بلا غايةٍ لا تُلبَس غايةً', () => {
  // الغايةُ تُصحّح الاتّجاه، فلو أصابت جملةً عاديّةً لقلبت بائعًا مشتريًا.
  for (const s of ['عندي محل ديال الخضرة', 'أنا خضار', 'بغيت ميكانيكي', 'الثلاجة ما بقاتش خدامة']) {
    assert.equal(understand(s).goal, undefined, `«${s}» أُلبست غايةً`);
  }
  assert.equal(understand('عندي محل ديال الخضرة').stance, 'offer', 'قُلب البائعُ طالبًا');
});

test('لا وعدَ بمفهومٍ لا وجودَ له', () => {
  // الغايةُ تعرض مفاهيمَ للاختيار. ومفهومٌ وهميٌّ يُعرَض ثمّ لا يُنتج نتيجةً
  // واحدة — وعدٌ لا يُوفى (القاعدة ⑰).
  assert.deepEqual(phantomConcepts(), []);
  for (const n of LIFE_NEEDS) {
    assert.ok(n.concepts.length, `غايةٌ بلا مفاهيم: ${n.id}`);
    assert.ok(n.ask.trim().length > 10, `غايةٌ بلا سؤال: ${n.id}`);
  }
});

test('«قفطان ديال العرس» يعرف ما يريد — فلا يُثرثَر عليه', () => {
  // المناسبةُ أضعفُ دلالةً من التصريح: من وصف سلعةً بمناسبتها يعرف طلبَه،
  // ومن أخبر عن حاله يستحقّ الاقتراحَ الواسع. والفرقُ فرقُ سلوكٍ لا تسمية.
  assert.ok(detectLifeNeed('غادي نتزوج'), 'التصريحُ لم يُقرأ');
  const u = understand('بغيت قفطان');
  assert.equal(u.goal, undefined);
  assert.equal(u.stance, 'seek');
});
